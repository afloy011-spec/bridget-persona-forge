def from_card(char):
    """(рука, поверхность) из карточки. Без умолчаний — или сказано, или отказ.

    Умолчание здесь стоило бы дороже отказа: тату, поставленная не на ту руку
    или не на ту сторону, выглядит как настоящая и проходит все прочие ворота.
    У трёх карточек проекта три разных места («back of the left wrist»,
    «inner right forearm», «outer left forearm»), и молчаливое «слева сзади»
    подставило бы двух персонажей из трёх.
    """
    p = ((char.get("tattoo") or {}).get("placement") or "").lower()
    side = "left" if "left" in p else ("right" if "right" in p else None)
    # «outer» и «back» — одна и та же разгибательная поверхность, разные слова.
    surface = ("inner" if "inner" in p else
               ("back" if ("back" in p or "outer" in p) else None))
    if not side or not surface:
        raise SystemExit(
            f"tattoo.placement не говорит, где тату: {p!r}\n"
            f"  Нужны рука (left/right) и сторона (inner/back|outer) — "
            f"например «back of the left wrist».")
    return side, surface


def _lut(cmap=cv2.COLORMAP_PARULA):
    """Таблица цветов 0..24 — та же, которой красит нода.

    Нода делает val = i * 255/24, приводит к uint8 и красит палитрой cv2.
    Здесь повторяется ровно это, поэтому разбор точный, а не приблизительный:
    цвета совпадают побайтно, и невязка отделяет края сглаживания от самих
    кусков.
    """
    vals = (np.arange(25, dtype=np.float32) * (255.0 / 24.0))
    v8 = np.clip(vals, 0, 255).astype(np.uint8).reshape(-1, 1)
    return cv2.applyColorMap(v8, cmap).reshape(-1, 3)[:, ::-1].astype(np.int16)


def decode(bgr, tol=30):
    """Картинка ноды → карта индексов кусков. Вне кусков ноль."""
    rgb = cv2.cvtColor(bgr, cv2.COLOR_BGR2RGB).astype(np.int16)
    lut = _lut()
    d = np.abs(rgb.reshape(-1, 1, 3) - lut[None, :, :]).sum(2)
    idx = d.argmin(1).astype(np.uint8)
    idx[d.min(1) > tol] = 0
    return idx.reshape(bgr.shape[:2])


