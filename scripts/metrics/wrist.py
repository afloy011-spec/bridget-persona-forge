_MIN_PASTE = {}


def min_paste_px(asset=None):
    """Наименьшая ширина вклейки, при которой надпись ещё надпись.

    СЧИТАЕТСЯ ПО САМОМУ АССЕТУ, А НЕ ЗАДАЁТСЯ ЧИСЛОМ. Здесь стоял порог на
    ширину предплечья (0.035 кадра), подобранный на глаз, и живой прогон
    показал, чего он стоит: на одном из девяти кадров надпись легла шириной
    49 px. «Manolo Blahnik» в 49 пикселей — это не мелкая тату, это серое
    пятно на запястье, и выглядит оно грязью, а не чернилом.

    Замер уменьшения ассета (689x165, рукописный штрих): пик альфы держится
    0.99 в натуральную величину, 0.89 при 209 px, 0.78 при 135 и 0.43 при 49
    — тонкий штрих при уменьшении усредняется с кожей и выцветает. Толщина
    штриха этого не ловит вовсе: `_stroke_px` показывает 1.91 px и на 400, и
    на 49, потому что упирается в собственное сглаживание. Ловит именно ПИК
    АЛЬФЫ, и порог по нему самокалибруется: сменится ассет — сменится и число.
    """
    from PIL import Image
    asset = asset or os.path.join(_root(), "assets",
                                  "tattoo_manolo_blahnik.png")
    if asset in _MIN_PASTE:
        return _MIN_PASTE[asset]
    with Image.open(asset) as im:
        im = im.convert("RGBA")
        w0, h0 = im.size
        lo, hi = 8, w0
        while lo < hi:                       # наименьшая ширина с живым чернилом
            mid = (lo + hi) // 2
            small = im.resize((mid, max(1, int(mid * h0 / w0))), Image.LANCZOS)
            peak = np.asarray(small)[..., 3].max() / 255.0
            if peak >= INK_KEEP:
                hi = mid
            else:
                lo = mid + 1
    _MIN_PASTE[asset] = lo
    return lo


def ink_box(at, ax, length, height, shape):
    """Прямоугольник, который займёт надпись, в осях кадра."""
    per = np.array([-ax[1], ax[0]])
    c = np.array([at + ax * (length / 2) + per * (height / 2),
                  at + ax * (length / 2) - per * (height / 2),
                  at - ax * (length / 2) - per * (height / 2),
                  at - ax * (length / 2) + per * (height / 2)])
    box = np.zeros(shape[:2], np.uint8)
    cv2.fillConvexPoly(box, c.astype(np.int32), 1)
    return box, c


def cloth_frac(img, arm_mask, hand_mask, box):
    """Доля НЕ КОЖИ под надписью: рукав, манжета, перчатка. Не металл.

    ЭТА ПРОВЕРКА БЫЛА, Я ЕЁ СНЯЛА, И ЭТО СТОИЛО БРАКА В КАДРЕ. Снимала я её
    за то, что она не различает ЧАСЫ: запястье с часами давало 0.20, чистое
    0.08 — разделение в 2.5 раза, монетка. Вывод «правило не работает» был
    неверен: оно плохо ловит металл и отлично ловит ТКАНЬ. Замер на кадре, где
    надпись легла прямо на рукав кашемирового свитера: 1.000. Чистая кожа на
    том же прогоне — 0.000, промежуточный кадр 0.327.
    Порог 0.5 стоит в этом промежутке и ловит именно ткань. Металл ловит
    сегментация по тексту (occluders), и это две разные проверки, а не одна
    с двумя порогами.

    Разметка поверхностей тела размечает ТЕЛО, в том числе под одеждой: рукав
    свитера она честно называет предплечьем, и вытянутость с тыльной стороной
    у такого куска в полном порядке. Отличить рукав от кожи можно только по
    самому кадру.
    """
    lab = cv2.cvtColor(img, cv2.COLOR_BGR2LAB).astype(np.float32)
    inside = (box > 0) & (arm_mask > 0)
    if inside.sum() < 64 or hand_mask.sum() < 256:
        return None
    ref = np.median(lab[hand_mask > 0][:, 1:], 0)
    d = np.abs(lab[inside][:, 1:] - ref).sum(1)
    return float((d > CHROMA_TOL).mean())


def occluders(src, out_dir=None):
    """Маска того, что лежит на запястье: часы, ремешок, браслет, манжета.

    ЗАЧЕМ. Карточка разводит латеральность жёстко — тату на левом запястье,
    металл на правом, — но карточка описывает ЧЕЛОВЕКА, а кадр рисует модель.
    На ОБОИХ кадрах сдачи, где тыльное запястье видно, часы оказались на левой
    руке, ровно на площадке под вклейку. Надпись поверх ремешка — видимый брак.

    ПОЧЕМУ НЕ ПО ЦВЕТУ, ХОТЯ ТАК БЫЛО СДЕЛАНО СНАЧАЛА. Первая версия считала
    долю «не кожи» под надписью: отход цветности (Lab a,b) от цвета КИСТИ,
    которая голая по определению. Замер на трёх кадрах: запястье с часами дало
    0.20, чистое 0.08 — разделение в 2.5 раза, и то же 0.20 дал третий кадр,
    где часов нет вовсе. Главные ворота этой метрики (сторона поверхности)
    разделяют в 40-60 раз; порог посреди континуума в 2.5 — это не порог, а
    монетка. Золотой ремешок по цветности от кожи почти не отличается — задача
    оказалась не цветовой, ровно как до неё оказался не цветовым поиск
    предплечья. Правило снято целиком, а не подпёрто множителем.

    ЧЕМ ЗАМЕНЕНО. Сегментация по тексту (SAM3Segment, шаблон
    wrist_occluders_api.json). Проверено глазами: на обоих кадрах маска легла
    ТОЧНО на циферблат и ремешок и никуда больше. Браслеты-обручи она берёт не
    всегда — на корте гладкий браслет не нашла вовсе; это известный предел, и
    он записан здесь, а не спрятан в пороге.
    """
    import comfy_client as cc
    from _util import work_dir
    up = cc.upload(src)
    g = cc.load_template("wrist_occluders_api")
    cc.apply_sets(g, {"1.image": up, "3.filename_prefix": "occluders"})
    got = cc.run_graph(g, out_dir or work_dir("_tmp", "occluders"))
    if not got:
        return None
    m = imread(got[0])
    return None if m is None else \
        (cv2.cvtColor(m, cv2.COLOR_BGR2GRAY) > 127).astype(np.uint8)


def measure(src, side="left", idx=None, out_dir=None, occ=None,
            check_occluders=True, surface="back", ipd=None, paste_width=None):
    """Вердикт по кадру: видна ли нужная сторона запястья и куда класть надпись.

    `paste_width` — ширина кадра, В КОТОРЫЙ надпись реально ляжет, если она
    отличается от ширины кадра, по которому идёт замер. Нужна ровно из-за
    порядка шагов доводки: разметка поверхностей тела на увеличенном кадре
    перестаёт узнавать предплечье (на 2560x3200 отдаёт облако 151x109 px и
    честно отказывает), поэтому МЕРИТЬ приходится до увеличения, а ВКЛЕИВАТЬ
    после. Геометрия переносится сама — `at` и `size` лежат в долях кадра, —
    но порог на читаемость чернила абсолютный, в пикселях, и без этой поправки
    он судил бы надпись по вдвое меньшему размеру, чем она получит. Замер:
    кадры с ясно видимой тыльной стороной (back 0.98-1.00) отсеивались со
    словами «надпись вышла бы шириной 88-152 px при нужных 153», хотя после
    увеличения им доставалось 176-304.
    """
    if idx is None:
        idx = part_map(src, out_dir)
    if idx is None:
        return {"state": NOT_MEASURED, "why": "воркер не отдал карту кусков"}
    img = imread(src)
    if img is None:
        return {"state": NOT_MEASURED, "why": f"кадр не прочитан: {src}"}
    H, W = img.shape[:2]
    g = geometry(idx, side)
    k = W / float(idx.shape[1])          # карта → кадр
    # ОДИН множитель на обе оси — и это надо проверить, а не предположить.
    # Нода приводит кадр к своему разрешению с паддингом и снимает паддинг
    # обратно, то есть пропорцию держит; но если однажды не удержит, точка
    # поедет по одной оси и никуда по другой — надпись просто ляжет мимо, без
    # единого сообщения. Полпроцента — это округление до целого пикселя.
    if abs(idx.shape[0] * k - H) > 0.005 * H:
        return {"state": NOT_MEASURED,
                "why": (f"карта кусков {idx.shape[1]}x{idx.shape[0]} не в "
                        f"пропорции кадра {W}x{H} — координаты не перевести")}
    res = {"state": NOT_MEASURED, "side": side, "surface": surface,
           "back_visible": False, "frame": [W, H]}
    res.update({q: g[q] for q in ("back_px", "inner_px", "hand_px",
                                  "hand_gap_px", "elongation") if q in g})
    if "back_frac" not in g:
        res["why"] = g.get("why", "разбор не удался")
        return res

    aw = g["arm_width_px"] * k / W
    # МАСШТАБ БЕРЁТСЯ ОТ МЕЖЗРАЧКОВОГО РАССТОЯНИЯ, А НЕ ОТ ШИРИНЫ РУКИ.
    # Ширина руки с разметки невоспроизводима (см. LEN_OVER_IPD выше: 144 и 88
    # px на двух версиях одного кадра), а IPD — стабильная физическая единица,
    # которой этот проект меряет всё остальное. Ширина руки остаётся в записи
    # и работает СВЕРКОЙ, а не источником числа.
    # Готовый IPD можно передать: скрин кадра уже гонял детектор лиц, и второй
    # прогон по тому же файлу — это просто потраченное время.
    ipd = ipd or _ipd_px(src)
    if not ipd:
        res["why"] = ("лица в кадре нет — нечем задать масштаб надписи "
                      "(ширина руки для этого недостаточно устойчива)")
        return res
    size_px = LEN_OVER_IPD * ipd
    along_px = ALONG_IPD * ipd
    ax = np.array(g["axis"], np.float64)          # смотрит В СТОРОНУ КИСТИ
    at = np.array(g["wrist_px"], np.float64) - ax * (along_px / k)
    # Доля НУЖНОЙ поверхности. У Бриджит это тыльная, у двух других карточек
    # проекта — другая: место тату берётся из карточки (from_card), а не
    # предполагается. Одно число, посчитанное один раз, читается с двух сторон.
    want = g["back_frac"] if surface == "back" else 1.0 - g["back_frac"]
    res.update({"state": PASS, "back_frac": g["back_frac"],
                "surface_frac": want, "ipd_px": ipd,
                "arm_width": aw, "rot": g["rot"],
                "at": [at[0] * k / W, at[1] * k / H],
                "wrist": [g["wrist_px"][0] * k / W, g["wrist_px"][1] * k / H],
                "size": size_px / W,
                "size_by_arm": LEN_OVER_W * g["arm_width_px"] * k / W})
    if want < BACK_MIN:
        other = "ладонная" if surface == "back" else "тыльная"
        res["why"] = (f"к камере {other} сторона: нужной у запястья "
                      f"{want:.0%} при пороге {BACK_MIN:.0%}")
        return res
    # СВЕРКА ДВУХ МАСШТАБОВ. Лицо и рука бывают на разном расстоянии от
    # объектива, и тогда «по лицу» и «по руке» расходятся законно; но сильное
    # расхождение значит либо вытянутую к объективу руку, либо провал
    # сегментации — и в обоих случаях вклеивать не надо. Полоса широкая
    # нарочно: сама ширина руки шумит, и узкая полоса ловила бы её шум.
    ratio = res["size"] / max(res["size_by_arm"], 1e-9)
    res["scale_ratio"] = ratio
    if not (IPD_VS_ARM[0] <= ratio <= IPD_VS_ARM[1]):
        res["why"] = (f"масштаб по лицу и по руке разошлись в {ratio:.2f} раза "
                      f"(допуск {IPD_VS_ARM[0]}-{IPD_VS_ARM[1]}) — рука сильно "
                      f"ближе к объективу или разметка промахнулась")
        return res
    need = min_paste_px()
    paste_w = float(paste_width or W)
    if res["size"] * paste_w < need:
        res["why"] = (f"надпись вышла бы шириной {res['size'] * paste_w:.0f} px "
                      f"при нужных {need} — на такой мелкоте чернило "
                      f"усредняется с кожей и читается грязью, а не именем")
        return res
    # Рамка вклейки обязана лечь в кадр целиком: половина надписи за краем
    # читается как обрезанная переводная картинка.
    if not (0.0 <= res["at"][0] <= 1.0 and 0.0 <= res["at"][1] <= 1.0):
        res["why"] = "место надписи вышло за кадр"
        return res

    # Направление строки восстанавливается из того же rot, которым её повернёт
    # композит: разъедется знак — прямоугольник ляжет не туда, и проверки будут
    # мерить не то место, куда попадёт надпись.
    a = np.radians(res["rot"])
    e = np.array([np.cos(a), -np.sin(a)])
    L = res["size"] * W
    box, _ = ink_box(np.array([res["at"][0] * W, res["at"][1] * H]), e, L,
                     L * _asset_aspect(), img.shape)

    # ПОД НАДПИСЬЮ ОБЯЗАНА БЫТЬ КОЖА, А НЕ РУКАВ. Разметка размечает тело под
    # одеждой, поэтому все прочие ворота на рукаве проходят: и сторона, и
    # вытянутость, и размер. Замер: рукав свитера 1.000, чистая кожа 0.000.
    pp = SIDE_PARTS[side]
    to_frame = lambda x: cv2.resize(x.astype(np.uint8), (W, H),  # noqa: E731
                                    interpolation=cv2.INTER_NEAREST)
    arm = to_frame((idx == pp["back"]) | (idx == pp["inner"]))
    hand = to_frame(idx == pp["hand"])
    cloth = cloth_frac(img, arm, hand, box)
    res["cloth"] = cloth
    if cloth is not None and cloth > CLOTH_MAX:
        res["why"] = (f"под надписью {cloth:.0%} не кожи — это рукав или "
                      f"манжета, а не запястье")
        return res

    # ЗАНЯТО ЛИ ЗАПЯСТЬЕ — считается ПОСЛЕДНИМ и только для кадров, дошедших
    # досюда: это второй круг по GPU, и гонять его на кадрах, где тыльной
    # стороны не видно, значит платить за ответ, который уже известен.
    if occ is None and check_occluders:
        occ = occluders(src, out_dir)
    if occ is not None:
        om = cv2.resize(occ, (W, H), interpolation=cv2.INTER_NEAREST)
        hit = float(((box > 0) & (om > 0)).sum()) / max(int(box.sum()), 1)
        res["occluded"] = hit
        # Порог низкий и намеренно: это не доля «похожего на металл», а
        # пересечение с НАЙДЕННЫМ предметом. Предмет, залезающий на буквы хоть
        # немного, уже виден глазом, а кадр без тату — кадр нормальный.
        if hit > OCCLUDE_MAX:
            res["why"] = (f"на запястье часы или браслет: они закрывают "
                          f"{hit:.0%} площадки под надписью")
            return res
    res["back_visible"] = True
    return res


def record(src, m, out_dir=None):
    """Запись разметки для composite_tattoo.

    ПРИЁМНИК ОБЯЗАН ЛЕЖАТЬ В ДРУГОЙ ПАПКЕ. Вклейка не идемпотентна — чернило
    умножается на кожу, — и приёмник, совпавший со входом, превращает повтор
    команды в тату поверх тату. Ровно этот дефект уже был в ручной разметке
    сдачи: у обеих записей out указывал на сданный файл. Сам композит от него
    защищён сравнением по иноду, но отказ на середине списка означает
    наполовину сделанную работу, поэтому проверка стоит и здесь, на сборке.
    """
    p = {"frame": src, "at": [round(m["at"][0], 4), round(m["at"][1], 4)],
         "size": round(m["size"], 4), "rot": round(m["rot"], 2)}
    if out_dir:
        d = os.path.dirname(os.path.abspath(src))
        if os.path.normcase(os.path.abspath(out_dir)) == os.path.normcase(d):
            raise SystemExit(
                f"приёмник разметки лежит в папке входа: {out_dir}\n"
                f"  Вклейка не идемпотентна, и повтор команды положит тату "
                f"поверх тату. Укажи другую папку.")
        p["out"] = os.path.join(out_dir, os.path.basename(src))
    return p


def placement(src, side="left", idx=None, out_dir=None, dst_dir=None):
    """Запись для composite_tattoo или None, если вклеивать нельзя."""
    m = measure(src, side, idx, out_dir)
    if not m.get("back_visible"):
        return None, m
    return record(src, m, dst_dir), m


def draw(src, m, dst):
    """Рамка на кадре — единственный способ проверить место глазами."""
    img = imread(src)
    if img is None:
        return None
    H, W = img.shape[:2]
    if m.get("wrist"):
        cv2.drawMarker(img, (int(m["wrist"][0] * W), int(m["wrist"][1] * H)),
                       (0, 255, 255), cv2.MARKER_TILTED_CROSS, 30, 2)
    if m.get("at"):
        c = (int(m["at"][0] * W), int(m["at"][1] * H))
        col = (0, 230, 0) if m.get("back_visible") else (0, 0, 255)
        L = m.get("size", 0.1) * W
        a = np.radians(-m.get("rot", 0.0))
        d = np.array([np.cos(a), np.sin(a)]) * L / 2
        cv2.line(img, (int(c[0] - d[0]), int(c[1] - d[1])),
                 (int(c[0] + d[0]), int(c[1] + d[1])), col, 3)
        cv2.drawMarker(img, c, col, cv2.MARKER_CROSS, 24, 2)
    # Латиницей: шрифты cv2 кириллицу не рисуют вовсе, и подпись выходила
    # рядом вопросительных знаков — то есть проверять глазами было нечего.
    txt = ("%s %.0f%%" % (m.get("surface", "back"), 100 * m["surface_frac"])) \
        if "surface_frac" in m else "no tattoo"
    cv2.putText(img, txt, (12, 34), cv2.FONT_HERSHEY_SIMPLEX, 0.8,
                (0, 230, 0) if m.get("back_visible") else (0, 0, 255), 2)
    imwrite(dst, img)
    return dst


def _frames(arg):
    if os.path.isdir(arg):
        out = []
        for e in ("*.png", "*.jpg", "*.jpeg"):
            out += glob.glob(os.path.join(arg, e))
        return sorted(p for p in out if "contact_sheet" not in
                      os.path.basename(p).lower())
    return [arg]


def main():
    setup_console()
    args = sys.argv[1:]
    if not args or args[0].startswith("--"):
        print(__doc__)
        raise SystemExit(1)
    # Место тату берётся ИЗ КАРТОЧКИ, если её дали, — у трёх карточек проекта
    # три разных места, и ключи --side/--surface здесь только для проб.
    side, surface = cli_opt(args, "--side", "left"), \
        cli_opt(args, "--surface", "back")
    card = cli_opt(args, "--card")
    if card:
        from _util import read_json
        side, surface = from_card(read_json(card))
        print(f"из карточки: {side}, поверхность {surface}")
    drawdir = cli_opt(args, "--draw")
    plfile = cli_opt(args, "--placements")
    outdir = cli_opt(args, "--out-dir")
    if drawdir:
        os.makedirs(drawdir, exist_ok=True)
    # ПУСТОЙ ВХОД — ОТКАЗ, А НЕ «НИ ОДНОГО ЗАПЯСТЬЯ». Шаг 9 обоих ранбуков
    # указывал на каталог `<W>/skin`, который создаёт только снятый с доводки
    # skin_graft.py. Команда печатала «видна на 0, не видна на 0» и выходила с
    # кодом 0 — то есть «посмотрел и не нашёл» и «смотреть было негде»
    # выглядели одинаково, а для любой автоматизации это успех.
    frames = list(_frames(args[0]))
    if not frames:
        raise SystemExit(
            "смотреть нечего: по пути {} нет ни одного кадра.\n"
            "  Это не «запястья не видно», это отсутствующий вход. Шаг 9 "
            "берёт кадры ПОСЛЕ увеличения: <work_root>/<id>/big.".format(args[0]))
    places, ok, no = [], 0, 0
    for src in frames:
        name = os.path.basename(src)
        try:
            m = measure(src, side, surface=surface)
        except Exception as e:
            print(f"{name:34s} сбой: {type(e).__name__}: {e}")
            continue
        if m.get("back_visible"):
            ok += 1
            print(f"{name:34s} ВИДНО {m['surface_frac']:.0%}  at "
                  f"{m['at'][0]:.3f},{m['at'][1]:.3f}  size {m['size']:.3f}  "
                  f"rot {m['rot']:+.1f}")
            places.append(record(src, m, outdir))
        else:
            no += 1
            print(f"{name:34s} без тату — {m.get('why', '')}")
        if drawdir:
            draw(src, m, os.path.join(drawdir, os.path.splitext(name)[0] +
                                      "_wrist.png"))
    print(f"\nнужная сторона запястья видна на {ok}, не видна на {no}")
    if plfile:
        os.makedirs(os.path.dirname(os.path.abspath(plfile)), exist_ok=True)
        with open(plfile, "w", encoding="utf-8") as fh:
            json.dump(places, fh, ensure_ascii=False, indent=1)
        print(f"разметка: {plfile}")


if __name__ == "__main__":
    main()
