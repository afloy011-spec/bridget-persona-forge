def _largest(mask):
    n, lab, st, _ = cv2.connectedComponentsWithStats(mask.astype(np.uint8), 8)
    if n < 2:
        return None
    return (lab == 1 + int(np.argmax(st[1:, cv2.CC_STAT_AREA]))).astype(np.uint8)


def _axis(mask, q=0.02):
    """Главная ось куска: (центр, единичный вектор, полудлина, полуширина).

    ДЛИНА И ШИРИНА БЕРУТСЯ ПО КВАНТИЛЯМ, А НЕ ПО КРАЙНИМ ТОЧКАМ, и это
    исправление замеренного дефекта. Здесь стоял размах (ptp), то есть обе
    величины задавала ОДНА крайняя точка облака. Проверка: один и тот же кадр
    до и после переноса лица — эдит руки не касается, размер кадра тот же —
    дал ширину предплечья 0.1685 и 0.1025, разброс 39%. Через ворота
    читаемости это прошло как «надпись 207 px» против «надпись 126 px»:
    первый кадр получал тату, второй нет, и виновата была не рука, а один
    пиксель сегментации на её краю. Квантиль 2% срезает бахрому разметки и
    оставляет саму руку; на тех же двух картинках разброс падает до единиц
    процента.
    """
    ys, xs = np.nonzero(mask)
    pts = np.stack([xs, ys], 1).astype(np.float64)
    c = pts.mean(0)
    w, v = np.linalg.eigh(np.cov((pts - c).T))
    ax = v[:, int(np.argmax(w))]
    ax /= np.linalg.norm(ax)
    per = np.array([-ax[1], ax[0]])
    t, s = (pts - c) @ ax, (pts - c) @ per
    span = lambda u: float(np.quantile(u, 1 - q)   # noqa: E731
                           - np.quantile(u, q)) / 2.0
    return c, ax, span(t), span(s)


def geometry(idx, side="left"):
    """Разбор карты кусков: сторона поверхности и место надписи.

    Всё считается В ПИКСЕЛЯХ КАРТЫ и переводится в доли кадра снаружи — карта
    приходит с воркера в своём разрешении, и смешивать системы здесь значило бы
    получить верную геометрию в неверном масштабе.
    """
    p = SIDE_PARTS[side]
    other = SIDE_PARTS["right" if side == "left" else "left"]
    n = idx.size
    back = (idx == p["back"])
    inner = (idx == p["inner"])
    hand = (idx == p["hand"])
    out = {"back_px": int(back.sum()), "inner_px": int(inner.sum()),
           "hand_px": int(hand.sum())}
    # ЧУЖАЯ РУКА В КАДРЕ — ЭТО ДИАГНОЗ, А НЕ ШУМ. Клетка просит показать
    # ЛЕВОЕ запястье, а модель на трети кадров поднимает правую руку; отказ
    # «кисти в кадре нет» читается тогда как поломка детектора, хотя кисть на
    # виду. Разница между «сцена не та» и «детектор не нашёл» — это разница
    # между «перепиши промпт» и «чини код», и путать их дорого.
    them = ((idx == other["back"]) | (idx == other["inner"]) |
            (idx == other["hand"])).sum() > n * MIN_PART
    mine = "левой" if side == "left" else "правой"
    theirs = "правая" if side == "left" else "левая"
    swap = f", в кадре {theirs} — модель взяла не ту руку" if them else ""
    arm = back | inner
    if arm.sum() < n * MIN_PART:
        out["why"] = f"{mine} руки в кадре нет{swap}"
        return out

    blob = _largest(arm)
    c, ax, half, halfw = _axis(blob > 0)
    width = 2.0 * halfw
    # КУСОК ОБЯЗАН БЫТЬ ВЫТЯНУТЫМ, ИНАЧЕ ОСИ У НЕГО НЕТ.
    # Проверка была в прежней метрике предплечья и потерялась при переписывании
    # — и тут же дала брак: на кадре, где рука поднята к волосам, кусок вышел
    # 194 на 160 px, то есть почти квадратным. У такого облака главная ось это
    # шум: она легла вверх-влево, тогда как рука идёт вверх-вправо, запястье
    # село у ЛОКТЕВОГО конца, и надпись встала вверх ногами. По рамке всё
    # выглядело правдоподобно — увидеть можно было только на 1:1.
    # Двойка не подобрана: предплечье вдвое длиннее своей ширины при любом
    # ракурсе, кроме съёмки почти вдоль руки, а при таком ракурсе вклеивать и
    # нечего.
    out["elongation"] = (2.0 * half) / max(width, 1e-6)
    if out["elongation"] < MIN_ELONGATION:
        out["why"] = (f"кусок предплечья не вытянут: {2 * half:.0f} на "
                      f"{width:.0f} px — у такого облака нет оси, и запястье с "
                      f"поворотом вышли бы наугад")
        return out

    # НАПРАВЛЕНИЕ ОСИ ЗАДАЁТ КИСТЬ: ось из PCA — это прямая, а нам нужно, где
    # на ней запястье, а где локоть. Кисть примыкает к запястью, значит конец,
    # ближний к её центру, и есть запястье. Без кисти в кадре направление
    # неизвестно, и это честный отказ, а не повод угадать: перепутанные концы
    # положат надпись у локтя и развернут её задом наперёд.
    if hand.sum() < n * MIN_PART:
        out["why"] = (f"{mine} кисти в кадре нет{swap} — конец предплечья не "
                      f"определить")
        return out

    # КИСТЬ ОБЯЗАНА ПРИМЫКАТЬ К ЭТОМУ ПРЕДПЛЕЧЬЮ, И ЭТО ПРОВЕРЯЕТСЯ.
    # В шапке этого файла стояло, что кисть и предплечье — соседние куски
    # одной разметки, и «пересечения может не быть» не бывает. Утверждение
    # оказалось неверным: на кадре в кафе разметка назвала кисть ПОДНЯТОЙ руки
    # левой, предплечье той же руки — правым, а левым предплечьем — другую
    # руку, лежащую на столе. Код брал самый крупный кусок каждого рода и
    # молча сшивал кисть одной руки с предплечьем другой. Место вклейки при
    # этом выглядело правдоподобным — ошибка видна только по числам, которые
    # прыгали на 39% между двумя версиями одного кадра.
    # Берётся не самая крупная кисть, а БЛИЖАЙШАЯ к предплечью, и если даже
    # она далеко — отказ: у прямой два конца, и выбрать не тот значит положить
    # надпись к локтю задом наперёд.
    nh, hlab, hst, hcen = cv2.connectedComponentsWithStats(
        hand.astype(np.uint8), 8)
    dist = cv2.distanceTransform((blob == 0).astype(np.uint8),
                                 cv2.DIST_L2, 3)
    best, bd = None, None
    for j in range(1, nh):
        if hst[j, cv2.CC_STAT_AREA] < n * MIN_PART * 0.25:
            continue
        d_j = float(dist[hlab == j].min())
        if bd is None or d_j < bd:
            best, bd = j, d_j
    if best is None:
        out["why"] = f"{mine} кисти в кадре нет{swap}"
        return out
    out["hand_gap_px"] = bd
    if bd > HAND_GAP_W * width:
        out["why"] = (f"кисть и предплечье не сходятся: между ними {bd:.0f} px "
                      f"при ширине руки {width:.0f} — это разные руки, конец "
                      f"предплечья не определить")
        return out
    hc = np.array(hcen[best], np.float64)
    if (hc - c) @ ax < 0:
        ax = -ax
    wrist = c + ax * half            # конец предплечья со стороны кисти

    # СТОРОНА РЕШАЕТСЯ ТОЛЬКО У ЗАПЯСТЬЯ. Полоса шириной NEAR_W ширин руки от
    # запястья к локтю: дальше рука может быть повёрнута иначе, и её голоса в
    # этом вопросе быть не должно.
    ys, xs = np.mgrid[0:idx.shape[0], 0:idx.shape[1]]
    d = ((xs - wrist[0]) * (-ax[0]) + (ys - wrist[1]) * (-ax[1]))
    band = (d >= 0) & (d <= NEAR_W * width)
    nb, ni = int((back & band).sum()), int((inner & band).sum())
    out.update({"near_back_px": nb, "near_inner_px": ni,
                "arm_width_px": width, "wrist_px": [float(wrist[0]),
                                                    float(wrist[1])],
                "axis": [float(ax[0]), float(ax[1])]})
    if nb + ni == 0:
        out["why"] = "у запястья разметки нет"
        return out
    out["back_frac"] = nb / float(nb + ni)

    # МЕСТА НАДПИСИ ЗДЕСЬ НЕТ НАМЕРЕННО. Оно считается в measure() от
    # межзрачкового расстояния, а не от ширины руки: ширина с разметки
    # невоспроизводима. Держать здесь второй, «почти такой же» ответ значило бы
    # завести два источника правды, из которых один тихо неверен.
    # ПОВОРОТ СЧИТАЕТСЯ ПО ВЕКТОРУ «ЗАПЯСТЬЕ → ЛОКОТЬ», то есть по МИНУС ax:
    # сам ax смотрит в сторону кисти, потому что кистью и определяется. Первая
    # версия брала угол прямо от ax, и на кадре с собакой вышло rot +174.7°,
    # то есть строка легла бы задом наперёд — место при этом было верным, и по
    # рамке ошибка не видна. Знак минус перед градусами — из-за PIL: он крутит
    # против часовой в зрительном смысле, а угол считается в осях картинки,
    # где y растёт вниз.
    out["rot"] = float(-np.degrees(np.arctan2(-ax[1], -ax[0])))
    return out


def _ipd_px(src):
    """Межзрачковое расстояние в пикселях кадра, или None.

    Единица масштаба всего проекта: 63 мм, меряется insightface и не зависит
    от того, как разметка поверхностей поделила руку в этот раз.
    """
    try:
        from metrics import faces
        d = faces.detect(src)
        if not d:
            return None
        k = np.asarray(d["kps"], np.float64)
        return float(np.linalg.norm(k[1] - k[0]))
    except Exception:
        return None


