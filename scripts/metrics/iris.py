def recolour(img, face, pigment):
    """Заменить пигмент радужки, сохранив яркость и фактуру.

    Не заливка цветом: множитель по каналам в ЛИНЕЙНОМ свете с возвратом
    исходной яркости — это то, что делает с отражённым светом другой пигмент.
    Блик внутри радужки при этом красится тоже, чего в природе не бывает; на
    замер это не влияет, потому что блики метрика выбрасывает.
    """
    out = img.copy()
    tgt = np.asarray(PIGMENTS[pigment], np.float64)
    for w in EYES:
        centre, lid_pts, d, ex, ey = eye_frame(face, w)
        m = eye_masks(img.shape, centre, lid_pts, d, ex, ey)
        if m is None:
            continue
        (x0, y0, x1, y1), iris_m, _ = m
        if int(iris_m.sum()) < 10:
            continue
        sub = out[y0:y1, x0:x1]
        lin = to_linear(sub[..., ::-1])
        yy, xx = np.mgrid[y0:y1, x0:x1].astype(np.float64)
        rad = np.hypot(xx - centre[0], yy - centre[1]) / d
        lid = np.zeros(rad.shape, np.uint8)
        cv2.fillPoly(lid, [np.round(lid_pts - [x0, y0]).astype(np.int32)], 255)
        disc = (lid > 0) & (rad <= RING_OUT * 1.12)
        cur = np.median(lin[iris_m], axis=0)
        gain = tgt / np.maximum(cur, 1e-6)
        gain *= float(cur @ RGB2XYZ[1]) / max(float((cur * gain) @ RGB2XYZ[1]), 1e-9)
        # Мягкий край, иначе на границе диска появляется кольцо, которого в
        # настоящей радужке нет, и метрика ловила бы его, а не пигмент.
        soft = cv2.GaussianBlur(disc.astype(np.float64), (0, 0),
                                max(0.8, 0.006 * d))[..., None]
        out[y0:y1, x0:x1] = to_srgb(lin * (1 - soft) + (lin * gain) * soft)[..., ::-1]
    return out


def relight(img, name):
    """Подменить освещение диагональю в линейном свете.

    Считается таблицей на канал: множитель в линейном свете — чистая функция
    входного байта, и таблица из 256 значений даёт РОВНО тот же результат, что
    поканальный проход по кадру, только без разгибания гаммы на полутора
    миллионах пикселей пять раз подряд.
    """
    gains = ILLUMINANTS[name][::-1]          # порядок каналов BGR, как у кадра
    lut = np.ascontiguousarray(
        np.stack([to_srgb(_LINEAR * g) for g in gains], axis=1)
        .reshape(1, 256, 3))
    return cv2.LUT(np.ascontiguousarray(img), lut)


def limbus_radius(img, face, which):
    """Радиус края радужки, найденный ПО КАРТИНКЕ, в долях IPD.

    В замере не участвует: кольцо задано долями IPD жёстко, чтобы у метрики не
    было лишней точки отказа. Нужен самотесту — им проверяется, что кольцо
    `RING_IN…RING_OUT` действительно лежит ВНУТРИ радужки. Если поколение
    кадров начнёт рисовать радужку другого размера, кольцо съедет на белок или
    на зрачок, и заметить это иначе будет нечем.

    Ищется по горизонтальным секторам: сверху и снизу радужку режут веки.

    ИЩЕТСЯ НЕ САМЫЙ СИЛЬНЫЙ ПЕРЕПАД, А ПЕРЕХОД РАДУЖКА→БЕЛОК ПО ПОЛОВИНЕ
    ВЫСОТЫ. Первая редакция брала максимум производной яркости наружу — и на
    каждом десятом глазу находила КРАЙ ЗРАЧКА: там яркость наружу тоже растёт,
    и на тёмной радужке растёт сильнее, чем на лимбе. Диагностика тогда
    рапортовала радужку вдвое меньше настоящей, и проверка кольца краснела на
    исправном кадре. Половина высоты между уровнем радужки и уровнем белка
    такой двусмысленности не имеет: зрачок лежит НИЖЕ уровня радужки, а не
    между ним и белком.
    """
    centre, _, d, ex, ey = eye_frame(face, which)
    # Окно вокруг глаза, а не весь кадр: перевод в серое на полном кадре ради
    # одного глаза — это почти всё время самотеста.
    pad = int(np.ceil(0.24 * d)) + 3
    x0, y0 = max(0, int(centre[0]) - pad), max(0, int(centre[1]) - pad)
    x1 = min(img.shape[1], int(centre[0]) + pad)
    y1 = min(img.shape[0], int(centre[1]) + pad)
    if x1 - x0 < 8 or y1 - y0 < 8:
        return None
    gray = cv2.cvtColor(img[y0:y1, x0:x1], cv2.COLOR_BGR2GRAY).astype(np.float64)
    centre = centre - np.array([x0, y0], np.float64)
    ang = np.deg2rad(np.linspace(-40, 40, 21))
    dirs = np.concatenate([np.outer(np.cos(ang), ex) + np.outer(np.sin(ang), ey),
                           -np.outer(np.cos(ang), ex) + np.outer(np.sin(ang), ey)])
    rr = np.arange(0.040, 0.210, 0.002)
    prof = []
    for r in rr:
        p = centre + dirs * (r * d)
        xs = np.clip(p[:, 0], 0, gray.shape[1] - 1).astype(np.int32)
        ys = np.clip(p[:, 1], 0, gray.shape[0] - 1).astype(np.int32)
        prof.append(float(np.median(gray[ys, xs])))
    prof = np.asarray(prof)
    inner = float(np.median(prof[(rr >= 0.060) & (rr <= 0.080)]))   # радужка
    outer = float(np.median(prof[(rr >= 0.150) & (rr <= 0.200)]))   # белок
    if outer - inner < 12.0:
        # Белок не светлее радужки на сколько-нибудь заметную величину: глаз в
        # тени, прищурен или блик во всю радужку. Края здесь не найти, и врать
        # числом нельзя — этот глаз в проверку не идёт.
        return None
    half = (inner + outer) / 2.0
    over = np.nonzero((rr >= 0.080) & (prof >= half))[0]
    return float(rr[over[0]]) if over.size else None


def landmark_check(face):
    """Проверить разметку из шапки на ОДНОМ лице. Возвращает список нарушений.

    Разметка 2d106det нигде не документирована и установлена экспериментом. Если
    insightface переставит порядок точек, метрика начнёт мерить бровь — и молча,
    потому что число она всё равно вернёт. Проверяется то, что от порядка точек
    не зависит: центр глаза обязан лежать ВНУТРИ контура века и рядом со зрачком
    из пяти точек детектора, а контур обязан этот центр окружать со всех сторон.

    Допуск `CENTRE_TOL` широкий намеренно. Два выхода одной сети про один и тот
    же зрачок расходятся на реальных кадрах на заметную долю IPD — на бликующем
    глазу пятиточечный детектор промахивается сам. Ловится здесь не эта дрожь, а
    перестановка: съехавший на бровь или на рот набор даёт промах в разы
    больший, и его же ловят две другие проверки.
    """
    bad = []
    k106 = np.asarray(face["kps106"], np.float64)
    k5 = np.asarray(face["kps"], np.float64)
    d = float(face["ipd_px"])
    for w, spec in EYES.items():
        c = k106[spec["centre"]]
        poly = k106[spec["lid"]]
        off = float(np.hypot(*(c - k5[spec["kps5"]]))) / d
        if off > CENTRE_TOL:
            bad.append(f"{w}: центр {spec['centre']} в {off:.3f} IPD от зрачка "
                       f"детектора — разметка 106 точек не та, что в шапке")
        if cv2.pointPolygonTest(poly.astype(np.float32),
                                (float(c[0]), float(c[1])), False) < 0:
            bad.append(f"{w}: центр {spec['centre']} лежит ВНЕ контура века "
                       f"{spec['lid']} — это разные части лица")
        rel = poly - c
        # Контур обязан окружать центр: точки должны найтись во всех четырёх
        # четвертях. Съехавший на бровь набор лежит с одной стороны.
        quads = {(x > 0, y > 0) for x, y in rel}
        if len(quads) < 4:
            bad.append(f"{w}: контур века {spec['lid']} не окружает центр — "
                       f"точки лежат в {len(quads)} четвертях из четырёх")
        rr = np.hypot(rel[:, 0], rel[:, 1]) / d
        if not (0.10 <= rr.max() <= LID_R_MAX):
            bad.append(f"{w}: контур века на {rr.max():.3f} IPD от центра — "
                       f"это не веко")
    return bad


