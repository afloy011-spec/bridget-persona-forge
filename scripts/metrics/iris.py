def _frames(argv):
    if argv:
        out = []
        for a in argv:
            if os.path.isdir(a):
                for ext in ("*.png", "*.jpg", "*.jpeg"):
                    out += glob.glob(os.path.join(a, "**", ext), recursive=True)
            else:
                out.append(a)
        return sorted(f for f in out
                      if "sheet" not in os.path.basename(f).lower())
    # По умолчанию берутся И кадры проекта, И пул кастинга. Кастинг здесь не
    # отрицательный класс (цвет глаз у него тот же, см. шапку), а проверка
    # ШИРИНЫ положительного класса: полоса, подогнанная под одно лицо, на
    # шестнадцати других лицах разъезжается, и увидеть это надо в калибровке, а
    # не на сдаче.
    root = work_root()
    out = []
    for proj in sorted(os.listdir(root)) if os.path.isdir(root) else []:
        out += sorted(glob.glob(os.path.join(root, proj, "frames", "*", "*.png")))
        out += sorted(glob.glob(os.path.join(root, proj, "frames", "*.png")))
        out += sorted(glob.glob(os.path.join(root, proj, "casting", "cast_*.png")))
    return out


def _fmt(r):
    if r["value"] is None:
        return "   —   ", "  —  "
    return f"{r['value']:7.1f}", f"{r['iris_chroma']:5.2f}"


def main():
    setup_console()
    files = _frames(sys.argv[1:])
    if not files:
        raise SystemExit("нечего мерить: передайте кадры или папку")
    from metrics.faces import detect

    g = manifest()["gates"]
    # Пороги метрика читает из манифеста БЕЗ запасных значений — и правильно
    # делает. Но голый KeyError посреди самотеста называет один ключ и не
    # говорит, что с ним делать, а ключей пять и заводятся они разом.
    absent = [k for k in ("iris_hue_max", "iris_chroma_min",
                          "iris_min_ipd_px", "iris_expect") if k not in g]
    if absent:
        raise SystemExit(
            "в assets.json → gates нет ключей: " + ", ".join(absent) + ".\n"
            "  Метрика читает пороги из манифеста без запасных значений: "
            "запасное значение — это\n  второй, невидимый порог, и разойтись с "
            "манифестом он может только молча.\n"
            "  Их значения и пояснение к ним — в integration этой метрики.")
    lo = float(g["iris_hue_min"]) if g.get("iris_hue_min") is not None else None
    hi = float(g["iris_hue_max"])
    print(f"полоса тона радужки {lo if lo is not None else 'без низа'}…{hi}° "
          f"при хроме не ниже "
          f"{g['iris_chroma_min']}; пол по IPD {g['iris_min_ipd_px']} px; "
          f"полоса откалибрована под «{g['iris_expect']}»")
    print(f"кольцо {RING_IN}…{RING_OUT} IPD, белок {SCLERA_IN}…{SCLERA_OUT} IPD "
          f"в секторе ±{SCLERA_CONE:.0f}°, блик выше {SPEC_REL} яркости белка\n")
    print(f"{'кадр':30} {'вариант':14} {'IPD':>6} {'тон':>7} {'хрома':>6} "
          f"{'px':>6} {'глаза':>6}  вердикт")

    bad = 0
    pos, neg, borderline, light, disagree, limbus = [], {}, [], [], [], []
    light_raw = []          # то же, но с ВЫКЛЮЧЕННОЙ отбивкой по белку
    under_floor = []        # вердикты кадров, отвергнутых полом по крупности,
                            # если пол опустить: чем пол оправдан
    for path in files:
        img = load_bgr(path)
        name = os.path.basename(path)[:30]
        # Лицо ищется ОДИН раз по неиспорченной копии и раздаётся вариантам:
        # перекраска радужки и подмена света геометрию не меняют, а детектор на
        # них слегка плывёт, и варианты сравнивались бы по разным кольцам.
        face = detect(img)
        if face["state"] != PASS:
            print(f"{name:30} {'лица нет':14} {face['note']}")
            continue
        if not face.get("kps106"):
            print(f"{name:30} {'нет 106 точек':14} калибровать нечем")
            bad += 1
            continue
        for why in landmark_check(face):
            print(f"{name:30} РАЗМЕТКА: {why}")
            bad += 1

        base = iris(img, face=face, gates=g)
        if base["state"] == NOT_MEASURED:
            # Кадр, на котором метрика отказалась считать по своей же
            # объявленной причине, из калибровки выпадает целиком: законный
            # отказ — не расхождение, и краснеть на нём нельзя.
            print(f"{name:30} {'вне калибровки':14} {base['note']}")
            # Отвергнутый ПОЛОМ ПО КРУПНОСТИ домеряется с опущенным полом: пол
            # обязан беречь годные кадры от ложного провала, и если он не
            # бережёт ни одного, он только режет покрытие.
            if face["ipd_px"] < float(g["iris_min_ipd_px"]):
                low = dict(g, iris_min_ipd_px=0)
                r = iris(img, face=face, gates=low)
                if r["state"] != NOT_MEASURED:
                    under_floor.append(r["state"])
            continue

        variants = [("как снято", img)]
        variants += [(p, recolour(img, face, p)) for p in PIGMENTS]
        variants += [(nm, relight(img, nm)) for nm in ILLUMINANTS]
        res = {}
        for tag, v in variants:
            r = iris(v, face=face, gates=g)
            res[tag] = r
            hv, cv_ = _fmt(r)
            print(f"{name:30} {tag:14} {r.get('ipd_px', 0):6.0f} {hv} {cv_} "
                  f"{r.get('iris_px', 0):6d} {r.get('eyes_measured', 0):6d}  "
                  f"{r['state']}"
                  f"{'  — ' + r['note'] if r['note'] else ''}")

        pos.append(base["value"])
        if base["state"] != PASS:
            bad += 1
            print(f"{'':30} НАРУШЕНО: настоящий кадр обязан проходить ворота")
        if base.get("eyes_disagree_deg") is not None:
            disagree.append((base["iris_chroma"], base["eyes_disagree_deg"]))
        for w in EYES:
            rr = limbus_radius(img, face, w)
            if rr is not None:
                limbus.append(rr)

        # ПОРЯДОК — то, что от поколения кадров не зависит. Метрика обязана
        # отвечать на смену пигмента в правильную сторону: карий теплее (тон
        # меньше), голубой холоднее (тон больше). Если порядок сломался,
        # метрика не мерит цвет радужки, и подбирать пороги бессмысленно.
        for pg, want in (("карий", "теплее"), ("голубой", "холоднее")):
            r = res[pg]
            if r["value"] is None:
                bad += 1
                print(f"{'':30} НАРУШЕНО: {pg} не замерен — {r['note']}")
                continue
            ok = (r["value"] < base["value"] if want == "теплее"
                  else r["value"] > base["value"])
            if not ok:
                bad += 1
                print(f"{'':30} НАРУШЕНО: перекрашенный в {pg} обязан быть "
                      f"{want} исходного")
        for pg in PIGMENTS:
            v = res[pg]["value"]
            if v is None:
                continue
            if pg in BORDERLINE:
                borderline.append(v)
            else:
                neg.setdefault(pg, []).append(v)

        # СВЕТ. Ради этой проверки метрика и отбивается по белку. Порог
        # LIGHT_TOL, а не «примерно столько же»: утверждение, которое не может
        # оказаться ложным, ничего не проверяет.
        #
        # ЧТО ИМЕННО ЗАПРЕЩЕНО. Смене света запрещено превращать PASS в FAIL и
        # запрещено двигать тон дальше LIGHT_TOL. Превратить замер в отказ ей
        # МОЖНО: свеча честно гасит насыщенность, и радужка, стоявшая у порога
        # хромы, под ней действительно перестаёт читаться. Считать это
        # нарушением значило бы требовать от метрики видеть то, чего в кадре
        # уже нет. Чтобы послабление не выродилось в «всегда отказываю»,
        # отказы считаются и печатаются: их не должно быть большинство.
        # Контрольная точка отсчёта считается ОДИН раз на кадр: она от подмены
        # света не зависит, а замер радужки не бесплатный.
        raw0 = iris(img, face=face, gates=g, balance=False)
        for nm in ILLUMINANTS:
            r = res[nm]
            if r["state"] == FAIL:
                bad += 1
                print(f"{'':30} НАРУШЕНО: «{nm}» превратил проходной кадр в "
                      f"провал — {r['note']}")
                continue
            if r["value"] is None:
                light.append(None)
                print(f"{'':30} свет довёл до отказа: «{nm}» — {r['note']}")
                continue
            drift = abs(r["value"] - base["value"])
            light.append(drift)
            if drift > LIGHT_TOL:
                bad += 1
                print(f"{'':30} НАРУШЕНО: «{nm}» увёл тон на {drift:.1f}° "
                      f"(потолок {LIGHT_TOL}°) — баланс по белку не держит")
            # Контроль: тот же кадр и тот же свет, но белая карта заменена на
            # серый той же яркости. Это и есть «а если бы отбивки не было».
            raw1 = iris(relight(img, nm), face=face, gates=g, balance=False)
            if raw0["value"] is not None and raw1["value"] is not None:
                light_raw.append(abs(raw1["value"] - raw0["value"]))
        print()

    if not pos:
        raise SystemExit("до калибровки не дошёл ни один кадр: лица либо не "
                         "найдены, либо мельче gates.iris_min_ipd_px, либо "
                         "радужка обесцвечена")

    print(f"настоящая радужка ({len(pos)}): {min(pos):.1f}…{max(pos):.1f}°")
    for pg in sorted(neg):
        v = neg[pg]
        print(f"перекрашено в {pg} ({len(v)}): {min(v):.1f}…{max(v):.1f}°")
    if borderline:
        print(f"пограничный {'/'.join(BORDERLINE)} ({len(borderline)}): "
              f"{min(borderline):.1f}…{max(borderline):.1f}° — на провал НЕ "
              f"проверяется: глазами он читается как ореховый")
    if light:
        drifts = [d for d in light if d is not None]
        refused = len(light) - len(drifts)
        print(f"уход тона от смены света: до {max(drifts):.1f}° при потолке "
              f"{LIGHT_TOL}° ({refused} отказов из {len(light)} подмен)")
        if refused * 2 >= len(light):
            bad += 1
            print("  СВЕТ ГАСИТ МЕТРИКУ: под подменённым освещением она "
                  "отказывается считать чаще, чем считает — послабление про "
                  "«свеча честно гасит насыщенность» превратилось в отказ "
                  "мерить вообще")
        # ЧТО ИМЕННО ДЕЛАЕТ БЕЛОК. Абсолютный потолок сам по себе выключенную
        # отбивку почти не ловит: без неё уход тона того же порядка, что и
        # потолок. Поэтому проверяется ВКЛАД белой карты — тот же кадр, тот же
        # свет, белая точка заменена на серый той же яркости.
        if light_raw:
            med, med_raw = float(np.median(drifts)), float(np.median(light_raw))
            print(f"  вклад белка: с отбивкой медиана {med:.1f}°, без неё "
                  f"{med_raw:.1f}° (нужно вдвое хуже без неё)")
            if med_raw < 2 * med:
                bad += 1
                print("  БЕЛОК НИЧЕГО НЕ ДАЁТ: без отбивки по белку тон уходит "
                      "не хуже, чем с ней. Либо белая карта берётся не с белка, "
                      "либо подмена света перестала быть подменой света — в "
                      "любом случае обоснование метрики больше не выполняется")
    if limbus:
        # Судится ДЕСЯТЫЙ ПЕРЦЕНТИЛЬ, а не минимум: поиск края — грубая
        # диагностика по одной картинке, и на отдельном глазу (блик во всю
        # радужку, веко почти закрыто) он промахивается. Утверждение здесь про
        # набор кадров: «радужка у этого поколения крупнее кольца», и оно
        # проверяется тем, что промахнуться на десятой части глаз можно, а на
        # трети — уже нет.
        p10 = float(np.percentile(limbus, 10))
        print(f"край радужки, найденный по картинке: {min(limbus):.3f}…"
              f"{max(limbus):.3f} IPD, p10 {p10:.3f} при кольце до "
              f"{RING_OUT} IPD — запас x{p10 / RING_OUT:.2f} "
              f"(нужен x{RING_MARGIN})")
        if p10 < RING_OUT * RING_MARGIN:
            bad += 1
            print(f"  КОЛЬЦО ПОДОШЛО К КРАЮ РАДУЖКИ: p10 края {p10:.3f} ближе "
                  f"чем x{RING_MARGIN} от RING_OUT {RING_OUT} — в выборку "
                  f"затекает белок, и метрика меряет его, а не пигмент. Это "
                  f"поколение кадров рисует радужку мельче прежнего: кольцо "
                  f"надо сузить и пороги пересчитать этим же самотестом")
    if under_floor:
        spoiled = sum(1 for s in under_floor if s == FAIL)
        print(f"кадры мельче iris_min_ipd_px ({len(under_floor)}), домеренные с "
              f"опущенным полом: ворота забраковали бы {spoiled}")
        if not spoiled:
            bad += 1
            print("  ПОЛ ПО КРУПНОСТИ НИЧЕГО НЕ БЕРЕЖЁТ: ни один мелкий кадр "
                  "без него не провалился бы,\n  то есть пол только режет "
                  "покрытие. Опустить его или обосновать заново.")
    if disagree:
        print("расхождение двух глаз одного лица против хромы "
              "(по нему ставится iris_chroma_min):")
        for a, b in ((0, 3), (3, 5), (5, 8), (8, 99)):
            s = [d for c, d in disagree if a <= c < b]
            if s:
                print(f"  хрома {a}-{b}: n={len(s):3d}  расхождение медиана "
                      f"{np.median(s):5.1f}°  макс {max(s):5.1f}°")

    # ВЕРХНИЙ ПОРОГ обязан стоять в НАСТОЯЩЕМ зазоре — так же, как порог
    # резкости. Голубой и серый от зелёно-орехового отделяются начисто, и если
    # зазор закрылся или порог из него вышел, самотест краснеет.
    cold = sorted(v for pg in ("голубой", "серый") for v in neg.get(pg, []))
    if cold:
        pos_hi, cold_lo = max(pos), min(cold)
        print(f"\nверх: настоящая радужка до {pos_hi:.1f}° · холодная от "
              f"{cold_lo:.1f}° · порог iris_hue_max {hi}")
        if pos_hi >= cold_lo:
            bad += 1
            print("  ЗАЗОРА НЕТ: настоящие и холодные кадры перекрылись — "
                  "верхним порогом их не разделить ни при каком значении")
        elif not (pos_hi < hi < cold_lo):
            bad += 1
            print(f"  ПОРОГ ВНЕ ЗАЗОРА: iris_hue_max надо перенести в "
                  f"({pos_hi:.1f}, {cold_lo:.1f})")

    # НИЖНИЙ ПОРОГ. Зазора там НЕТ и не будет: золотое кольцо орехового глаза
    # по пигменту то же, что светло-карая радужка. Поэтому проверяются два
    # более слабых, но честных свойства, а не выдуманный зазор.
    warm = sorted(neg.get("карий", []))
    if warm and lo is None:
        print(f"\nниз: карий {min(warm):.1f}…{max(warm):.1f}° · настоящая "
              f"радужка от {min(pos):.1f}° · нижнего порога НЕТ — и правильно: "
              f"классы перекрыты на {max(0.0, max(warm) - min(pos)):.1f}°, "
              f"разделить их тоном нельзя ни при каком значении")
    elif warm:
        caught = sum(1 for v in warm if v < lo)
        print(f"низ: карий {min(warm):.1f}…{max(warm):.1f}° · настоящая радужка "
              f"от {min(pos):.1f}° · порог iris_hue_min {lo}")
        print(f"  ЗАЗОРА СНИЗУ НЕТ И НЕ БУДЕТ (перекрытие "
              f"{max(0.0, max(warm) - min(pos)):.1f}°): порог стоит ПОД всем "
              f"положительным классом и ловит {caught} карих из {len(warm)}")
        if lo >= min(pos):
            bad += 1
            print(f"  ПОРОГ СЛИШКОМ ВЫСОК: iris_hue_min {lo} валит настоящие "
                  f"кадры начиная с {min(pos):.1f}° — опустить ниже")
        if caught * 2 < len(warm):
            bad += 1
            print("  ПОРОГ НИЧЕГО НЕ ЛОВИТ: меньше половины перекрашенных в "
                  "карий кадров проваливают ворота — нижняя граница перестала "
                  "быть воротами и стала украшением")

    print(f"\nРАСХОЖДЕНИЙ: {bad}" if bad else
          "\nсходится: настоящая радужка проходит, голубая и серая падают, "
          "смена света тон не двигает,\nкольцо лежит внутри радужки. Светло-"
          "карий и янтарный этими воротами НЕ отделяются — см. шапку.")
    raise SystemExit(1 if bad else 0)


