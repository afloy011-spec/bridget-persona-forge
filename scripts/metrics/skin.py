#!/usr/bin/env python3
"""Микрорельеф кожи: доля щёк и лба, на которой поры и морщины стёрты.

  py -3 scripts/metrics/skin.py [<png> …]

Без аргументов проходит по `<work_root>/bridget/frames` и печатает оригиналы
против нарочно заглаженных копий. Пороги самотест берёт из манифеста и
печатает первой строкой — в этой шапке их нет намеренно, см. ниже.

ЧТО БЫЛО НЕ ТАК С ФОРМУЛИРОВКОЙ. «Доля кожи без микрорельефа» невыполнима как
написано: не сказано, что считать микрорельефом. Детектор, настроенный на
«перепад мельче нескольких пикселей», на портрете крупным планом видит поры, а
на кадре в полный рост — уже целые морщины; одна и та же кожа получает разные
оценки, и метрика меряет крупность плана.

МАСШТАБ ЗАДАН В ДОЛЯХ МЕЖЗРАЧКОВОГО РАССТОЯНИЯ. IPD у любого взрослого
практически один и тот же — это единственная линейка на лице, не зависящая от
кадра. От неё считаются все три числа метрики: сторона участка кожи, граница
верхних частот («микрорельеф») и окно, по которому усредняется энергия. Сами
доли лежат константами рядом с кодом (`PATCH_IPD`, `HP_IPD`, `WIN_IPD`), а
самотест печатает их и переводит границу микрорельефа в миллиметры.

РЕЛЬЕФ МЕРЯЕТСЯ ОТНОСИТЕЛЬНЫМ КОНТРАСТОМ (энергия верхних частот, делённая на
локальную яркость), а не абсолютным. Иначе тёмная щека при свечах читается как
пластик просто потому, что в тени меньше сигнала: у ресторанной ячейки щека
заметно темнее, чем у оконной, а рельеф кожи у них одинаковый.

ВЫБРОСЫ ВЫКИДЫВАЮТСЯ. Из участка выбрасываются пиксели, отстоящие от медианы
яркости дальше нескольких MAD (`MAD_K`): это прядь волос, край очков, блик.
Волос даёт огромный «рельеф» и маскировал бы заглаженную кожу вокруг.

ЗАМЕРОВ В ЭТОЙ ШАПКЕ НЕТ, И ЭТО ПРАВИЛО, А НЕ ЛЕНЬ. Здесь стояла таблица
«оригиналы / Gauss / билатеральный фильтр» по двум поколениям кадров и полоса
ворот резкости — и всё это разошлось с кадрами на диске: поле рельефа
опускали, `face_sharp_min` поднимали, а проза оставалась прежней и продолжала
звучать как обоснование порогов. Число, которое нельзя пересчитать на месте,
рядом с кодом, который это же число меняет, — не документация, а ловушка; то
же правило и по той же причине записано в `assets.json` →
`gates._identity_erratum`. Актуальные числа печатает самотест:
`py -3 scripts/metrics/skin.py`.

ПОЛЕ РЕЛЬЕФА — СВОЙСТВО РЕНДЕРА, А НЕ КОНСТАНТА. Это единственная величина
метрики, привязанная к абсолютному контрасту, и при смене базовой модели или
стека лор она уезжает целиком: поле, снятое на прошлом поколении кадров, потом
объявляет «стёртой» почти всю кожу на безупречном кадре. Поэтому поле живёт в
манифесте (`gates.skin_relief_floor`), а не в коде, и перекалибровка — это тот
же самотест: оригиналы обязаны проходить, билатеральные копии — падать.
Отношение между честной кожей и аэрографом при этом держится, уезжает только
абсолютная шкала.

МЫЛО ЛОВИТСЯ НЕ ЗДЕСЬ, И ЭТО НЕ ДЫРА. Gauss задан в ПИКСЕЛЯХ, а метрика меряет
в долях IPD — линейки разные: на крупном плане размытие мельче микрорельефа,
который метрика ищет, и доля стёртой кожи до порога не дотягивает; на мелком
лице то же размытие с микрорельефом сопоставимо и ловится. Требовать от этих
ворот провала на пиксельном размытии значило бы требовать, чтобы они мерили
крупность плана, — ровно то, от чего метрику и уводили. Мыло валят ворота
резкости, поэтому самотест печатает обе колонки и требует, чтобы размытый кадр
падал хоть где-то, а аэрограф — именно здесь.

РАЗДЕЛ ТРУДА С РЕЗКОСТЬЮ СЧИТАЕТСЯ, А НЕ ОБЪЯВЛЯЕТСЯ. Итогом самотеста стояла
зашитая строка про то, что билатеральный фильтр ворота резкости проходит и
падает только на коже. Она печаталась как вывод независимо от данных — в том
числе когда таблица прямо над ней показывала обратное, — и самотест при этом
выходил нулём. Теперь итог считается по собранным строкам таблицы (см.
`labour_split`), и если ворота кожи перестали ловить то, что резкость
пропускает, самотест говорит это вслух и возвращает ненулевой код: именно этим
утверждением обоснованы отдельные ворота кожи.

Лицо мельче `gates.min_face_ipd_px` — `NOT_MEASURED`: на мелком лице верхняя
граница микрорельефа уходит под предел дискретизации, и мерить там нечего.
"""
import sys, os, glob

import numpy as np
import cv2

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from _util import setup_console, manifest
from metrics import load_bgr
from metrics.verdict import FAIL, NOT_MEASURED, PASS, gate, not_measured

PATCH_IPD = 0.30     # сторона участка кожи в долях IPD
HP_IPD = 0.010       # граница «микрорельефа» в долях IPD
WIN_IPD = 0.05       # окно, по которому усредняется энергия рельефа
MAD_K = 2.5          # отсечка выбросов внутри участка
IPD_MM = 63.0        # межзрачковое расстояние взрослого, мм. Нужно только для
                     # печати: перевод границы микрорельефа в миллиметры стоял
                     # прозой в шапке и устаревал вместе с ней, а посчитанный
                     # из HP_IPD он не может разойтись с кодом.

# Род порчи, по которому в конце считается раздел труда с воротами резкости.
# Строк ровно две, потому что и ворот двое: аэрограф — то, ради чего написаны
# ворота кожи, мыло — то, ради чего написаны ворота резкости.
AIRBRUSH = "аэрограф"
BLUR = "мыло"


def skin_patches(bgr, face, patch_ipd=PATCH_IPD):
    """Щёки и лоб по пяти точкам детектора. Возвращает (участки, IPD).

    Точки: 0 — левый глаз, 1 — правый, 2 — нос, 3 и 4 — углы рта. Оси строятся
    от линии глаз, а не от осей кадра: на наклонённой голове участок «щека»
    иначе уезжает в волосы. Направление «вниз» берётся по рту — так участки
    остаются на месте и на перевёрнутом (зеркальное селфи) кадре.
    """
    k = np.asarray(face["kps"], np.float32)
    le, re, ml, mr = k[0], k[1], k[3], k[4]
    d = float(face["ipd_px"])
    ex = (re - le) / (np.linalg.norm(re - le) + 1e-6)
    ey = np.array([-ex[1], ex[0]], np.float32)
    mid = (le + re) / 2.0
    if float(np.dot((ml + mr) / 2.0 - mid, ey)) < 0:
        ey = -ey

    centres = {
        "щека левая": le + ey * 0.55 * d - ex * 0.10 * d,
        "щека правая": re + ey * 0.55 * d + ex * 0.10 * d,
        "лоб": mid - ey * 0.55 * d,
    }
    r = int(round(patch_ipd * d / 2))
    out = {}
    for name, c in centres.items():
        cx, cy = int(round(float(c[0]))), int(round(float(c[1])))
        x0, y0 = max(0, cx - r), max(0, cy - r)
        x1 = min(bgr.shape[1], cx + r)
        y1 = min(bgr.shape[0], cy + r)
        # Обрезанный краем кадра участок пропускаем целиком: половина щеки
        # даёт долю, посчитанную не по той площади, а по какой — не видно.
        if x1 - x0 >= 1.5 * r and y1 - y0 >= 1.5 * r:
            out[name] = bgr[y0:y1, x0:x1]
    return out, d


def relief(patch, ipd):
    """Относительный микрорельеф участка, одно число на пиксель.

    Возвращает только пиксели, пережившие отсечку выбросов; пустой массив
    означает, что участок целиком — волосы или блик.
    """
    g = cv2.cvtColor(patch, cv2.COLOR_BGR2GRAY).astype(np.float32)
    sigma = max(0.8, HP_IPD * ipd)
    hp = g - cv2.GaussianBlur(g, (0, 0), sigma)
    win = max(3, int(WIN_IPD * ipd)) | 1
    energy = cv2.GaussianBlur(hp * hp, (win, win), 0)
    base = cv2.GaussianBlur(g, (win, win), 0) + 1e-3
    rel = np.sqrt(np.maximum(energy, 0.0)) / base

    med = float(np.median(g))
    mad = float(np.median(np.abs(g - med))) + 1e-3
    return rel[np.abs(g - med) < MAD_K * mad]


def skin(src, face=None, gates=None):
    """Ворота микрорельефа. Возвращает результат в формате `verdict.gate`."""
    g = gates or manifest()["gates"]
    # Пороги берутся из манифеста БЕЗ запасных значений. Запасное значение —
    # это второй, невидимый порог: манифест правят, а метрика продолжает
    # считать по числу, зашитому здесь, и разойтись они могут только молча.
    # Так и разошлась шапка этого файла с `face_sharp_min`. Отсутствие ключа —
    # поломанный манифест, и сказать об этом надо вслух: раннер ворот ловит
    # исключение метрики и превращает его в NOT_MEASURED с причиной.
    hi = float(g["skin_smooth_max"])
    floor = float(g["skin_relief_floor"])
    min_ipd = float(g["min_face_ipd_px"])

    img = load_bgr(src)
    if face is None:
        from metrics.faces import detect
        face = detect(img)
    if not face or face.get("state") != PASS:
        why = (face or {}).get("note", "лицо не передано и не найдено")
        return not_measured("skin", f"кожа не замерена — {why}")
    if face["ipd_px"] < min_ipd:
        return not_measured(
            "skin", f"лицо мелкое: IPD {face['ipd_px']:.0f} px < {min_ipd:.0f} — "
                    f"детектор рельефа ушёл бы под пиксель", ipd_px=face["ipd_px"])

    patches, ipd = skin_patches(img, face)
    values = [relief(p, ipd) for p in patches.values()]
    values = [v for v in values if v.size]
    if not values:
        return not_measured("skin", "участков кожи не осталось: кадр обрезан "
                                    "или щёки и лоб закрыты", ipd_px=ipd)

    rel = np.concatenate(values)
    share = float((rel < floor).mean())
    return gate("skin", share, hi=hi,
                note="кожа заглажена: аэрограф стирает и рельеф, и возраст"
                     if share > hi else "",
                skin_smooth=share, relief_median=float(np.median(rel)),
                relief_floor=floor, patches=len(values), ipd_px=ipd)


def measure(src, face=None, gates=None):
    """Второе имя тех же ворот: `gates.py` ищет метрику по списку кандидатов.

    Синоним, а не отдельный расчёт. Обёртка, отдающая голые числа, лишила бы
    результат поля `state`, и раннер объявил бы живую метрику незамером —
    молча и на всём наборе, из-за одной перестановки в списке имён.
    """
    return skin(src, face=face, gates=gates)


def labour_split(rows):
    """Итог самотеста, ПОСЧИТАННЫЙ ПО ТАБЛИЦЕ. Возвращает (текст, сходится ли).

    `rows` — по строке на каждую испорченную копию: (род порчи, состояние
    ворот кожи, состояние ворот резкости).

    Здесь стояла готовая фраза «билатеральный фильтр проходит ворота резкости и
    падает на коже». Она печаталась как вывод независимо от того, что показала
    таблица над ней, и самотест выходил нулём даже когда резкость валила
    аэрограф на большинстве копий. Утверждение, которое не может оказаться
    ложным, не проверяет ничего, поэтому оно сведено к счётчикам по той самой
    таблице:

      дыра — испорченную копию не поймала ни одна из двух метрик. Провал в
        любом случае: порчу обязано заметить хоть что-нибудь;
      аэрограф мимо резкости — то, ради чего ворота кожи стоят отдельно. Их
        обоснование звучит «резкость аэрограф пропускает», а это утверждение о
        ТИПИЧНОЙ копии: оно держится, пока таких копий больше, чем тех, что
        резкость валит и сама. Сравниваются два счётчика, порога здесь нет;
      мыло мимо кожи — обратная сторона того же. Если кожа валит и всё мыло,
        то на этом материале обе метрики ловят одно и то же, и разделения
        труда между ними нет.
    """
    out = [f"раздел труда, посчитанный по таблице выше "
           f"({len(rows)} испорченных копий):"]
    if not rows:
        out.append("  считать не по чему: ни один кадр не дошёл до вариантов")
        return "\n".join(out), False

    dead = [r for r in rows if r[1] != FAIL and r[2] != FAIL]
    air = [r for r in rows if r[0] == AIRBRUSH]
    air_past_sharp = [r for r in air if r[1] == FAIL and r[2] != FAIL]
    air_both = [r for r in air if r[1] == FAIL and r[2] == FAIL]
    blur = [r for r in rows if r[0] == BLUR]
    blur_past_skin = [r for r in blur if r[1] != FAIL]

    ok = True
    out.append(f"  {AIRBRUSH} ({len(air)}): резкость пропускает "
               f"{len(air_past_sharp)}, валит {len(air_both)}")
    out.append(f"  {BLUR} ({len(blur)}): кожа пропускает {len(blur_past_skin)}, "
               f"валит {len(blur) - len(blur_past_skin)}")
    out.append(f"  не поймано ни одной метрикой: {len(dead)}")

    if dead:
        ok = False
        out.append("  ДЫРА: испорченная копия прошла и кожу, и резкость — "
                   "порча обязана падать хоть где-то")
    if not air:
        ok = False
        out.append(f"  {AIRBRUSH}а в таблице нет — раздел труда проверять не на чем")
    elif len(air_past_sharp) <= len(air_both):
        ok = False
        out.append(
            "  РАЗДЕЛ ТРУДА НЕ ДЕРЖИТСЯ: отдельные ворота кожи обоснованы тем,\n"
            "  что резкость аэрограф ПРОПУСКАЕТ, — а на текущих порогах она\n"
            "  валит его чаще, чем пропускает. Либо порог резкости уехал и его\n"
            "  надо пересчитать самотестом metrics/sharpness.py, либо\n"
            "  обоснование ворот кожи больше не верно и его надо переписать.\n"
            "  Чего делать нельзя — печатать в итоге обратное: ровно этим\n"
            "  строка итога и была раньше.")
    if blur and not blur_past_skin:
        ok = False
        out.append("  кожа валит ВСЁ мыло: на этом материале обе метрики ловят "
                   "одно и то же, и раздела труда между ними нет")
    if ok:
        out.append("  сходится: аэрограф чаще проходит ворота резкости и падает "
                   "только на коже,\n  мыло кожа частью пропускает — одной "
                   "метрикой не ловится ни то, ни другое")
    return "\n".join(out), ok


def _frames(argv):
    if argv:
        return list(argv)
    root = os.path.join(manifest()["paths"]["work_root"], "bridget", "frames")
    return sorted(glob.glob(os.path.join(root, "*", "*.png"))
                  + glob.glob(os.path.join(root, "*.png")))


def main():
    setup_console()
    files = _frames(sys.argv[1:])
    if not files:
        raise SystemExit("нечего мерить: передайте пути к кадрам")
    from metrics.faces import detect
    from metrics.sharpness import sharpness

    g = manifest()["gates"]
    # Пороги печатаются ИЗ МАНИФЕСТА — и полоса резкости тоже, хотя ворота
    # чужие: в шапке этого файла она осталась от старой калибровки и
    # разошлась с манифестом, а таблица под ней продолжала печататься как
    # обоснование порога кожи.
    print(f"пороги из манифеста: доля кожи с рельефом ниже "
          f"{g['skin_relief_floor']} не выше {g['skin_smooth_max']}; "
          f"резкость лица {g['face_sharp_min']}…{g['face_sharp_max']}; "
          f"пол по IPD {g['min_face_ipd_px']} px")
    print(f"масштаб детектора в долях IPD: участок {PATCH_IPD}, микрорельеф "
          f"выше {HP_IPD} (при IPD {IPD_MM:.0f} мм это {HP_IPD * IPD_MM:.2f} мм), "
          f"окно {WIN_IPD}, выбросы дальше {MAD_K} MAD\n")
    print(f"{'кадр':26} {'вариант':18} {'IPD':>6} {'уч.':>4} {'медиана':>8} "
          f"{'доля':>6} {'кожа':>13} {'резкость':>13}")

    bad, rows = 0, []
    for path in files:
        img = load_bgr(path)
        name = os.path.basename(path)
        # Лицо ищется ОДИН раз, по неиспорченной копии, и раздаётся вариантам:
        # замыливание геометрию не меняет, но сдвигает точки детектора, и
        # участки кожи сравнивались бы не одни и те же. Заодно вчетверо меньше
        # запусков buffalo_l — на сорока кадрах это минуты.
        face = detect(img)
        if face["state"] != PASS:
            print(f"{name:26} {'лицо не найдено':18} {face['note']}")
            bad += 1
            continue

        # Кадр, на котором метрика отказалась считать по своей же объявленной
        # причине (лицо мельче пола IPD, щёки за краем кадра), из калибровки
        # выпадает целиком. Иначе законный отказ считался бы расхождением, и
        # самотест краснел бы на кадре в полный рост, где всё правильно.
        base = skin(img, face=face, gates=g)
        if base["state"] == NOT_MEASURED:
            print(f"{name:26} {'вне калибровки':18} {base['note']}")
            continue

        bilat = cv2.bilateralFilter(img, 15, 60, 15)
        # Ожидание задаётся тем, чьи это ворота. Аэрограф обязан падать ЗДЕСЬ —
        # ради него метрика и написана. Обычное мыло падать здесь НЕ обязано:
        # Gauss задан в пикселях, и на крупном плане он мельче микрорельефа,
        # который метрика ищет; ловит его резкость. Требовать провала здесь
        # значило бы требовать от метрики мерить крупность плана — ровно то, от
        # чего её и уводили. Род порчи последним полем: по нему в конце
        # считается раздел труда между этими воротами и воротами резкости.
        variants = [
            ("оригинал", img, "кожа PASS", None),
            ("Gauss σ=1.5", cv2.GaussianBlur(img, (0, 0), 1.5),
             "хоть где-то FAIL", BLUR),
            ("билатеральный x1", bilat, "кожа FAIL", AIRBRUSH),
            ("билатеральный x2", cv2.bilateralFilter(bilat, 15, 60, 15),
             "кожа FAIL", AIRBRUSH),
        ]
        for tag, v, want, kind in variants:
            r = skin(v, face=face, gates=g)
            s = sharpness(v, face=face, gates=g)
            ok = {"кожа PASS": r["state"] == PASS,
                  "кожа FAIL": r["state"] == FAIL,
                  "хоть где-то FAIL": FAIL in (r["state"], s["state"])}[want]
            bad += not ok
            if kind:
                rows.append((kind, r["state"], s["state"]))
            share = "—" if r["value"] is None else f"{r['value']:6.3f}"
            med = "—" if r["value"] is None else f"{r['relief_median']:8.4f}"
            ipd = "—" if r.get("ipd_px") is None else f"{r['ipd_px']:6.0f}"
            sharp_v = "—" if s["value"] is None else f"{s['value']:.0f}"
            print(f"{name:26} {tag:18} {ipd:>6} {r.get('patches', 0):4} "
                  f"{med:>8} {share:>6} {r['state']:>13} "
                  f"{s['state'] + ' ' + sharp_v:>13}"
                  f"{'' if ok else '  ← ОЖИДАЛОСЬ ' + want}")
        print()

    # Колонка резкости здесь не для красоты: она показывает раздел труда, и
    # итог теперь СЧИТАЕТСЯ по ней, а не объявляется заранее.
    report, split_ok = labour_split(rows)
    print(report)
    bad += not split_ok
    if bad:
        print(f"\nРАСХОЖДЕНИЙ: {bad}")
    raise SystemExit(1 if bad else 0)


