# Зеркальные пары точек брови: (её правая, её левая). Порядок внутри пары
# важен только для знака; важно, что 43 сравнивается с 101, а не с 97.
BROW_PAIRS = ((43, 101), (44, 100), (45, 99), (46, 97), (47, 98),
              (48, 105), (49, 104), (50, 102), (51, 103))
BROW_R = tuple(a for a, _ in BROW_PAIRS)
BROW_L = tuple(b for _, b in BROW_PAIRS)

# Контуры глаз БЕЗ центров зрачков (34/38 и 88/92 — одна и та же точка, и она
# вошла бы в среднее дважды, перевесив контур).
EYE_R = (33, 35, 36, 37, 39, 40, 41, 42)
EYE_L = (87, 89, 90, 91, 93, 94, 95, 96)

PUPIL_R, PUPIL_L, NOSE_TIP = 38, 88, 86
SIDES = ("left", "right")


def face_axes(kps106):
    """Система координат лица по 106 точкам: (центр, IPD, ось X, ось Y).

    Ось X — по линии зрачков (наклон головы вычитается целиком), ось Y — вниз
    по лицу. Направление «вниз» сверяется по кончику носа: у перевёрнутой
    головы знак иной, и без сверки брови оказались бы «под» глазами.
    """
    k = np.asarray(kps106, np.float64)
    if k.ndim != 2 or k.shape[0] < 106:
        return None
    er, el = k[PUPIL_R], k[PUPIL_L]
    ex = el - er
    ipd = float(np.hypot(*ex))
    if ipd <= 0:
        return None
    ux = ex / ipd
    uy = np.array([-ux[1], ux[0]])
    centre = (er + el) / 2
    if float((k[NOSE_TIP] - centre) @ uy) < 0:
        uy = -uy
    return centre, ipd, ux, uy


def asymmetry(kps106):
    """Разность высот бровей над своими глазами, в долях IPD.

    Возвращает словарь: `asym` — насколько ЕЁ ЛЕВАЯ бровь выше правой (знак
    положительный = левая выше), `lift_right`/`lift_left` — высота каждой брови
    над своим глазом, `yaw` — смещение кончика носа как оценка поворота головы.
    None, если точек не хватает.
    """
    axes = face_axes(kps106)
    if axes is None:
        return None
    k = np.asarray(kps106, np.float64)
    centre, ipd, ux, uy = axes
    down = k @ uy                       # координата «вниз по лицу», пиксели
    # Высота брови НАД своим глазом: положительная, потому что бровь выше.
    lift_r = float(down[list(EYE_R)].mean() - down[list(BROW_R)].mean()) / ipd
    lift_l = float(down[list(EYE_L)].mean() - down[list(BROW_L)].mean()) / ipd
    return {"asym": lift_l - lift_r, "lift_right": lift_r, "lift_left": lift_l,
            "yaw": float((k[NOSE_TIP] - centre) @ ux) / ipd, "ipd_px": ipd}


def brows(src, face=None, gates=None):
    """Ворота асимметрии бровей. Результат в формате `verdict.gate`."""
    g = gates if gates is not None else manifest()["gates"]
    # Пороги читаются ДО кадра и без запасных значений в коде: запасное
    # значение — это второй, невидимый порог, который продолжает судить после
    # того, как манифест поправили.
    lo = float(g["brow_asymmetry_min"])
    max_yaw = float(g["brow_max_yaw"])
    min_ipd = float(g["min_face_ipd_px"])
    # Сторона — не порог, а объявление о персонаже, и её отсутствие обязано
    # давать NOT_MEASURED с внятной причиной, а не KeyError без подсказки.
    side = (g.get("brow_higher_side") or "").strip().lower()

    if face is None:
        from metrics.faces import detect
        face = detect(src)
    if not face or face.get("state") != PASS:
        return not_measured("brows", (face or {}).get("note") or "лица нет",
                            refusal="face")
    kps = face.get("kps106")
    if not kps:
        return not_measured("brows", "детектор не отдал 106 точек лица — "
                                     "брови описывать нечем", refusal="landmarks")
    m = asymmetry(kps)
    if m is None:
        return not_measured("brows", "по 106 точкам не строится система "
                                     "координат лица", refusal="landmarks")
    # `refusal` — машиночитаемая причина незамера рядом с человеческой. Нужна
    # калибровке: незамер «сторона не объявлена» число НЕ портит (сторона к
    # величине отношения не имеет), а незамер по ракурсу портит целиком, и
    # различать их разбором текста примечания — значит ломать метрику опечаткой.
    extra = {"asym": m["asym"], "lift_right": m["lift_right"],
             "lift_left": m["lift_left"], "yaw": m["yaw"],
             "ipd_px": m["ipd_px"], "side": side or None, "refusal": None}

    if m["ipd_px"] < min_ipd:
        return not_measured("brows", f"лицо мелкое: IPD {m['ipd_px']:.0f} px "
                                     f"< {min_ipd:.0f}",
                            **{**extra, "refusal": "ipd"})
    if abs(m["yaw"]) > max_yaw:
        # Не FAIL: в три четверти ближняя бровь кажется выше у ЛЮБОГО лица, и
        # то же смещение замерено на посторонних женщинах. Провал здесь означал
        # бы, что ворота судят ракурс, а не лицо.
        return not_measured(
            "brows", f"голова повёрнута: смещение носа {m['yaw']:+.3f} IPD при "
                     f"пределе {max_yaw:.3f} — дальняя бровь поднимается "
                     f"ракурсом", **{**extra, "refusal": "yaw"})
    if side not in SIDES:
        return not_measured(
            "brows", "какая бровь выше — не установлено: заполните "
                     "gates.brow_higher_side (left/right) замером по пулу, "
                     "py -3 scripts/metrics/brows.py <кадры>",
            **{**extra, "refusal": "side"})

    # Значение ворот — подъём ОБЪЯВЛЕННОЙ брови. Так порог остаётся простой
    # нижней границей, а знак спрашивается у манифеста, а не у кадра.
    value = m["asym"] if side == "left" else -m["asym"]
    higher = "левая" if m["asym"] > 0 else "правая"
    note = (f"выше её {higher} на {abs(m['asym']):.4f} IPD; карточка обещает "
            f"{'левую' if side == 'left' else 'правую'}")
    return gate("brows", value, lo=lo, hi=None, note=note, **extra)


def measure(src, face=None, gates=None):
    """Второе имя тех же ворот: `gates.py` ищет метрику по списку кандидатов.

    Синоним, а не отдельный расчёт: обёртка, отдающая голое число, лишила бы
    результат поля `state`, и раннер объявил бы живую метрику незамером.
    """
    return brows(src, face=face, gates=gates)


