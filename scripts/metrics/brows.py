def lift_one_brow(img, kps106, side, delta):
    """Поднять ОДНУ бровь кадра на delta*IPD — источник заведомо асимметричных
    кадров для самотеста.

    Своего «известно асимметричного» класса у метрики нет: в природе он и есть
    то, что мы пытаемся замерить. Поэтому положительный класс делается из тех
    же кадров управляемой деформацией — как замыленные копии в sharpness.py.
    Маска эллиптическая и растушёванная: резкий сдвиг прямоугольника даёт шов,
    и детектор ставит точки по шву, а не по брови.
    """
    import cv2
    axes = face_axes(kps106)
    if axes is None:
        return img
    k = np.asarray(kps106, np.float64)
    centre, ipd, ux, uy = axes
    pts = k[list(BROW_L if side == "left" else BROW_R)]
    along = pts @ ux
    length = float(np.hypot(*(pts[int(along.argmax())] - pts[int(along.argmin())])))
    c = pts.mean(axis=0)
    mask = np.zeros(img.shape[:2], np.float32)
    cv2.ellipse(mask, (int(c[0]), int(c[1])),
                (int(length * 0.66), int(ipd * 0.13)),
                float(np.degrees(np.arctan2(ux[1], ux[0]))), 0, 360, 1.0, -1)
    mask = cv2.GaussianBlur(mask, (0, 0), ipd * 0.035)
    d = -uy * delta * ipd                      # вверх по лицу
    h, w = img.shape[:2]
    gx, gy = np.meshgrid(np.arange(w, dtype=np.float32),
                         np.arange(h, dtype=np.float32))
    return cv2.remap(img, gx - mask * float(d[0]), gy - mask * float(d[1]),
                     cv2.INTER_CUBIC, borderMode=cv2.BORDER_REPLICATE)


def _skew(img, kps106, delta, gates):
    """Встречный сдвиг бровей: одна вверх на delta, другая вниз на delta.

    Почему встречно, а не одной бровью на 2*delta. Сдвиг больше примерно
    0.13 IPD детектор точек перестаёт отслеживать: он подтягивает бровь к
    своему априорному месту, и замеренная асимметрия не растёт, а ПАДАЕТ до
    нуля и уходит в минус — проверено лесенкой сдвигов. Два встречных сдвига
    вдвое меньшего размера остаются в той области, где детектор ещё следует за
    картинкой, и дают вдвое большую асимметрию, чем один большой.

    Вторая бровь двигается по точкам, найденным УЖЕ НА СДВИНУТОМ кадре: после
    первого сдвига координаты уехали, и по старым точкам маска легла бы мимо.
    """
    from metrics.faces import detect
    out = lift_one_brow(img, kps106, "left", delta)
    f = detect(out)
    k2 = f["kps106"] if (f["state"] == PASS and f.get("kps106")) else kps106
    return lift_one_brow(out, k2, "right", -delta)


def _rotate(img, deg):
    import cv2
    h, w = img.shape[:2]
    M = cv2.getRotationMatrix2D((w / 2, h / 2), deg, 1.0)
    return cv2.warpAffine(img, M, (w, h), flags=cv2.INTER_CUBIC,
                          borderMode=cv2.BORDER_REPLICATE)


def usable(res):
    """Годится ли результат для калибровки величины.

    Годится замеренный и тот, чей единственный незамер — неустановленная
    сторона: сторона к самому числу отношения не имеет и в этом же прогоне и
    устанавливается. Незамер по лицу, размеру или ракурсу — не годится.
    """
    return res.get("asym") is not None and res.get("refusal") in (None, "side")


def _asym_of(img, gates):
    """Сырая асимметрия варианта кадра: число или None с причиной."""
    from metrics.faces import detect
    r = brows(img, face=detect(img), gates=gates)
    return (r["asym"] if usable(r) else None), r["note"]


def _frames(argv):
    out, skip = [], False
    for a in argv:
        if skip:
            skip = False
            continue
        if a.startswith("--"):
            skip = a in ("--negative", "--lift")
            continue
        out.append(a)
    files = []
    for a in out:
        if os.path.isdir(a):
            for ext in ("*.png", "*.jpg", "*.jpeg"):
                files += glob.glob(os.path.join(a, "**", ext), recursive=True)
        else:
            files.append(a)
    return sorted(f for f in files if "sheet" not in os.path.basename(f).lower())


def _pool(files, gates):
    """Асимметрия по списку кадров: [(имя, asym, yaw)] только для замеренных.

    В пул идут кадры, которые метрика согласилась мерить. На повёрнутых и
    мелких она сама сказала «не сужу», и тянуть их в статистику значило бы
    считать по числам, которые она же объявила недействительными. Незамер
    из-за неустановленной стороны — исключение: сторона тут и устанавливается,
    а к самому числу она отношения не имеет.
    """
    from metrics.faces import detect
    out = []
    for p in files:
        r = brows(p, face=detect(p), gates=gates)
        if usable(r):
            out.append((os.path.basename(p), r["asym"], r["yaw"]))
    return out


def main():
    setup_console()
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        raise SystemExit(1)
    files = _frames(args)
    if not files:
        raise SystemExit("нечего мерить: передайте кадры или папку")
    from metrics.faces import detect

    g = manifest()["gates"]
    lo = float(g["brow_asymmetry_min"])
    noise_max = float(g["brow_noise_max"])
    delta = float(cli_opt(args, "--lift", 0.06))
    side = (g.get("brow_higher_side") or "").strip().lower() or "не установлена"
    print(f"порог видимой асимметрии brow_asymmetry_min {lo} IPD · предел "
          f"поворота brow_max_yaw {g['brow_max_yaw']} · допустимый разброс "
          f"brow_noise_max {noise_max}\nсторона персонажа: {side}")
    print(f"положительный класс: одна бровь поднята, другая опущена на "
          f"{delta} IPD — встречно\n")

    print(f"{'кадр':26} {'вариант':16} {'IPD':>6} {'yaw':>7} {'asym':>9}  примечание")
    bad, plain, lifted, noise = 0, [], [], []
    for path in files:
        img = load_bgr(path)
        name = os.path.basename(path)[:25]
        face = detect(img)
        base = brows(img, face=face, gates=g)
        ipd = "—" if base.get("ipd_px") is None else f"{base['ipd_px']:6.0f}"
        yaw = "—" if base.get("yaw") is None else f"{base['yaw']:+7.3f}"
        val = "—" if base.get("asym") is None else f"{base['asym']:+9.4f}"
        # Кадр, который метрика отказалась судить, из калибровки выпадает
        # целиком, и это не расхождение: она отказалась по объявленной
        # причине. Без этой ветки повёрнутые кадры тянули бы в зазор числа,
        # которые сама метрика признала недействительными.
        print(f"{name:26} {'как снято':16} {ipd:>6} {yaw:>7} {val:>9}  "
              f"{'' if usable(base) else base['note']}")
        if not usable(base):
            print()
            continue

        kps = face["kps106"]
        variants = [("её левая выше", _skew(img, kps, +delta, g)),
                    ("её правая выше", _skew(img, kps, -delta, g)),
                    ("зеркало", img[:, ::-1].copy()),
                    ("наклон +8°", _rotate(img, 8)),
                    ("наклон -8°", _rotate(img, -8))]
        v = {"как снято": base["asym"]}
        for tag, im in variants:
            a, why = _asym_of(im, g)
            v[tag] = a
            shown = "—" if a is None else f"{a:+9.4f}"
            print(f"{name:26} {tag:16} {'':>6} {'':>7} {shown:>9}  "
                  f"{'' if a is not None else why}")

        # Проверяется то, что от рендера не зависит: направление, знак и
        # величина вложенного. Абсолютные числа зависят от кадра целиком.
        checks = [
            ("встречный подъём её левой увеличил asym",
             v["её левая выше"] is not None and v["её левая выше"] > v["как снято"]),
            ("встречный подъём её правой уменьшил asym",
             v["её правая выше"] is not None and v["её правая выше"] < v["как снято"]),
            # Зеркало меняет местами левое и правое, а больше ничего: знак
            # обязан перевернуться, модуль — сохраниться. Допуск — заявленный
            # разброс метрики, иначе проверка мерила бы шум детектора.
            ("зеркало перевернуло знак",
             v["зеркало"] is not None
             and abs(v["зеркало"] + v["как снято"]) <= noise_max),
            ("обе вложенные асимметрии читаются выше порога",
             v["её левая выше"] is not None and v["её правая выше"] is not None
             and min(abs(v["её левая выше"]), abs(v["её правая выше"])) >= lo),
        ]
        for why, ok in checks:
            if not ok:
                bad += 1
                print(f"{'':26} НАРУШЕНО: {why}")

        # РАЗБРОС СЧИТАЕТСЯ ОТДЕЛЬНО ОТ ЗАЗОРА, И ЭТО НЕ ПРИДИРКА. Поворот
        # кадра геометрию лица не меняет, значит всё, что метрика на нём
        # показала иначе, — её собственный разброс. Он у этой метрики
        # СОПОСТАВИМ С ПОРОГОМ (детектор ставит точки брови по-разному на
        # повёрнутом кадре), поэтому в зазор он не складывается — иначе порог
        # видимости пришлось бы задрать выше того, что видно глазу, — а
        # проверяется своим ключом как обещание не ухудшаться.
        stable = [v[t] for t in ("как снято", "наклон +8°", "наклон -8°")
                  if v[t] is not None]
        if len(stable) > 1:
            noise.append((max(stable) - min(stable), name))
        plain.append((abs(v["как снято"]), name))
        for t in ("её левая выше", "её правая выше"):
            if v[t] is not None:
                lifted.append((abs(v[t]), name))
        print()

    if not plain:
        raise SystemExit("до калибровки не дошёл ни один кадр: лица не найдены, "
                         "мельче gates.min_face_ipd_px или повёрнуты сильнее "
                         "gates.brow_max_yaw")

    hi_plain, who_plain = max(plain)
    lo_lift, who_lift = min(lifted) if lifted else (None, None)
    print(f"как снято до {hi_plain:.4f} ({who_plain}) · со встречно сдвинутыми "
          f"бровями от " + (f"{lo_lift:.4f} ({who_lift})" if lo_lift is not None
                            else "—") + f" · порог brow_asymmetry_min {lo}")
    if lo_lift is None:
        bad += 1
        print("  ПОЛОЖИТЕЛЬНОГО КЛАССА НЕТ: ни на одном кадре встречный сдвиг "
              "не замерился — калибровать порог не на чем")
    elif hi_plain >= lo_lift:
        bad += 1
        print(f"  ЗАЗОРА НЕТ: кадры «как снято» и кадры с заведомо разными\n"
              f"  бровями перекрылись — нижним порогом их не разделить ни при\n"
              f"  каком значении. Если {who_plain} — лицо с НАСТОЯЩЕЙ\n"
              f"  асимметрией, ему не место в калибровочном наборе.")
    elif not (hi_plain < lo < lo_lift):
        bad += 1
        print(f"  ПОРОГ ВНЕ ЗАЗОРА: brow_asymmetry_min нужно перенести в "
              f"({hi_plain:.4f}, {lo_lift:.4f}) — сейчас он либо пропускает\n"
              f"  ровные брови, либо валит заведомо разные.")

    if noise:
        worst, who = max(noise)
        print(f"разброс одного кадра от наклона на восемь градусов до "
              f"{worst:.4f} ({who}) при обещанном brow_noise_max {noise_max}")
        if worst > noise_max:
            bad += 1
            print("  РАЗБРОС ВЫРОС: детектор ставит точки брови на повёрнутом\n"
                  "  кадре иначе, чем раньше. Порог видимости от этого не\n"
                  "  двигается — двигается доверие к одному кадру: сверьте\n"
                  "  brow_noise_max замером и решите, годятся ли ворота вообще.")
        if worst >= lo:
            print("  ВНИМАНИЕ: разброс НЕ МЕНЬШЕ порога видимости — ответ по\n"
                  "  одному кадру ненадёжен, и ворота могут быть только\n"
                  "  справочными. Это замеренное свойство детектора точек, а\n"
                  "  не ошибка настройки; блокировать отгрузку по ним нельзя.")

    # ЧТО ПУЛ ГОВОРИТ О ПЕРСОНАЖЕ. Ровно это и заполняет brow_higher_side —
    # и ровно это надо сравнить с посторонними, иначе «признак» опознаёт всех.
    pool = _pool(files, g)
    if pool:
        vals = np.array([a for _, a, _ in pool])
        share = float((np.abs(vals) >= lo).mean())
        print(f"\nпул: замерено {len(vals)} из {len(files)} · медиана "
              f"{np.median(vals):+.4f} ({'её левая' if np.median(vals) > 0 else 'её правая'}"
              f" выше) · разброс {vals.min():+.4f}…{vals.max():+.4f} · "
              f"выше порога {share:.0%} кадров")
    neg = cli_opt(args, "--negative")
    if neg and pool:
        other = _pool(_frames([neg]), g)
        if other:
            ov = np.array([a for _, a, _ in other])
            oshare = float((np.abs(ov) >= lo).mean())
            print(f"чужие: замерено {len(ov)} · медиана {np.median(ov):+.4f} · "
                  f"разброс {ov.min():+.4f}…{ov.max():+.4f} · выше порога "
                  f"{oshare:.0%} кадров")
            print("ПРИЗНАК ОПОЗНАЁТ ПЕРСОНАЖА, только если своих выше порога "
                  "заметно больше, чем чужих;\nиначе он описывает не её, а "
                  "детектор — и ставить по нему ворота нельзя.")
    print("\nсторона персонажа берётся ОТСЮДА, а не из вкуса: gates."
          "brow_higher_side заполняется,\nтолько если медиана пула уверенно "
          "выше порога и чужие её не повторяют.")
    if bad:
        print(f"\nРАСХОЖДЕНИЙ: {bad}")
    raise SystemExit(1 if bad else 0)


if __name__ == "__main__":
    main()
