# ОТРИЦАТЕЛЬНОГО КЛАССА В ПУЛЕ НЕТ, И ЭТО ФАКТ, А НЕ ОТГОВОРКА. Все кадры —
# и героини, и кастинга — сгенерированы по одному описанию волос, поэтому
# «плоского блонда» и «платины» на диске не существует ни одного. Порог,
# поставленный по одной группе, не порог. Отрицательная группа поэтому
# СТРОИТСЯ ПОРЧЕЙ настоящих кадров, и порча — ровно то, что карточка
# запрещает: «one flat blonde tone» и высветленные корни. Мутированные копии
# смотрелись глазами: они читаются как ровный однотонный блонд.
FLAT_TONE = "ровный тон"
BLEACHED = "корни высветлены"
FLAT_LOW = 0.9       # масштаб, выше которого светлота — это свет, а не окраска


def head_mask(shape, face, ipd, centre, ux, uy):
    """Грубая область головы для порчи: эллипс черепа минус овал лица.

    Геометрия, а не маска метрики: порча не должна знать, какие именно точки
    метрика объявила волосами, иначе самотест проверял бы сам себя.
    """
    m = np.zeros(shape[:2], np.float32)
    c = centre + 0.55 * ipd * uy
    ang = float(np.degrees(np.arctan2(ux[1], ux[0])))
    cv2.ellipse(m, (int(c[0]), int(c[1])),
                (int(2.7 * ipd), int(3.1 * ipd)), ang, 0, 360, 1.0, -1)
    oval = np.asarray(face["kps106"], np.float32)[:33]
    poly = oval[OVAL_CHAIN].astype(np.int32)
    face_m = np.zeros(shape[:2], np.uint8)
    cv2.fillConvexPoly(face_m, cv2.convexHull(poly), 255)
    # Овал лица СЖИМАЕТСЯ перед вычитанием на ширину растушёвки. Иначе после
    # размытия края маска у самого лица стоит вполсилы — а лучи длины начинаются
    # ровно там, и порча до них не доходила: у одного кадра порченая копия
    # отличалась от оригинала на два процента.
    r = max(3, int(0.14 * ipd)) | 1
    face_m = cv2.erode(face_m, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (r, r)))
    m[face_m > 0] = 0.0
    # Край растушёван: резкая граница порчи — это ступенька яркости, которую
    # метрика приняла бы за силуэт и оборвала бы на ней луч. Порча обязана
    # менять тон волос и ничего больше.
    return cv2.GaussianBlur(m, (0, 0), max(1.0, 0.06 * ipd))


def flat_tone(img, face, k=0.15):
    """«Один ровный тон»: убрать пятна окраски, оставив свет и фактуру.

    Светлота раскладывается на три слоя — свет по голове (низкие частоты),
    рисунок окраски (средние) и сами волоски (высокие). Гасится ТОЛЬКО
    средний. Порча, которая заодно сносит свет, была бы слишком лёгкой:
    настоящий плоский блонд всё так же имеет освещённую и теневую сторону.
    """
    axes = face_axes(face)
    if axes is None:
        return img
    centre, ipd, ux, uy = axes
    m = head_mask(img.shape, face, ipd, centre, ux, uy)
    lab = cv2.cvtColor(img, cv2.COLOR_BGR2LAB).astype(np.float32)
    L = lab[..., 0]
    # Нижняя граница гашения — весь масштаб, который метрика вообще меряет:
    # местный уровень она берёт по соседям в радиусе LOCAL_IPD, значит рисунок
    # окраски живёт вплоть до размера головы. Гасить только мелкое — значит
    # оставить порченой копии половину исходного разброса.
    low = cv2.GaussianBlur(L, (0, 0), FLAT_LOW * ipd)
    fine = cv2.GaussianBlur(L, (0, 0), max(0.8, TONE_IPD * ipd))
    mid = fine - low
    out = np.clip(L - (1.0 - k) * m * mid, 0, 255)
    lab[..., 0] = out
    return cv2.cvtColor(lab.astype(np.uint8), cv2.COLOR_LAB2BGR)


def bleached_roots(img, face, gates=None):
    """«Отросших корней нет»: поднять светлоту у кожи головы до уровня длины.

    Область берётся по линии роста волос, которую нашла сама метрика, —
    иначе порчу пришлось бы ставить наугад и она била бы мимо. Независимость
    проверяется вторым родом порчи: `flat_tone` линию роста не использует.
    """
    r = analyse(img, face=face, gates=gates)
    if r["why"]:
        return img
    axes = face_axes(face)
    centre, ipd, ux, uy = axes
    probe = Probe(img, ipd, centre, ux, uy)
    m = np.zeros(img.shape[:2], np.float32)
    for x, y in probe.xy(r["root_xy"]).astype(int):
        cv2.circle(m, (int(x), int(y)), max(2, int(0.08 * ipd)), 1.0, -1)
    m = cv2.GaussianBlur(m, (0, 0), max(1.0, 0.04 * ipd))
    lab = cv2.cvtColor(img, cv2.COLOR_BGR2LAB).astype(np.float32)
    # Осветление УМНОЖЕНИЕМ, а не прибавкой. Прибавка гасит относительную
    # фактуру (энергия волосков делится на местную яркость, а та выросла), и
    # осветлённые корни начинали читаться как гладкая кожа — линия роста волос
    # уезжала вверх, полоса корней уходила из порченой области, и порча
    # получалась вдвое слабее, чем задумано. Умножение фактуру не трогает:
    # и числитель, и знаменатель растут одинаково.
    f = r["len_light"] / max(r["root_dark"], 1.0)
    lab[..., 0] = np.clip(lab[..., 0] * (1.0 + m * (max(f, 1.0) - 1.0)), 0, 255)
    return cv2.cvtColor(lab.astype(np.uint8), cv2.COLOR_LAB2BGR)


# --------------------------------------------------------------- самотест ---

# РАЗМЕТКА ГЛАЗАМИ И ЧЕМ ОНА КОНЧИЛАСЬ.
#
# Просмотрены головы всех кадров пула, крупно и по одной: 40 кадров сцен P1-P5,
# 8 сданных кадров и 16 кандидаток кастинга — по два вопроса на кадр: видно ли,
# что у пробора волосы темнее, чем на длине, и несколько ли в массе тонов.
# ОТВЕТ ОКАЗАЛСЯ ОДИН И ТОТ ЖЕ НА ВСЕХ: и корни темнее, и тонов несколько.
# Отрицательного класса в пуле НЕТ НИ ОДНОГО КАДРА, и кастинг его не даёт —
# кандидатки нарисованы по тому же описанию волос, что героиня, поэтому
# отличаются лицом, а не окраской.
#
# Отсюда устройство калибровки: положительная группа — настоящие кадры,
# отрицательная СТРОИТСЯ ПОРЧЕЙ (`flat_tone`, `bleached_roots`) и тоже
# просмотрена глазами — порченые копии читаются как ровный однотонный блонд и
# как голова без отросших корней, то есть ровно как то, что карточка запрещает
# словами «never platinum and never one flat blonde tone».
#
# Ниже — кадры, на которых глаз видит отросшие корни отчётливо, а число выходит
# у самого нуля: волосы у лица лежат в собственной тени, темя освещено, и
# разность «длина минус корни» съедается светом. Два из трёх метрика теперь
# честно отказывается считать (пряди нашлись с одной стороны), третий проходит
# с самым низким числом пула. Список нужен не для исключений из калибровки, а
# чтобы следующий читатель видел, ГДЕ у метрики тонко, и мог проверить, что
# правка это не сломала: самотест печатает их судьбу отдельной строкой.
EYE_TIGHT = ("P3_s20954841_01.png", "02_mirror_selfie_phone.jpg",
             "03_paddle_court.jpg")

CATCH_MIN = 0.75     # доля порченых копий, которую ворота ОБЯЗАНЫ ловить
ORDER_TOL = 0.05     # доля кадров, где порча может не опустить число


def _frames(argv):
    out, skip = [], False
    for a in argv:
        if skip:
            skip = False
            continue
        if a.startswith("--"):
            skip = a in ("--draw",)
            continue
        out.append(a)
    files = []
    for a in out:
        if os.path.isdir(a):
            for ext in ("*.png", "*.jpg", "*.jpeg"):
                files += glob.glob(os.path.join(a, "**", ext), recursive=True)
        else:
            files.append(a)
    if not files:
        root = os.path.join(manifest()["paths"]["work_root"], "bridget", "frames")
        files = glob.glob(os.path.join(root, "*", "*.png"))
    return sorted(f for f in files if "sheet" not in os.path.basename(f).lower())


def draw(src, r, out_path):
    """Куда легла маска. Единственный способ увидеть, что метрика мерила."""
    img = load_bgr(src)
    from metrics.faces import detect
    face = detect(img)
    axes = face_axes(face)
    centre, ipd, ux, uy = axes
    probe = Probe(img, ipd, centre, ux, uy)
    v = img.copy()
    for pts, col in ((r.get("root_xy"), (0, 0, 255)),
                     (r.get("len_xy"), (0, 255, 0))):
        if pts is None or not len(pts):
            continue
        for x, y in np.round(probe.xy(pts)).astype(int):
            if 0 <= x < v.shape[1] and 0 <= y < v.shape[0]:
                cv2.circle(v, (x, y), 2, col, -1)
    return imwrite(out_path, v)


def calibration(rows, lo, key_real, key_mut):
    """Свод по одним воротам: (строки отчёта, сошлось ли).

    `rows` — по строке на кадр: настоящее число и число порченой копии.
    Проверок ТРИ, и все три считаются по этим строкам, а не объявляются:

      честные не валятся — ни один настоящий кадр не ниже порога. Ворота,
        которые бракуют годную работу, хуже отсутствия ворот;
      порча ловится — доля порченых копий ниже порога не меньше `CATCH_MIN`.
        Порог, под который не попадает ничего, ворот не образует;
      порядок — порченая копия обязана давать число НИЖЕ оригинала. Это
        единственная проверка, не зависящая от шкалы: числа уедут с рендером,
        а порядок нет. Допуск `ORDER_TOL` не милость, а замер: на одном кадре
        из пула маска ловит слишком мало пряди, и порча его не сдвигает.

    ЗАЗОР МЕЖДУ ГРУППАМИ СЧИТАЕТСЯ И ПЕЧАТАЕТСЯ, но требовать его целиком
    нельзя, и это честная слабость, а не недосмотр: у самых контровых кадров
    разница «длина минус корни» вдесятеро больше, чем у самых плоско
    освещённых, поэтому хвост порченых копий заходит на голову честных.
    Порог поэтому стоит ПОД честным минимумом, а не в середине зазора.
    """
    pairs = [r for r in rows
             if r[key_real] is not None and r[key_mut] is not None]
    real = [r[key_real] for r in rows if r[key_real] is not None]
    mut = [r[key_mut] for r in rows if r[key_mut] is not None]
    out = []
    if not real or not mut:
        return ["  считать не по чему: ни одной пары «кадр и его порча»"], False
    real_lo, mut_hi = min(real), max(mut)
    caught = sum(1 for v in mut if v < lo) / len(mut)
    lost = [r["file"] for r in rows
            if r[key_real] is not None and r[key_real] < lo]
    bad_order = [r["file"] for r in pairs if r[key_mut] >= r[key_real]]
    out.append(f"  честные ({len(real)}): от {real_lo:+.3f} до {max(real):+.3f}, "
               f"медиана {sorted(real)[len(real) // 2]:+.3f}")
    out.append(f"  порча   ({len(mut)}): от {min(mut):+.3f} до {mut_hi:+.3f}, "
               f"медиана {sorted(mut)[len(mut) // 2]:+.3f}")
    out.append(f"  порог {lo}: ловит порчи {caught * 100:.0f} %, "
               f"валит честных {len(lost)}")
    ok = True
    if lost:
        ok = False
        out.append(f"  ПОРОГ ВЫШЕ ЧЕСТНОГО МИНИМУМА: ворота бракуют годные "
                   f"кадры {', '.join(lost[:4])} — перенести под {real_lo:.3f}")
    if caught < CATCH_MIN:
        ok = False
        out.append(f"  ПОРОГ НИЧЕГО НЕ ЛОВИТ: под ним {caught * 100:.0f} % порчи "
                   f"при требуемых {CATCH_MIN * 100:.0f} %. Либо порог занижен, "
                   f"либо метрика перестала отличать плоский тон от окраски")
    if len(bad_order) > ORDER_TOL * len(pairs):
        ok = False
        out.append(f"  ПОРЯДОК СЛОМАН на {len(bad_order)} кадрах из {len(rows)} "
                   f"({', '.join(bad_order[:4])}): порча обязана опускать число, "
                   f"иначе метрика мерит не то, что объявлено")
    elif bad_order:
        out.append(f"  порча не опустила число на {len(bad_order)} кадрах "
                   f"({', '.join(bad_order)}) — в пределах допуска")
    if mut_hi >= real_lo:
        out.append(f"  СПЛОШНОГО ЗАЗОРА НЕТ: худшая порча {mut_hi:+.3f} выше "
                   f"лучшего честного минимума {real_lo:+.3f}. Порог стоит под "
                   f"честным минимумом и потому пропускает часть порчи — это "
                   f"пол, а не разделитель")
    return out, ok


def main():
    setup_console()
    args = sys.argv[1:]
    files = _frames(args)
    if not files:
        raise SystemExit("нечего мерить: передайте кадры или папку")
    draw_dir = cli_opt(args, "--draw")
    g = manifest()["gates"]
    need = [k for k in ("hair_root_drop_min", "hair_tone_spread_min")
            if k not in g]
    if need:
        # Запасного значения у порога нет намеренно (см. skin.py): второй,
        # невидимый порог в коде расходится с манифестом молча. Но сказать об
        # этом надо словами, а не KeyError посреди таблицы.
        raise SystemExit(f"в assets.json → gates нет ключей {', '.join(need)} — "
                         f"метрика волос не подключена; что именно вписать, "
                         f"сказано в отчёте по этой метрике")
    lo_r, lo_t = float(g["hair_root_drop_min"]), float(g["hair_tone_spread_min"])
    print(f"пороги из манифеста: корни темнее длины от {lo_r}, многотонность "
          f"от {lo_t}; пол по IPD {g['min_face_ipd_px']} px")
    print(f"порча: «{FLAT_TONE}» гасит рисунок окраски, оставляя свет и волоски; "
          f"«{BLEACHED}» поднимает светлоту у кожи головы до уровня длины\n")
    print(f"{'кадр':32} {'IPD':>5} {'корни':>7} {'порча':>7} | "
          f"{'тон':>7} {'порча':>7} | {'лучи':>5} {'точек':>5}  вердикт")

    rows, skipped = [], 0
    for path in files:
        name = os.path.basename(path)
        from metrics.faces import detect
        img = load_bgr(path)
        face = detect(img)
        base = analyse(img, face=face, gates=g)
        if base["why"]:
            print(f"{name:32} {'—':>5} {'—':>7} {'—':>7} | {'—':>7} {'—':>7} | "
                  f"{'—':>4} {'—':>4}  {NOT_MEASURED}: {base['why']}")
            skipped += 1
            continue
        flat = analyse(flat_tone(img, face), face=face, gates=g)
        bleach = analyse(bleached_roots(img, face, gates=g), face=face, gates=g)
        rv = roots_darker(img, face=face, gates=g)
        tv = tone_spread(img, face=face, gates=g)
        # Кадр, у которого ворота корней отказались считать по своей же
        # объявленной причине, из ИХ калибровки выпадает целиком: иначе
        # законный отказ определял бы порог для всех остальных.
        one_side = rv["state"] == NOT_MEASURED
        row = {"file": name,
               "d0": None if one_side else base["root_drop"],
               "dB": None if one_side else bleach.get("root_drop"),
               "t0": base["tone_spread"], "tF": flat.get("tone_spread")}
        rows.append(row)
        mark = "".join("" if x["state"] == PASS else " ← " + x["gate"]
                       for x in (rv, tv))
        print(f"{name:32} {base['ipd_px']:5.0f} {_num(row['d0']):>7} "
              f"{_num(row['dB']):>7} | {base['tone_spread']:7.3f} "
              f"{_num(row['tF']):>7} | "
              f"{base['ray_sides'][0]:2d}/{base['ray_sides'][1]:<2d} "
              f"{base['len_pts']:4d}  {rv['state']}/{tv['state']}{mark}")
        if draw_dir:
            draw(path, base, os.path.join(draw_dir, name))

    if not rows:
        raise SystemExit("до калибровки не дошёл ни один кадр: волос над лбом "
                         "или прядей у лица не нашлось нигде")

    tight = [f"{r['file']} {_num(r['d0'])}" for r in rows
             if r["file"] in EYE_TIGHT]
    print(f"\nне замерено кадров: {skipped}")
    print("\nКОРНИ ТЕМНЕЕ ДЛИНЫ  (порча — «корни высветлены»)")
    lines_r, ok_r = calibration(rows, lo_r, "d0", "dB")
    print("\n".join(lines_r))
    print("\nМНОГОТОННОСТЬ  (порча — «ровный тон»)")
    lines_t, ok_t = calibration(rows, lo_t, "t0", "tF")
    print("\n".join(lines_t))
    if tight:
        print(f"\nтонкие места, размеченные глазами как «корни темнее» "
              f"(«—» значит ворота отказались считать): {', '.join(tight)} — "
              f"там волосы у лица в тени, а темя на свету")
    if not (ok_r and ok_t):
        print("\nКАЛИБРОВКА НЕ СОШЛАСЬ — см. строки выше")
    raise SystemExit(0 if ok_r and ok_t else 1)


def _num(v):
    return "—" if v is None else f"{v:+.3f}"


if __name__ == "__main__":
    main()
