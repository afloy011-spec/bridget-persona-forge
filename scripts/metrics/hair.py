def face_axes(face):
    """Начало координат, единица длины и оси лица по пяти точкам детектора.

    Оси строятся по линии глаз, а не по краям кадра: голова наклонена почти
    всегда, и полоса «над лбом», выровненная по кадру, съезжала бы на висок.
    Направление «вниз» сверяется по носу — у зеркального или перевёрнутого
    кадра знак иной, и без сверки корни искались бы под подбородком.
    """
    k = np.asarray(face["kps"], np.float32)
    eyes = k[:2][np.argsort(k[:2, 0])]
    centre = eyes.mean(axis=0)
    ex = eyes[1] - eyes[0]
    ipd = float(np.hypot(*ex))
    if ipd <= 0:
        return None
    ux = ex / ipd
    uy = np.array([-ux[1], ux[0]], np.float32)
    if float((k[2] - centre) @ uy) < 0:
        uy = -uy
    return centre, ipd, ux, uy


def _fields(img, ipd, ref_gray):
    """Три поля кадра: светлота, цветность и волосяная фактура.

    Цвет снимается с кадра, размытого на масштаб пряди: иначе одна точка
    попадает то на волос, то на просвет между волосами, и цветность скачет
    вдвое от шага сканирования.
    """
    soft = cv2.GaussianBlur(img, (0, 0), max(0.8, 0.012 * ipd))
    lab = cv2.cvtColor(soft, cv2.COLOR_BGR2LAB).astype(np.float32)
    L = lab[..., 0] * (100.0 / 255.0)
    a = lab[..., 1] - 128.0
    b = lab[..., 2] - 128.0

    g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY).astype(np.float32)
    hp = g - cv2.GaussianBlur(g, (0, 0), max(0.8, 0.012 * ipd))
    win = max(3, int(0.06 * ipd)) | 1
    energy = cv2.GaussianBlur(hp * hp, (win, win), 0)
    # Фактура ОТНОСИТЕЛЬНАЯ, как рельеф в skin.py: в тени абсолютный перепад
    # меньше при той же волосатости, и тёмная прядь читалась бы как гладкая.
    # НО ЗНАМЕНАТЕЛЬ ОГРАНИЧЕН СНИЗУ. В почти чёрной области деление на местную
    # яркость раздувает шум кодека до величины настоящей пряди: у P1 тёмная
    # стена справа от головы давала «фактуру» выше, чем волосы на свету, и лучи
    # длины уходили в неё целиком.
    base = cv2.GaussianBlur(g, (win, win), 0)
    strand = np.sqrt(np.maximum(energy, 0.0)) / np.maximum(base, 0.25 * ref_gray)
    # Отдельное поле светлоты для многотонности: волоски из него убраны. Без
    # этого «разброс тона» на треть состоял из шума самих волос, и плоский
    # блонд отличался от балаяжа всего в полтора раза — то есть почти никак.
    Lm = cv2.GaussianBlur(L, (0, 0), max(1.0, TONE_IPD * ipd))
    return L, a, b, strand, Lm


class Probe:
    """Съём полей кадра в точках, заданных в координатах лица."""

    def __init__(self, img, ipd, centre, ux, uy):
        self.h, self.w = img.shape[:2]
        self.ipd, self.c, self.ux, self.uy = ipd, centre, ux, uy
        # Опорная яркость — медиана по самому лицу, а не по кадру: кадр бывает
        # наполовину чёрным интерьером, и порог, посчитанный по нему, уехал бы
        # вместе с фоном, который метрика как раз и должна не пускать в маску.
        g = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        box = self.xy(_patch(-0.7, 0.7, -0.2, 1.4, 15))
        ix = np.clip(np.round(box[:, 0]).astype(int), 0, self.w - 1)
        iy = np.clip(np.round(box[:, 1]).astype(int), 0, self.h - 1)
        self.ref_gray = max(float(np.median(g[iy, ix])), 8.0)
        self.L, self.a, self.b, self.s, self.Lm = _fields(img, ipd, self.ref_gray)

    def xy(self, pts):
        p = np.asarray(pts, np.float32).reshape(-1, 2)
        return (self.c[None] + p[:, :1] * self.ipd * self.ux[None]
                + p[:, 1:] * self.ipd * self.uy[None])

    def _idx(self, pts):
        xy = self.xy(pts)
        ix = np.round(xy[:, 0]).astype(int)
        iy = np.round(xy[:, 1]).astype(int)
        ok = (ix >= 0) & (ix < self.w) & (iy >= 0) & (iy < self.h)
        return np.clip(ix, 0, self.w - 1), np.clip(iy, 0, self.h - 1), ok

    def at(self, pts):
        """(L, a, b, фактура, внутри-кадра) в точках лица."""
        ix, iy, ok = self._idx(pts)
        return (self.L[iy, ix], self.a[iy, ix], self.b[iy, ix],
                self.s[iy, ix], ok)

    def tone(self, pts):
        """Светлота без волосков — то, по чему считается многотонность."""
        ix, iy, _ = self._idx(pts)
        return self.Lm[iy, ix]


def _patch(x0, x1, y0, y1, n=13):
    gx, gy = np.meshgrid(np.linspace(x0, x1, n), np.linspace(y0, y1, n))
    return np.stack([gx.ravel(), gy.ravel()], 1).astype(np.float32)


def skin_model(probe):
    """Кожа лба и щёк: (медианы L/a/b лба, фактура лба, медиана L щёк).

    Лоб — опора света для корней, щёки — для длины. Взяты они порознь именно
    потому, что светятся по-разному; на этом и держится нормировка.
    """
    L, a, b, s, ok = probe.at(_patch(*FOREHEAD))
    if ok.sum() < 40:
        return None
    fore = (float(np.median(L[ok])), float(np.median(a[ok])),
            float(np.median(b[ok])), float(np.median(s[ok])))
    pts = np.concatenate([
        _patch(-CHEEK_DX - CHEEK_R, -CHEEK_DX + CHEEK_R,
               CHEEK_DY - CHEEK_R, CHEEK_DY + CHEEK_R, 11),
        _patch(CHEEK_DX - CHEEK_R, CHEEK_DX + CHEEK_R,
               CHEEK_DY - CHEEK_R, CHEEK_DY + CHEEK_R, 11)])
    cL, _, _, _, cok = probe.at(pts)
    if cok.sum() < 40:
        return None
    return fore, float(np.median(cL[cok]))


def _is_skin(L, a, b, s, fore):
    """Кожа ли это: телесная цветность И гладкость одновременно."""
    _, a0, b0, s0 = fore
    near = (np.abs(a - a0) <= SKIN_DA) & (np.abs(b - b0) <= SKIN_DB)
    smooth = s <= max(s0 * SKIN_STRAND, SKIN_STRAND_MIN)
    return near & smooth


def hairline(probe, fore):
    """Линия роста волос по столбцам. Возвращает (x, y) найденных столбцов.

    Сканируется снизу вверх от заведомой кожи лба. Линией считается первая
    точка, за которой подряд идут `SCAN_RUN` «не кожи»: одиночный тёмный
    пиксель — это родинка, ресница на просвет или шум, а не край причёски.
    """
    ys = np.arange(SCAN_FROM, SCAN_TO, -SCAN_STEP, dtype=np.float32)
    out = []
    for x in np.linspace(-SCAN_X, SCAN_X, SCAN_COLS):
        col = np.stack([np.full_like(ys, x), ys], 1)
        L, a, b, s, ok = probe.at(col)
        skin = _is_skin(L, a, b, s, fore) | ~ok
        run = 0
        for i in range(len(ys)):
            if not ok[i]:
                # Столбец упёрся в край кадра раньше, чем в волосы: линии
                # здесь нет, и выдумывать её нельзя.
                run = 0
                break
            if skin[i]:
                run = 0
                continue
            run += 1
            if run >= SCAN_RUN:
                out.append((float(x), float(ys[i - SCAN_RUN + 1])))
                break
    if len(out) < 3:
        return out
    # Столбцы, чья линия ушла далеко от общей, выбрасываются: так из полосы
    # выпадает прядь, перечеркнувшая лоб наискось, — на ней линия находилась
    # на середине лба, и корни собирались с кожи над этой прядью.
    med = float(np.median([y for _, y in out]))
    return [(x, y) for x, y in out if abs(y - med) <= SCAN_OUTLIER]


def root_points(probe, line, fore):
    """Точки волос у кожи головы: от линии роста вверх, столбец за столбцом.

    ПРАВИЛА ЗДЕСЬ МЯГЧЕ, ЧЕМ У ЛУЧЕЙ ДЛИНЫ, И ЭТО НЕ НЕДОСМОТР. Луч длины
    уходит вбок от лица и может встретить что угодно — плечо, телефон, стену,
    — поэтому там требуется тёплый цвет и запрещена чернота. Столбец корней
    поднимается на 0.34 IPD над найденной линией роста волос, то есть заведомо
    по темени, и требовать от него тёплого цвета нельзя: отросшие корни как
    раз тёмные и почти бесцветные. С теми же правилами, что у лучей, метрика
    выбрасывала кадры с самыми чёрными корнями — то есть ровно те, ради
    которых написана.

    Остаётся один сторож — обрыв на скачке светлоты: если верх головы за краем
    кадра или волос там нет, столбец упрётся в силуэт и оборвётся сам.
    """
    ds = np.arange(ROOT_GAP, ROOT_DEPTH, ROOT_STEP, dtype=np.float32)
    keep = []
    for x, y in line:
        pts = np.stack([np.full_like(ds, x), y - ds], 1)
        L, a, b, s, ok = probe.at(pts)
        Ls = _smooth(L)
        mask = ok & ~_is_skin(_smooth(L), _smooth(a), _smooth(b), _smooth(s), fore)
        run = _first_run(mask, ds - ROOT_GAP, Ls)
        if run:
            keep.append(pts[run])
    return np.concatenate(keep) if keep else np.zeros((0, 2), np.float32)


# ПОРЯДОК ОБХОДА ОВАЛА. Индексы 0-32 идут по контуру НЕ подряд: 1 и 17 — виски,
# от них счёт спускается по щекам (9-16 и 25-32), потом по челюсти к подбородку
# (2-8 и 18-24, 0 — низ). Установлено тем же экспериментом с номерами поверх
# кадра. Порядок нужен, чтобы взять касательную у соседей по КОНТУРУ.
OVAL_CHAIN = ([1] + list(range(9, 17)) + list(range(2, 9)) + [0]
              + list(range(24, 17, -1)) + list(range(32, 24, -1)) + [17])


def outward_rays(face):
    """Начала и внешние нормали лучей длины — по овалу лица.

    Нормаль строится по КАСАТЕЛЬНОЙ контура (сосед слева минус сосед справа по
    цепочке), а не от центра овала наружу. Радиальная нормаль у верхних точек
    щеки смотрит вверх-вбок и уводит луч мимо волос за верхний угол головы: на
    P1 все восемь лучей правой стороны уходили в тёмную стену и метрика мерила
    её.
    """
    oval = np.asarray(face["kps106"], np.float32)[:33]
    c = oval.mean(axis=0)
    pos = {idx: j for j, idx in enumerate(OVAL_CHAIN)}
    out = []
    for i in RAY_IDX:
        j = pos[i]
        prv = OVAL_CHAIN[(j - 1) % len(OVAL_CHAIN)]
        nxt = OVAL_CHAIN[(j + 1) % len(OVAL_CHAIN)]
        t = oval[nxt] - oval[prv]
        n = np.array([-t[1], t[0]], np.float32)
        d = float(np.hypot(*n))
        if d <= 0:
            continue
        n /= d
        if float(n @ (oval[i] - c)) < 0:
            n = -n
        out.append((oval[i], n))
    return out


def _smooth(v, k=RAY_SMOOTH):
    """Скользящее среднее ВДОЛЬ луча с продлением краёв."""
    pad = k // 2
    return np.convolve(np.pad(v, pad, mode="edge"), np.ones(k) / k, "valid")


def _is_hair(L, a, b, s, fore, skin_L):
    """Похоже ли на волосы: не кожа, не чёрная дыра, тёплое или тёмное."""
    C = np.hypot(a, b)
    hue = np.degrees(np.arctan2(b, a))
    warm = (hue >= HUE_MIN) & (hue <= HUE_MAX)
    neutral_dark = (C < HUE_C_MIN) & (L < NEUTRAL_L * skin_L)
    return (~_is_skin(L, a, b, s, fore) & (L > DARK_FLOOR * skin_L)
            & (((C >= HUE_C_MIN) & warm) | neutral_dark))


def _warm_run(a, b):
    """Тёплый ли кусок В ЦЕЛОМ. Решение по куску, а не по каждой точке.

    Точка сама по себе может быть тёмной и бесцветной — это тень между
    прядями, и запрещать её нельзя. Но кусок ЦЕЛИКОМ бесцветный волосами не
    бывает: так в маску попал чёрный корпус телефона у лица на кадре
    `02_mirror_selfie_phone`, и «длина» получилась темнее корней вдвое.
    """
    ma, mb = float(np.median(a)), float(np.median(b))
    hue = np.degrees(np.arctan2(mb, ma))
    return np.hypot(ma, mb) >= HUE_C_MIN and HUE_MIN <= hue <= HUE_MAX


def _first_run(mask, ts, Ls):
    """Первый кусок волос на луче: индексы или None.

    Просветы шириной до `RAY_GAP` перешагиваются — между прядями видно тень, и
    без этого луч обрывался на каждой второй точке. Кусок режется на первом
    СКАЧКЕ светлоты: балаяж меняет тон плавно вдоль пряди, а переход «волосы →
    стена» укладывается в один-два отсчёта. Края среза выбрасываются: решение
    принимается по сглаженному профилю, и край силуэта размазан на ширину
    сглаживания.
    """
    m = mask.copy()
    i = 0
    while i < len(m):
        if m[i]:
            i += 1
            continue
        j = i
        while j < len(m) and not m[j]:
            j += 1
        if 0 < i and j < len(m) and j - i <= RAY_GAP:
            m[i:j] = True
        i = max(j, i + 1)

    start = None
    for i in range(len(m)):
        if m[i]:
            start = i
            break
    if start is None or ts[start] > RAY_SKIN_MAX:
        return None
    end = start
    while end + 1 < len(m) and m[end + 1]:
        step = abs(Ls[end + 1] - Ls[end])
        if step > RAY_STEP_L * max(Ls[end], 1e-3):
            break
        end += 1
    lo, hi = start + RAY_TRIM[0], end + 1 - RAY_TRIM[1]
    return list(range(lo, hi)) if hi - lo >= RAY_MIN_RUN else None


def length_points(probe, face, fore, skin_L):
    """Точки длины: первый сплошной кусок волос на луче наружу от овала.

    Луч пропускает кожу у самого лица (щека, ухо, шея) — но не дальше
    `RAY_SKIN_MAX`: если на этом расстоянии волос не началось, значит их у
    лица нет, и всё, что дальше, — фон за ухом.
    """
    ts = np.arange(RAY_FROM, RAY_TO, RAY_STEP, dtype=np.float32)
    keep, sides = [], [0, 0]
    for idx, (p0, n) in zip(RAY_IDX, outward_rays(face)):
        xy = p0[None] + ts[:, None] * probe.ipd * n[None]
        # Луч задан уже в пикселях кадра — переводим обратно в координаты лица
        # одним общим ходом, чтобы съём шёл единственным путём.
        rel = xy - probe.c[None]
        pts = np.stack([(rel @ probe.ux) / probe.ipd,
                        (rel @ probe.uy) / probe.ipd], 1)
        L, a, b, s, ok = probe.at(pts)
        Ls, as_, bs = _smooth(L), _smooth(a), _smooth(b)
        mask = ok & _is_hair(Ls, as_, bs, _smooth(s), fore, skin_L)
        run = _first_run(mask, ts, Ls)
        if run and _warm_run(as_[run], bs[run]):
            keep.append(pts[run])
            # Индексы 9-16 — щека СЛЕВА ОТ ЗРИТЕЛЯ, 25-32 — справа: это из той
            # же карты 106 точек, что в шапке. Считаем стороны врозь, чтобы
            # ворота корней могли отказаться от односторонней выборки.
            sides[0 if idx < 17 else 1] += 1
    pts = np.concatenate(keep) if keep else np.zeros((0, 2), np.float32)
    return pts, tuple(sides)


def local_spread(pts, L, ipd_frac=LOCAL_IPD):
    """Разброс светлоты ВОКРУГ МЕСТНОГО УРОВНЯ, в долях медианной светлоты.

    Местный уровень — медиана соседей в радиусе `ipd_frac`, и считается он по
    самим точкам волос: размытие по картинке затянуло бы в уровень кожу и фон,
    которые стоят вплотную. Так из числа уходит свет по голове и остаётся
    рисунок окраски.
    """
    if len(pts) < 30:
        return None, None
    d2 = ((pts[:, None, :] - pts[None, :, :]) ** 2).sum(-1)
    near = d2 <= ipd_frac ** 2
    base = np.array([np.median(L[near[i]]) for i in range(len(L))], np.float32)
    dev = L - base
    med = float(np.median(L))
    if med <= 1e-3:
        return None, None
    lo, hi = np.percentile(dev, [15, 85])
    return float((hi - lo) / (2 * med)), float(np.median(np.abs(dev)) / med)


def analyse(src, face=None, gates=None):
    """Общий разбор волос. Возвращает словарь с обоими числами или причиной.

    Оба числа считаются одним проходом намеренно: маска волос у них общая, и
    два независимых прохода разошлись бы на первой же правке геометрии.
    """
    g = gates if gates is not None else manifest()["gates"]
    min_ipd = float(g["min_face_ipd_px"])

    img = load_bgr(src)
    if face is None:
        from metrics.faces import detect
        face = detect(img)
    if not face or face.get("state") != PASS:
        why = (face or {}).get("note", "лицо не передано и не найдено")
        return {"why": f"волосы не замерены — {why}"}
    if face.get("kps106") is None:
        return {"why": "детектор не отдал 106 точек — овала лица нет"}
    if face["ipd_px"] < min_ipd:
        return {"why": f"лицо мелкое: IPD {face['ipd_px']:.0f} px < {min_ipd:.0f}"
                       f" — полоса корней уже пикселя"}

    axes = face_axes(face)
    if axes is None:
        return {"why": "зрачки совпали — систему координат не построить"}
    centre, ipd, ux, uy = axes
    probe = Probe(img, ipd, centre, ux, uy)

    model = skin_model(probe)
    if model is None:
        return {"why": "лоб или щёки за краем кадра — сравнивать волосы не с чем"}
    fore, cheek_L = model

    line = hairline(probe, fore)
    if len(line) < SCAN_COLS // 3:
        return {"why": "линия роста волос не найдена: волосы зачёсаны назад, "
                       "убраны или верх головы вне кадра"}

    rp = root_points(probe, line, fore)
    if len(rp) < MIN_ROOT_PTS:
        return {"why": "волос над лбом не нашлось: верх головы вне кадра, "
                       "закрыт или сливается с фоном"}
    rL, ra, rb, rs, rok = probe.at(rp)
    rp, rL = rp[rok], rL[rok]
    if len(rL) < MIN_ROOT_PTS:
        return {"why": "полоса корней почти вся за краем кадра"}

    lp, sides = length_points(probe, face, fore, cheek_L)
    lL, la, lb, ls, lok = probe.at(lp) if len(lp) else (None,) * 5
    if lp is None or len(lp) < MIN_LEN_PTS:
        return {"why": "прядей у лица не нашлось: волосы убраны за плечи, "
                       "закрыты рукой или сливаются с фоном"}
    lp, lL = lp[lok], lL[lok]
    if len(lL) < MIN_LEN_PTS:
        return {"why": "пряди у лица почти все за краем кадра"}

    # СРАВНИВАЮТСЯ КРАЯ, А НЕ СЕРЕДИНЫ. Утверждение карточки — «самое тёмное
    # на голове это корни, а на длине есть светлое», и меряется именно оно:
    # тёмная четверть полосы корней против светлой четверти длины. Медиана
    # против медианы этого не ловит, потому что обе области наполовину состоят
    # из теней между прядями и бликов на них: у корней медиану тянет вверх
    # блик, у длины вниз — просвет, и разность между двумя серединами на трети
    # пула уходила в минус на кадрах, где глазами разница очевидна.
    #
    # Знаменатель ОДИН на оба слагаемых — медиана кожи лба и щёк. Раздельная
    # нормировка (корни на лоб, длина на щёку) выглядела точнее, но на деле
    # добавляла шум: на контровом кадре лоб в тени, а темя на солнце, и
    # раздельное деление это расхождение усиливало вместо того чтобы гасить.
    skin_L = float(np.median([fore[0], cheek_L]))
    root_dark = float(np.percentile(rL, ROOT_PCT))
    len_light = float(np.percentile(lL, LEN_PCT))
    spread, mad = local_spread(lp, probe.tone(lp))

    return {"root_drop": (len_light - root_dark) / max(skin_L, 1e-3),
            "tone_spread": spread,
            "tone_mad": mad,
            "root_dark": root_dark, "len_light": len_light,
            "root_L": float(np.median(rL)), "len_L": float(np.median(lL)),
            "forehead_L": fore[0], "cheek_L": cheek_L, "skin_L": skin_L,
            "root_pts": int(len(rL)), "len_pts": int(len(lL)),
            "ray_sides": sides,
            "hairline_cols": len(line), "ipd_px": ipd,
            "root_xy": rp, "len_xy": lp, "why": None}


def roots_darker(src, face=None, gates=None):
    """Ворота «корни темнее длины». Число — разность относительных яркостей."""
    g = gates if gates is not None else manifest()["gates"]
    r = analyse(src, face=face, gates=g)
    if r["why"]:
        return not_measured("hair_roots", r["why"])
    if min(r["ray_sides"]) < MIN_SIDE_RAYS:
        return not_measured(
            "hair_roots",
            f"пряди нашлись только с одной стороны головы "
            f"({r['ray_sides'][0]} и {r['ray_sides'][1]} лучей) — на такой "
            f"выборке разность мерит освещение, а не окраску", **_extra(r))
    lo = float(g["hair_root_drop_min"])
    return gate("hair_roots", r["root_drop"], lo=lo,
                note="" if r["root_drop"] >= lo else
                     "корни не темнее длины: ровный тон или высветленные корни",
                **_extra(r))


def tone_spread(src, face=None, gates=None):
    """Ворота многотонности. Число — разброс светлоты вокруг местного уровня."""
    g = gates if gates is not None else manifest()["gates"]
    r = analyse(src, face=face, gates=g)
    if r["why"]:
        return not_measured("hair_tone", r["why"])
    if r["tone_spread"] is None:
        return not_measured("hair_tone", "точек волос меньше, чем нужно "
                                         "для местного уровня освещения")
    lo = float(g["hair_tone_spread_min"])
    return gate("hair_tone", r["tone_spread"], lo=lo,
                note="" if r["tone_spread"] >= lo else
                     "волосы одного тона: плоский блонд или платина",
                **_extra(r))


def _extra(r):
    """Сырьё в отчёт — без массивов точек: вердикт уезжает в JSON."""
    return {k: v for k, v in r.items()
            if k not in ("why", "root_xy", "len_xy")}


