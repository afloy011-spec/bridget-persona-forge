#!/usr/bin/env python3
"""Резкость: дисперсия лапласиана НА КРОПЕ ЛИЦА, приведённом к масштабу лица.

  py -3 scripts/metrics/sharpness.py [<png> …]

Без аргументов проходит по `<work_root>/bridget/frames` и печатает лицо против
кадра на оригиналах и на нарочно испорченных копиях.

ПОЧЕМУ НЕ ПО КАДРУ. Один глобальный порог на дисперсию лапласиана не значит
ничего, потому что величину ведёт фактура, а не фокус. Замер на паре кадров
с одним сидом: у портрета P1 полнокадровое число 75 при резкости лица 149, у
уличного P2, где половину площади занимают трава и сетка, — 133 при резкости
лица 75. По кадру выходит, что улица вдвое резче; по лицу — ровно наоборот, и
правы именно лица. Мягкое лицо на фактурном фоне проходит глобальный порог не
глядя.

Показательнее всего вырожденный случай: уменьшив кадр вдвое, получаем ХУДШЕЕ
изображение, но глобальная дисперсия РАСТЁТ (детали собираются в пиксель и
лапласиан звенит на них сильнее) — у портретов P1 с 226 до 459, со 106 до 250,
с 84 до 195, — а дисперсия на лице при этом честно падает: со 198 до 152, со
148 до 126, со 137 до 123. Полнокадровое число считается и печатается для
контекста, но не судит.

НОРМИРОВКА. Кроп лица (бокс + 15 % на поля) масштабируется так, чтобы
межзрачковое расстояние стало ровно 128 px, и дисперсия считается уже на нём.
Смысл: лапласиан меряет перепад на СОСЕДНИХ пикселях, поэтому его величина
зависит от того, сколько пикселей пришлось на одну и ту же деталь лица. Портрет
крупным планом (IPD 230 px) и кадр в полный рост (IPD 90 px) без приведения
несравнимы — метрика мерила бы крупность плана. После приведения оба кадра
описывают одно и то же: сколько детали на единицу лица, а не на пиксель.
Нормировать по площади бокса нельзя: бокс детектора гуляет от поворота головы
и от причёски, IPD — не гуляет.

ШКАЛА ЛАПЛАСИАНА — СВОЙСТВО РЕНДЕРА, А НЕ КОНСТАНТА, и это ровно та же беда,
что у `skin_relief_floor`. Замеры на двух подряд поколениях одних и тех же
ячеек (менялись только модель и стек лор):

                       поколение A (30)   поколение B (31)
  оригиналы            103 … 563           75 … 299
  Gauss 3x3             23 …  62           25 …  90
  Gauss σ=1.5            5 …  18            8 …  26
  сильный unsharp      325 … 2662         300 … 1179

На поколении A между мылом и честными кадрами была щель 62 → 103, и порог 70
в неё попадал. На поколении B щели НЕТ ВООБЩЕ: самый мягкий честный кадр даёт
75 (уличный общий план P2), а самое «резкое» мыло — 90 (замыленный крупный
план P4), распределения перекрылись, и нижним порогом их не разделить ни при
каком значении. Девять из тридцати одного нарочно замыленного кадра проходят
ворота. Причина в том, что после приведения к IPD величина всё ещё зависит от
СОДЕРЖИМОГО кадра: замыленный крупный план несёт больше перепадов на лицо,
чем честный общий. Пока это не вылечено, проход снизу означает только «не
совсем каша», а не «резко».

Поэтому самотест этого файла проверяет не абсолютные числа, а две вещи, от
рендера не зависящие:

  порядок — метрика обязана ранжировать одно лицо «замылено < как снято <
    перешарплено»; если порядок ломается, метрика не мерит резкость вообще;
  зазор — между максимумом мыла и минимумом честных кадров должна оставаться
    щель, и `face_sharp_min` обязан лежать ВНУТРИ неё. Самотест печатает обе
    границы щели и падает, если порог из неё вышел. Это и есть процедура
    перекалибровки: `py -3 scripts/metrics/sharpness.py`.

Верхняя граница слабая честно: перешарп и самые детальные честные кадры
ПЕРЕСЕКАЮТСЯ на обоих поколениях, поэтому на провал перешарп не проверяется —
верхние ворота ловят только грубый звон, а не любую перешарпленность.

Билатеральный фильтр — «аэрограф» — резкость почти не роняет: он съедает
микрорельеф внутри ровных участков, сохраняя контуры, и остаётся на лице в
пределах 75-249 на обоих поколениях, то есть эти ворота проходит насквозь.
Ловится он не здесь, а в `skin.py`. Две метрики не дублируют друг друга
намеренно — таблица `skin.py` печатает обе колонки рядом и это показывает.

Лицо мельче `gates.min_face_ipd_px` — `NOT_MEASURED`: кроп пришлось бы
растягивать, а растяжение детали не создаёт, и метрика мерила бы интерполяцию.
"""
import sys, os, glob

import numpy as np
import cv2

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from _util import setup_console, manifest
from metrics import load_bgr
from metrics.verdict import FAIL, PASS, gate, not_measured

BOX_PAD = 0.15      # поля вокруг бокса: детектор режет по бровям, а лоб и
                    # подбородок несут столько же микродетали, сколько щёки


def lap_var(bgr):
    """Дисперсия лапласиана по яркости."""
    g = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY).astype(np.float32)
    return float(cv2.Laplacian(g, cv2.CV_32F).var())


def face_crop(bgr, face, canon_ipd=128.0, pad=BOX_PAD):
    """Кроп лица, приведённый к каноническому межзрачковому расстоянию."""
    x0, y0, x1, y1 = face["bbox"]
    w, h = x1 - x0, y1 - y0
    x0 = max(0, int(x0 - pad * w)); y0 = max(0, int(y0 - pad * h))
    x1 = min(bgr.shape[1], int(x1 + pad * w))
    y1 = min(bgr.shape[0], int(y1 + pad * h))
    crop = bgr[y0:y1, x0:x1]
    if crop.size == 0:
        return None, 0.0
    s = canon_ipd / max(face["ipd_px"], 1e-3)
    # INTER_AREA при уменьшении: обычная билинейная выборка прореживает, а не
    # усредняет, и оставляет на кропе алиасинг, который лапласиан считает
    # деталью — резкость получалась тем выше, чем крупнее было исходное лицо.
    interp = cv2.INTER_AREA if s < 1 else cv2.INTER_CUBIC
    out = cv2.resize(crop, (max(8, int(crop.shape[1] * s)),
                            max(8, int(crop.shape[0] * s))), interpolation=interp)
    return out, s


def sharpness(src, face=None, gates=None):
    """Ворота резкости. Возвращает результат в формате `verdict.gate`."""
    g = gates or manifest()["gates"]
    lo, hi = float(g["face_sharp_min"]), float(g["face_sharp_max"])
    canon = float(g.get("face_sharp_canon_ipd", 128))
    min_ipd = float(g.get("min_face_ipd_px", 100))

    img = load_bgr(src)
    full = lap_var(img)
    if face is None:
        from metrics.faces import detect
        face = detect(img)
    if not face or face.get("state") != PASS:
        why = (face or {}).get("note", "лицо не передано и не найдено")
        return not_measured("sharp", f"резкость лица не замерена — {why}",
                            full_sharpness=full)
    if face["ipd_px"] < min_ipd:
        return not_measured(
            "sharp", f"лицо мелкое: IPD {face['ipd_px']:.0f} px < {min_ipd:.0f}",
            full_sharpness=full, ipd_px=face["ipd_px"])

    crop, scale = face_crop(img, face, canon)
    if crop is None:
        return not_measured("sharp", "бокс лица вне кадра", full_sharpness=full)
    value = lap_var(crop)
    note = ("мыло на лице" if value < lo else
            "перешарп: звенящие края — подпись апскейлера" if value > hi else "")
    return gate("sharp", value, lo=lo, hi=hi, note=note,
                face_sharpness=value, full_sharpness=full,
                ipd_px=face["ipd_px"], crop_scale=scale, canon_ipd=canon)


def measure(src, face=None, gates=None):
    """Второе имя тех же ворот: `gates.py` ищет метрику по списку кандидатов.

    Синоним, а не отдельный расчёт. Обёртка, отдающая голые числа, лишила бы
    результат поля `state`, и раннер объявил бы живую метрику незамером —
    молча и на всём наборе, из-за одной перестановки в списке имён.
    """
    return sharpness(src, face=face, gates=gates)


def _frames(argv):
    if argv:
        return list(argv)
    root = os.path.join(manifest()["paths"]["work_root"], "bridget", "frames")
    return sorted(glob.glob(os.path.join(root, "*", "*.png"))
                  + glob.glob(os.path.join(root, "*.png")))


def main():
    setup_console()
    files = _frames(sys.argv[1:])
    if not files:
        raise SystemExit("нечего мерить: передайте пути к кадрам")
    from metrics.faces import detect

    g = manifest()["gates"]
    print(f"полоса резкости лица: {g['face_sharp_min']}…{g['face_sharp_max']} "
          f"при IPD {g.get('face_sharp_canon_ipd', 128)} px\n")
    print(f"{'кадр':26} {'вариант':14} {'IPD':>6} {'лицо':>9} {'кадр':>9}  вердикт")

    bad, sharp_vals, soft_vals = 0, [], []
    for path in files:
        img = load_bgr(path)
        name = os.path.basename(path)
        # Лицо ищется один раз по оригиналу и раздаётся вариантам: размытие и
        # перешарп геометрию не меняют, а детектор на них слегка «плывёт», и
        # варианты сравнивались бы по разным кропам. «Уменьшен x0.5» —
        # исключение: там координаты другие, и лицо обязано искаться заново,
        # весь смысл варианта в том, что IPD падает под пол.
        face = detect(img)
        if face["state"] != PASS:
            print(f"{name:26} {'лицо не найдено':14} {face['note']}")
            bad += 1
            continue
        half = cv2.resize(img, None, fx=0.5, fy=0.5, interpolation=cv2.INTER_AREA)
        variants = [
            ("оригинал", img, face),
            ("Gauss 3x3", cv2.GaussianBlur(img, (3, 3), 0), face),
            ("Gauss σ=1.5", cv2.GaussianBlur(img, (0, 0), 1.5), face),
            ("перешарп", cv2.addWeighted(img, 2.2,
                                         cv2.GaussianBlur(img, (0, 0), 2.0),
                                         -1.2, 0), face),
            ("уменьшен x0.5", half, None),
        ]
        res = {}
        for tag, v, f in variants:
            r = sharpness(v, face=f, gates=g)
            res[tag] = r
            face_v = "—" if r["value"] is None else f"{r['value']:9.1f}"
            ipd = "—" if r.get("ipd_px") is None else f"{r['ipd_px']:6.0f}"
            print(f"{name:26} {tag:14} {ipd:>6} {face_v:>9} "
                  f"{r['full_sharpness']:9.1f}  {r['state']}"
                  f"{'  — ' + r['note'] if r['note'] else ''}")

        # Кадр, у которого лицо мельче пола IPD, из калибровки выпадает целиком,
        # и это не расхождение: метрика на нём отказалась считать по своей же
        # объявленной причине. Без этой ветки дальше был бы KeyError на кадре в
        # полный рост — то есть самотест падал бы там, где всё правильно.
        v = {k: res[k]["value"] for k in res if res[k]["value"] is not None}
        if "оригинал" not in v:
            print(f"{'':26} вне калибровки: {res['оригинал']['note']}\n")
            continue

        # Проверяется ПОРЯДОК, а не абсолютные числа: он от рендера не зависит,
        # а числа зависят целиком (см. шапку). Метрика обязана ранжировать одно
        # и то же лицо «замылено < как снято < перешарплено» — если этот порядок
        # ломается, метрика не мерит резкость и пороги подбирать бессмысленно.
        checks = [
            ("Gauss σ=1.5 мягче Gauss 3x3", v["Gauss σ=1.5"] < v["Gauss 3x3"]),
            ("Gauss 3x3 мягче оригинала", v["Gauss 3x3"] < v["оригинал"]),
            ("перешарп резче оригинала", v["перешарп"] > v["оригинал"]),
            ("сильное мыло валится", res["Gauss σ=1.5"]["state"] == FAIL),
            # Уменьшение вдвое ухудшает кадр, но провалом это назвать нельзя: у
            # крупного портрета IPD остаётся выше пола и метрика считает, у
            # общего плана уходит под пол и метрика отказывается. FAIL здесь
            # означал бы, что ворота судят крупность плана, а не резкость.
            ("уменьшенный кадр не объявлен провалом",
             res["уменьшен x0.5"]["state"] != FAIL),
        ]
        for why, ok in checks:
            if not ok:
                bad += 1
                print(f"{'':26} НАРУШЕНО: {why}")
        sharp_vals.append(v["оригинал"])
        soft_vals.append(v["Gauss 3x3"])
        print()

    if not sharp_vals:
        raise SystemExit("до калибровки не дошёл ни один кадр: лица либо не "
                         "найдены, либо мельче gates.min_face_ipd_px")

    # Зазор между мылом и честным кадром — то, во что ставится нижний порог.
    # Он ЕДЕТ вместе с рендером, поэтому проверяется не «Gauss 3x3 обязан
    # провалиться» (это закрепило бы в тесте число из чужого файла), а само
    # существование зазора и положение порога внутри него.
    lo = float(g["face_sharp_min"])
    soft_hi, sharp_lo = max(soft_vals), min(sharp_vals)
    print(f"мыло (Gauss 3x3) до {soft_hi:.1f} · честные кадры от {sharp_lo:.1f} · "
          f"порог face_sharp_min {lo}")
    if soft_hi >= sharp_lo:
        bad += 1
        print("  ЗАЗОРА НЕТ: замыленные и честные кадры перекрываются — нижним\n"
              "  порогом их не разделить ни при каком значении")
    elif not (soft_hi < lo < sharp_lo):
        bad += 1
        print(f"  ПОРОГ ВНЕ ЗАЗОРА: face_sharp_min нужно перенести в "
              f"({soft_hi:.1f}, {sharp_lo:.1f}) — сейчас он либо пропускает\n"
              f"  мыло, либо валит честные кадры. Шкала лапласиана — свойство\n"
              f"  рендера, при смене модели или лор она уезжает целиком.")

    print("\nполнокадровое число рядом — для контекста: у «уменьшен x0.5» оно\n"
          "растёт, хотя изображение стало хуже, а лицо честно падает или\n"
          "отказывается считаться. «перешарп» на провал не проверяется: он и\n"
          "самые детальные честные кадры пересекаются, верхняя граница ловит\n"
          "только грубый звон." if not bad else f"\nРАСХОЖДЕНИЙ: {bad}")
    raise SystemExit(1 if bad else 0)


if __name__ == "__main__":
    main()
