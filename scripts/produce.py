            # встал НА ПЕРВОМ ЖЕ, когда прививка не нашла лица. Съёмка от этого
            # защищена с самого начала («один упавший кадр не роняет батч на
            # сотни»), доводка — не была.
            it["final"], it["finish_error"] = None, f"{type(e).__name__}: {e}"
