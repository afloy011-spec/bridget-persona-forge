def plan(project_dir, refs, n, axes_path=None, only=None, path=None):
    """Развернуть оси в список работ и записать его. Возвращает (план, путь).

    СИД ЗАКРЕПЛЯЕТСЯ В ПЛАНЕ, а не берётся случайным в момент съёмки. Иначе
    «доснять оборвавшийся батч» означало бы снять ДРУГИЕ кадры, и повторный
    прогон не воспроизводил бы ничего.
    """
    ax = load_axes(project_dir, axes_path)
    project = project_name(project_dir)
    cells = ax["cells"]
    if only:
        want = {s.strip() for s in only.split(",") if s.strip()}
        cells = [c for c in cells if c["id"] in want]
        if not cells:
            raise SystemExit(f"ни одна клетка не совпала с {sorted(want)}")
    # Проверка карты референсов пропускается, когда референсов нет вовсе:
    # это режим t2i с персонажной лорой, и требовать «референс на каждый план»
    # там значит требовать то, что режим отменяет. Сторож в main() уже
    # убедился, что лора объявлена — без неё пустые refs сюда не доходят.
    if refs:
        check_refs(refs, cells)
    char = read_json(os.path.join(project_dir, "character.json"))
    wrist_clause = (char.get("tattoo") or {}).get("prompt_clause", "")
    if any(c.get("tattoo_visible") for c in cells) and not wrist_clause:
        raise SystemExit(
            "клетки просят тату, а в карточке нет tattoo.prompt_clause.\n"
            "  Без него кадр не обязан показать запястье, и вклейка не "
            "случится ни разу — молча.")

    rnd = random.Random(0xB41D6E7)
    items = []
    i = 0
    while len(items) < n:
        cell = cells[i % len(cells)]
        rep = i // len(cells)
        items.append({
            "id": f"{cell['id']}_r{rep:02d}",
            "cell": cell["id"], "plan": cell["plan"],
            "size": [int(cell["w"]), int(cell["h"])],
            # Клетка, просящая тату, просит и ПЛОЩАДКУ под неё: нужную сторону
            # запястья, открытую и без металла. Без этой добавки просьба
            # сводилась к ключу в плане, а кадр про запястье ничего не знал.
            "prompt": ", ".join(x for x in (
                ax.get("base", ""), cell["prompt"],
                wrist_clause if cell.get("tattoo_visible") else "") if x),
            "seed": rnd.randint(1, 2 ** 31 - 1),
            # ПРОСЬБА, А НЕ РЕЗУЛЬТАТ. Ключ tattoo пишет доводка — и только
            # если замер кадра разрешил вклейку. Разводить их обязательно:
            # на сдаче просьба и результат разошлись на всех пяти кадрах.
            "wants_tattoo": bool(cell.get("tattoo_visible")),
            "state": "planned", "file": None,
        })
        i += 1
    out = {"project": project, "n": len(items), "cells": len(cells),
           "refs": {k: (list(v) if isinstance(v, tuple) else v)
                    for k, v in refs.items()},
           "items": items}
    path = path or os.path.join(work_dir(project, "produce"), PLAN)
    write_json(path, out)
    return out, path


def shoot(project_dir, plan_data, path, refs):
    """Снять всё, что ещё не снято. Обрыв не теряет работу: план пишется после
    каждого кадра."""
    project = plan_data["project"]
    todo = [it for it in plan_data["items"]
            if it["state"] != "shot" or not (it["file"]
                                             and os.path.exists(it["file"]))]
    if not todo:
        print("снимать нечего: весь план уже отснят")
        return plan_data
    print(f"снять: {len(todo)} из {len(plan_data['items'])}")
    cc.preflight()

    # БЕЗ РЕФЕРЕНСОВ СНИМАЕМ t2i, А НЕ ЭДИТОМ, И ЭТО НЕ МЕЛОЧЬ.
    # Эдит-шаблон обязан получить картинку-референс; подсунуть ему пустоту
    # нельзя, а звать его при обученной персонажной лоре незачем — лицо уже в
    # весах. Ветка здесь появилась вместе с лорой: до неё пустые refs просто
    # не пропускались наверх (см. сторож в main). Граф берётся у generate,
    # чтобы цепочка лор — включая персонажную — строилась ОДНИМ кодом; своя
    # сборка графа здесь означала бы второй источник правды о том, какие лоры
    # попадают в кадр.
    t2i = not refs
    if t2i:
        import generate as G
        # Карточка читается РАДИ ЕЁ id: без него generate.build_graph не может
        # свериться с ключом `for` у персонажной лоры и вешает её на любого.
        char_id = (read_json(os.path.join(project_dir, "character.json"))
                   .get("id"))
        print("съёмка t2i: личность из лоры, референс не используется")

    uploaded = {}
    for it in todo:
        for p in _pair(refs, it["plan"]):
            if p and p not in uploaded:
                uploaded[p] = cc.upload(p)

    t0 = time.time()
    for k, it in enumerate(todo, 1):
        scene_ref, subj = _pair(refs, it["plan"])
        if not subj:                       # одиночный путь = лицо
            subj = scene_ref
        try:
            if t2i:
                # char_id ПЕРЕДАЁТСЯ, иначе проверка принадлежности лоры не
                # срабатывает: _util.character_lora сверяет ключ `for` только
                # когда ей сказали, чей это кадр. Без него лора Бриджит
                # молча уезжала в кадры любого персонажа.
                graph = G.build_graph(it["prompt"], it["seed"],
                                      tuple(it["size"]), it["id"],
                                      char_id=char_id)
                files = cc.run_graph(graph, work_dir(project,
                                                     f"produce/shots/{it['id']}"))
                it["file"] = files[0] if files else None
                it["state"] = "shot" if it["file"] else "planned"
                write_json(path, plan_data)
                left = (time.time() - t0) / k * (len(todo) - k)
                print(f"  [{k}/{len(todo)}] {it['id']} — осталось "
                      f"{left / 60:.0f} мин")
                continue
            graph = cc.load_template(TEMPLATE)
            # ВТОРОЙ РЕФЕРЕНС — ТОЛЬКО СВОЙ. У ростового плана сценой идёт
            # кроп фигуры персонажа, субъектом — кроп его же лица (замерено:
            # 0.515 против 0.323 одним референсом). У близких планов второго
            # нет вовсе: лицо и есть сцена.
            if subj is scene_ref:
                drop_second_ref(graph)
            else:
                cc.apply_sets(graph, {KNOB["ref_b"]: uploaded[subj]})
            cc.apply_sets(graph, {
                KNOB["ref"]: uploaded[scene_ref],
                KNOB["prompt"]: it["prompt"], KNOB["seed"]: it["seed"],
                KNOB["width"]: it["size"][0], KNOB["height"]: it["size"][1],
                KNOB["prefix"]: it["id"],
            })
            files = cc.run_graph(graph, work_dir(project,
                                                 f"produce/raw/{it['plan']}"))
            if not files:
                raise RuntimeError("воркер не вернул кадр")
            it["file"], it["state"] = files[0], "shot"
        except Exception as e:
            # ОДИН УПАВШИЙ КАДР НЕ РОНЯЕТ БАТЧ НА СОТНИ. Он помечается и
            # пересниимается следующим запуском; батч, падающий целиком из-за
            # одного кадра, на этом масштабе не заканчивается никогда.
            it["state"], it["error"] = "failed", f"{type(e).__name__}: {e}"
            print(f"  [{k}/{len(todo)}] {it['id']}: ОШИБКА {it['error'][:60]}")
        else:
            done = k / len(todo)
            left = (time.time() - t0) / max(done, 1e-6) * (1 - done)
            print(f"  [{k}/{len(todo)}] {it['id']} — осталось "
                  f"{left / 60:.0f} мин")
        write_json(path, plan_data)
    bad = sum(1 for it in plan_data["items"] if it["state"] == "failed")
    print(f"\nснято {sum(1 for i in plan_data['items'] if i['state'] == 'shot')}"
          f", не снялось {bad}")
    return plan_data


def screen(plan_data, path, ref_face):
    """Замерить снятое: сходство и три признака рисованности."""
    from metrics import faces, artifacts
    r = faces.detect(ref_face)
    if r["state"] != "PASS":
        raise SystemExit(f"на референсе лица нет: {r['note']}")
    emb = r["embedding"]
    shot = [it for it in plan_data["items"] if it["state"] in ("shot", "screened")]
    print(f"мерить: {len(shot)}")
    for it in shot:
        if not os.path.exists(it["file"]):
            it["state"] = "planned"
            continue
        f = faces.detect(it["file"])
        if f["state"] != "PASS":
            it.update(state="screened", cos=None, why=f["note"])
            continue
        a = artifacts.measure(it["file"], face=f)
        it.update(state="screened", why="",
                  cos=faces.cosine(f["embedding"], emb), age=f["age"],
                  faces_in_frame=f.get("faces_in_frame", 1),
                  hair=a["hair"], background=a["background"], gaze=a["gaze"])
    write_json(path, plan_data)
    return plan_data


def judge(plan_data, path, per_axis=0.2, repaired=False):
    """Пометить годное и брак. НИЧЕГО НЕ УДАЛЯЕТ.

    ОТБРАКОВКА СЧИТАЕТСЯ ОДНОЙ КВОТОЙ, А НЕ ТРЕМЯ. Порог по признакам
    рисованности относительный — худшая доля прогона; абсолютное число
    означало бы, что «нейрослоп» известен заранее, а он зависит и от сцены, и
    от плана. Но три независимые квоты по 20% складывались, и на прогоне в 39
    кадров из них выжило 14: волосы отрезали семь, фон ещё семь, взгляд
    четыре, сходство пять. Это уже не ворота, а фиксированная норма выбраковки
    в две трети, и хуже всего она била по разнообразию — у широких планов
    оставалось 2 из 10 и 1 из 10, то есть сдача сама собой сползала в одни
    портреты, ровно в ту скуку, против которой сетка и строилась.
    Теперь три признака сводятся в ОДИН ранг: у каждого кадра берётся его
    место по каждой оси в долях, из них худшее, и режется худшая доля
    `per_axis` по этому общему числу. Кадр всё так же вылетает за свой
    худший признак — но один раз, а не трижды.
    """
    ok = [it for it in plan_data["items"]
          if it.get("cos") is not None and it["state"] == "screened"]
    for it in ok:
        it["verdict"], it["reason"] = "ok", ""
    for it in ok:
        if (it.get("faces_in_frame") or 1) > 1:
            it["verdict"], it["reason"] = "reject", "в кадре второе лицо"
    AX = (("hair", "волосы-ленты"), ("background", "фон-каша"),
          ("gaze", "разъезжается взгляд"))
    rank = {}
    for key, name in AX:
        vals = sorted(it[key] for it in ok if it.get(key) is not None)
        if len(vals) < 10:
            continue
        for it in ok:
            v = it.get(key)
            if v is None:
                continue
            # Доля кадров, которые по этой оси НЕ ХУЖЕ данного.
            q = sum(1 for u in vals if u <= v) / float(len(vals))
            prev = rank.get(id(it))
            if prev is None or q > prev[0]:
                rank[id(it)] = (q, key, name, v)
    if rank:
        qs = sorted(q for q, _, _, _ in rank.values())
        cut = qs[int(len(qs) * (1 - per_axis))]
        for it in ok:
            r = rank.get(id(it))
            if r and r[0] > cut and it["verdict"] == "ok":
                it["verdict"] = "reject"
                it["reason"] = (f"{r[2]} {r[3]:.3f} — худший признак кадра, "
                                f"и он в худших {100 * (1 - cut):.0f}% прогона")
    # СХОДСТВО. Планка внутри КАЖДОГО плана: косинус растёт с крупностью лица,
    # и общий порог оставил бы одни портреты.
    #
    # А ЕСЛИ ИДЕНТИЧНОСТЬ ЧИНИТСЯ ДАЛЬШЕ ПО КОНВЕЙЕРУ — планка становится
    # абсолютной и низкой. Замерено переносом на четырёх худших кадрах прогона:
    # 0.482 → 0.819 и 0.489 → 0.848 чинятся начисто, а 0.213 → 0.251 и
    # 0.340 → 0.340 не чинятся вовсе (у второго в кадре второе лицо, и перенос
    # ушёл не туда). Порог 0.40 стоит в этом промежутке. Относительная планка
    # здесь выбрасывала ровно те кадры, которые перенос вылечил бы.
    by_plan = {}
    for it in ok:
        by_plan.setdefault(it["plan"], []).append(it)
    for plan_name, group in by_plan.items():
        if repaired:
            for g in group:
                if g["cos"] < IDENTITY_UNFIXABLE and g["verdict"] == "ok":
                    g["verdict"] = "reject"
                    g["reason"] = (f"сходство {g['cos']:.3f} ниже "
                                   f"{IDENTITY_UNFIXABLE} — перенос лица такое "
                                   f"уже не чинит")
            continue
        cs = sorted(g["cos"] for g in group)
        floor = cs[int(len(cs) * 0.25)] if len(cs) >= 8 else cs[0]
        for g in group:
            if g["cos"] < floor and g["verdict"] == "ok":
                g["verdict"] = "reject"
                g["reason"] = f"сходство {g['cos']:.3f} ниже {floor:.3f} по плану"
    write_json(path, plan_data)
    good = [it for it in ok if it["verdict"] == "ok"]
    print(f"\nгодных {len(good)} из {len(ok)} замеренных")
    for key, name in (("hair", "волосы"), ("background", "фон"),
                      ("gaze", "взгляд"), ("cos", "сходство")):
        v = [it[key] for it in good if it.get(key) is not None]
        if v:
            v.sort()
            print(f"  {name:10} {v[0]:+.3f}…{v[-1]:+.3f}  медиана "
                  f"{v[len(v) // 2]:+.3f}")
    return plan_data


