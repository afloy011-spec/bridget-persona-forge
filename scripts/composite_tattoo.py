#!/usr/bin/env python3
"""Вклейка тату на запястье: ассет + подгонка под свет и зерно кадра.

  py -3 composite_tattoo.py <кадр.png> --at 0.42,0.78 --size 0.11 [--rot -18]
                            [--out <файл>] [--preview] [--flip]
  py -3 composite_tattoo.py --placements projects/bridget/tattoo_placements.json

ПОЧЕМУ РУКАМИ, А НЕ АВТОМАТОМ. Запястье надёжно не детектируется: в кадре две
руки, часть перекрыта, ракурс любой. Автопоиск ошибётся молча и посадит тату на
бокал. Ретушёр ставит вклейку глазами — здесь то же самое, только координаты
записаны в файл, поэтому результат воспроизводим и его видно в ревью.

--at — центр вклейки в долях кадра (0..1), --size — ширина в долях ширины
кадра, --rot — поворот в градусах по часовой (запястье почти никогда не
горизонтально). --preview рисует рамку вместо вклейки, чтобы подобрать цифры
за один проход, не тратя кадр.

КУДА ПИШЕТСЯ РЕЗУЛЬТАТ. Только в ДРУГОЙ файл — приёмник, равный входному кадру,
отвергается. Вклейка не идемпотентна по своей природе: чернило УМНОЖАЕТСЯ на
кожу, и второй прогон умножает его на уже вклеенное, а зерно сыплется поверх
зерна. Шаг стоит после сдачи, то есть его вход — это файл в deliverables,
который уходит клиенту; запись «на месте» тихо портила его на каждом повторе
команды. С отдельным приёмником шаг становится повторяемым: вход не меняется,
приёмник переписывается целиком, и одна и та же разметка даёт один и тот же
байт. Отказывать на втором прогоне было бы честно ровно один раз — а координаты
подбираются циклом «--preview → поправить → перевклеить», и запрет повтора
убил бы сам способ работы.

ПОЧЕМУ НЕ ПРОСТО alpha_composite. Плоская наклейка опознаётся как подделка с
первого взгляда, потому что нарушает три вещи разом:
  1. Свет. Чернило под кожей не светится: вклейка идёт УМНОЖЕНИЕМ, и её
     локальная яркость привязана к яркости кожи под ней. В тени рукав тату
     обязан темнеть вместе с кожей.
  2. Резкость. Тату не может быть резче кожи, на которой лежит. Ассет
     размывается по локальной резкости участка.
  3. Зерно. Кадр после последней мили зернистый, а вклейка — нет; ровная
     область в шумном кадре видна даже глазом. Зерно добавляется поверх.
"""
import os, sys, zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _util import (setup_console, read_json, write_json, ROOT, work_root,
                   imread as u_imread, imwrite as u_imwrite, cli_opt, same_path)


def _same_file(a, b):
    """Тот же файл — через общий сторож _util.same_path.

    Имя оставлено локальным: на него ссылается таблица мутаций и
    комментарии, объясняющие, что здесь было сломано.
    """
    return same_path(a, b)

def _local_stats(bgr, cx, cy, r):
    """Средняя яркость и резкость участка кожи под вклейкой."""
    import cv2
    h, w = bgr.shape[:2]
    x0, x1 = max(cx - r, 0), min(cx + r, w)
    y0, y1 = max(cy - r, 0), min(cy + r, h)
    patch = bgr[y0:y1, x0:x1]
    if patch.size == 0:
        return 0.5, 100.0
    gray = cv2.cvtColor(patch, cv2.COLOR_BGR2GRAY)
    return float(gray.mean()) / 255.0, float(cv2.Laplacian(gray, cv2.CV_64F).var())


def _stroke_px(alpha):
    """Толщина линии вклейки в пикселях кадра — по расстоянию до края чернила.

    Меряется на УЖЕ отмасштабированном ассете, поэтому отвечает на нужный
    вопрос: не «какой рисунок», а «какой толщины линия ляжет на кожу». Внутри
    штриха расстояние до ближайшей прозрачной точки равно половине толщины;
    берётся медиана по чернилу, а не максимум — максимум сидит в самой жирной
    точке (петля буквы, пятка силуэта) и завышал бы толщину вдвое.
    """
    import numpy as np, cv2
    m = (alpha > 0.35).astype("uint8")
    if not m.any():
        return 1.0
    d = cv2.distanceTransform(m, cv2.DIST_L2, 3)
    return float(np.median(d[m > 0])) * 2.0


def _expand(path):
    """Развернуть $PERSONA_WORK_ROOT в пути разметки.

    ЗАЧЕМ. Приёмник вклейки — не файл клиента: тату кладётся ДО последней мили,
    и её результат ещё пойдёт в обработку. Пока приёмники лежали в
    deliverables/, рядом с папкой сдачи заводилась вторая папка с почти теми
    же именами — её подбирает всё, что обходит дерево сдачи, и клиент получает
    два набора вместо одного. Место таким файлам — рабочий корень, а он
    машинный, в репозиторий его путь не впишешь.

    Разворачивается тем же work_root(), которым пользуется весь конвейер, а не
    os.path.expandvars: переменная может быть не задана вовсе, и тогда корень
    берётся из манифеста — expandvars оставил бы в пути литеральное
    «$PERSONA_WORK_ROOT» и создал каталог с таким именем.
    """
    for token in ("$PERSONA_WORK_ROOT", "${PERSONA_WORK_ROOT}", "<W_ROOT>"):
        if token in path:
            path = path.replace(token, work_root().replace("\\", "/"))
    return path


def _auto_out(frame_path, preview=False):
    """Приёмник по умолчанию: рядом с кадром, с суффиксом.

    Одна функция на два места — composite и предпроверку разметки. Пока
    умолчание считалось только внутри composite, предпроверка про него не
    знала и пропускала запись без ключа out, то есть ровно тот случай, ради
    которого предпроверка и написана.

    splitext, а не замена ".png": на .jpg замена не срабатывала, приёмник
    оставался равен ВХОДУ, и шаг писал поверх файла в deliverables.
    """
    base, ext = os.path.splitext(frame_path)
    return base + ("_preview" if preview else "_tattoo") + (ext or ".png")


# СИЛА ЧЕРНИЛА — ЗАМЕР ПО ФОТОГРАФИИ ЗАКАЗЧИКА, А НЕ ВКУС.
# Здесь стояло 0.72, и заказчик сказал: «сейчас я не вижу ни одной надписи на
# руке». Проверено числом: контраст чернила к соседней коже ВНУТРИ маски
# вклейки был 28-33%, тогда как на фотографии, с которой снят ассет, он 49%.
# Тату выходила в полтора раза бледнее живой. Свод по прозрачности на том же
# кадре: 0.72 → 31%, 0.85 → 37%, 0.95 → 42%, 1.00 → 44%. Взято 0.95: на полном
# кадре надпись читается, а не мажется, и остаётся запас до предела.
# ВАЖНО, ЧЕМ МЕРИТЬ: первая попытка считала второй процентиль яркости по
# квадрату вокруг вклейки и показала контраст 93% — «темнее фотографии». Это
# был не текст, а тёмный фон, попавший в кроп. Мерить надо по альфе ассета.
INK_OPACITY = 0.95

# ЧЕРНИЛО ПОД КОЖЕЙ ХОЛОДНЕЕ КОЖИ, И ЭТО ЗАМЕР, А НЕ ВКУС. Заказчица сказала,
# что вклейка «похожа на рисунок ручкой». Замер объяснил почему.
#
# Убедительная надпись (взята с кадров, где тату нарисовала сама диффузия)
# работает как фильтр с отношением к коже R 0.65 · G 0.67 · B 0.69: она
# затемняет кожу примерно до двух третей И ГАСИТ КРАСНЫЙ СИЛЬНЕЕ СИНЕГО. Это
# физика: пигмент лежит в дерме, и рассеяние на ней съедает длинные волны —
# отсюда холодный серо-синий тон любой старой татуировки.
#
# Наш ассет как фильтр давал R 0.29 · G 0.24 · B 0.26, то есть гасил СИНИЙ
# сильнее красного — оттенок был перевёрнут. По плотности вклейка попадала
# верно (после альфы выходило ~0.62 против замеренных 0.65), а по тону уходила
# в тёплое, и тонкая тёплая линия читается как паста, а не как чернило.
# Тон задаётся ЯВНО, а не множителями к исходному цвету: слабая поправка не
# сдвигает фильтр туда, куда нужно, а сильная ломает плотность. Поэтому от
# ассета берётся только РИСУНОК ШТРИХА (его яркость), а цвет ставится этот.
# Подобран так, чтобы отношение чернило/кожа легло около замеренных
# R 0.65 · G 0.67 · B 0.69 — см. проверку в tests/test_round6_tattoo.py.
INK_TONE = (0.50, 0.54, 0.60)   # R·G·B чернила в долях, холодное серо-синее

# ПОДКОЖНЫЙ ОРЕОЛ. Пигмент за годы расплывается в дерме на доли миллиметра:
# у настоящей надписи вокруг штриха есть еле заметное поле, у наклейки —
# резкий край. Ореол берётся размытой копией альфы, вчетверо шире основного
# размытия и почти прозрачной.
HALO_SPREAD = 4.0
HALO_STRENGTH = 0.16

# УТОЛЩЕНИЕ ШТРИХА. Плотность упёрлась в потолок: даже на ядре фильтр давал
# 0.70 при замеренных у настоящей надписи 0.65, и дальше давить цветом значит
# получить чёрную линию вместо чернила. Читается же не плотность отдельного
# пикселя, а ПЛОЩАДЬ под чернилом — а рисованный штрих в 1.9 px тоньше того,
# во что расплывается пигмент за годы. Расширение на треть штриха подводит
# фильтр к цели, не трогая ни тон, ни рисунок букв.
STROKE_GAIN = 0.34

# ПЛОТНОЕ ЯДРО ШТРИХА. Заказчица: «будто маркером написано». Замер ассета
# объяснил: медианная альфа под чернилом 0.55, и почти непрозрачных пикселей
# всего 4% — то есть полупрозрачная заливка по всей длине линии. У настоящей
# надписи ядро штриха плотное, а мягкие только края; ровная полупрозрачность
# и читается как маркер.
#
# Кривая поднимает середину, оставляя край градиентом: alpha ** ALPHA_GAMMA,
# затем масштаб. Гамма ниже единицы тянет вверх ВСЁ, поэтому край отдельно
# прижимается порогом — иначе вокруг буквы появляется ореол грязи, которого в
# ассете нет.
ALPHA_GAMMA = 0.55
ALPHA_FLOOR = 0.12

# ЧЕРНИЛО ДОЛЖНО ЖИТЬ НА КОЖЕ. Заказчица: «всё ещё маркерная надпись, посмотри
# как делает диффузия». Разница не в тоне — тон уже подтянут замером, — а в
# том, что у нас альфа РОВНАЯ по всей строке. У настоящей надписи ровной не
# бывает никогда, и три вещи ниже как раз про это.
#
# 1. ПЛОТНОСТЬ ГУЛЯЕТ ВДОЛЬ СТРОКИ. Мастер ведёт иглу неравномерно, за годы
#    часть пигмента уходит. Ровная плотность — первый признак печати.
DENSITY_VARIATION = 0.30     # доля, на которую плотность гуляет
DENSITY_SCALE = 0.22         # крупность пятен: доля ширины вклейки
#
# 2. КРАЙ РВЁТСЯ О КОЖУ. Пигмент садится в неровную поверхность, и граница
#    штриха идёт по порам, а не по кривой Безье. Берём высокочастотную деталь
#    самой кожи под вклейкой и модулируем ею альфу У КРАЯ, не трогая ядро.
EDGE_BITE = 0.55             # насколько край слушается кожи
#
# 3. НАДПИСЬ ПОДЧИНЯЕТСЯ СВЕТУ РУКИ. Освещённость вдоль предплечья меняется,
#    и чернило в тени плотнее по контрасту, на блике почти пропадает. Раньше
#    яркость бралась ОДНА на всю вклейку — отсюда и плоскость.
LIGHT_FOLLOW = 0.45          # насколько альфа идёт за яркостью кожи


def composite(frame_path, at, size, rot=0.0, out=None, asset=None,
              preview=False, flip=False, opacity=INK_OPACITY):
    import numpy as np, cv2
    from PIL import Image

    # ИМЯ ПРИЁМНИКА И ЗАПРЕТ — ДО ЧТЕНИЯ КАДРА: отказ обязан случиться раньше
    # работы, а не после неё. Имя строится через splitext, а не заменой
    # ".png": на .jpg замена не срабатывала, out оставался равен ВХОДУ, и шаг
    # молча писал поверх файла в deliverables — того самого, что уходит
    # клиенту. Раньше эта ловушка была закрыта только в ветке превью, то есть
    # ровно там, где она НЕ портила кадр.
    out = out or _auto_out(frame_path, preview)
    if _same_file(out, frame_path):
        raise SystemExit(
            f"приёмник совпадает с входным кадром: {out}\n"
            f"  Вклейка не идемпотентна: чернило умножается на кожу, и второй "
            f"прогон умножит его на уже вклеенное. Укажи другой файл.")

    asset = asset or os.path.join(ROOT, "assets", "tattoo_manolo_blahnik.png")
    frame = u_imread(frame_path)
    if frame is None:
        raise SystemExit(f"кадр не прочитан: {frame_path}")
    H, W = frame.shape[:2]

    tw = int(size * W)
    tat = Image.open(asset).convert("RGBA")
    if flip:
        tat = tat.transpose(Image.FLIP_LEFT_RIGHT)
    tat = tat.resize((tw, max(int(tw * tat.height / tat.width), 1)), Image.LANCZOS)
    if rot:
        tat = tat.rotate(rot, resample=Image.BICUBIC, expand=True)
    ta = np.asarray(tat).astype(np.float32) / 255.0
    th, tw = ta.shape[:2]

    cx, cy = int(at[0] * W), int(at[1] * H)
    x0, y0 = cx - tw // 2, cy - th // 2
    x1, y1 = x0 + tw, y0 + th
    sx0, sy0 = max(x0, 0), max(y0, 0)
    sx1, sy1 = min(x1, W), min(y1, H)
    if sx0 >= sx1 or sy0 >= sy1:
        raise SystemExit("вклейка целиком за пределами кадра — проверь --at")

    if preview:
        vis = frame.copy()
        cv2.rectangle(vis, (sx0, sy0), (sx1, sy1), (0, 230, 255), 3)
        cv2.drawMarker(vis, (cx, cy), (0, 230, 255), cv2.MARKER_CROSS, 40, 2)
        u_imwrite(out, vis)
        print(f"превью рамки: {out}  ({sx1-sx0}x{sy1-sy0} px в кадре {W}x{H})")
        return out

    lum, sharp = _local_stats(frame, cx, cy, max(tw, th) // 2)

    # 2. Резкость: тату не может быть резче кожи под ней — но и не должна
    # исчезнуть. Потолок размытия задан ТОЛЩИНОЙ ШТРИХА вклейки, а не её
    # шириной: ширина ничего не говорит о том, что именно размывается. Пока
    # потолок стоял как 0.018 от ширины, он был подобран под рисованный силуэт
    # с жирным контуром — а рукописная надпись при той же ширине вклейки имеет
    # штрих в 1.8 px, и разрешённые 1.8 px размытия стирали её в грязное
    # пятно на запястье. Тату в критериях оценки стоит отдельной строкой — она
    # обязана читаться.
    blur = min(0.6 + 2.2 * max(0.0, 1.0 - sharp / 260.0),
               max(0.4, 0.35 * _stroke_px(ta[..., 3])))
    # Штрих расширяется ДО размытия: расширенное потом мягко растворится по
    # краю, а размытое потом расширится жёстким краем.
    k = max(1, int(round(_stroke_px(ta[..., 3]) * STROKE_GAIN)))
    if k > 0:
        ta = ta.copy()
        ta[..., 3] = cv2.dilate(ta[..., 3], np.ones((k * 2 + 1,) * 2,
                                                    np.uint8))
    # Плотность ядра: кривая ДО размытия, иначе поднимется и размытый край.
    a0 = ta[..., 3].astype(np.float32)
    a0 = np.where(a0 > ALPHA_FLOOR, np.power(np.clip(a0, 0, 1), ALPHA_GAMMA),
                  a0)
    ta = ta.copy()
    ta[..., 3] = a0

    ta_rgb = cv2.GaussianBlur(ta[..., :3], (0, 0), blur)
    alpha = cv2.GaussianBlur(ta[..., 3], (0, 0), blur)

    # Тон: от ассета остаётся рисунок штриха, цвет ставится холодный.
    # Яркость нормируется по самому плотному пикселю, иначе выцветший ассет
    # даёт бледную вклейку, а густой — чёрную.
    g = ta_rgb.mean(axis=2, keepdims=True)
    gmax = float(g.max()) or 1.0
    ta_rgb = np.clip((g / gmax) * np.array(INK_TONE, dtype=np.float32),
                     0.0, 1.0)

    # Ореол: широкая почти прозрачная копия под основным штрихом. Складывается
    # с альфой ДО модуляции светом, чтобы в тени гас вместе с ней.
    halo = cv2.GaussianBlur(alpha, (0, 0), blur * HALO_SPREAD) * HALO_STRENGTH
    alpha = np.clip(alpha + halo * (1.0 - alpha), 0.0, 1.0)

    # 1. Свет: непрозрачность падает вместе с яркостью кожи. В глубокой тени
    # выцветшая пятнадцатилетняя татуировка почти не читается — и это правда.
    alpha = alpha * opacity * (0.45 + 0.55 * min(lum / 0.55, 1.0))

    a = alpha[sy0 - y0:sy1 - y0, sx0 - x0:sx1 - x0][..., None]
    ink = ta_rgb[sy0 - y0:sy1 - y0, sx0 - x0:sx1 - x0][..., ::-1]  # RGB→BGR
    skin = frame[sy0:sy1, sx0:sx1].astype(np.float32) / 255.0

    # --- чернило начинает слушаться кожи -------------------------------------
    a2 = a[..., 0]
    sl = skin.mean(axis=2)
    seed = zlib.crc32(os.path.basename(frame_path).encode("utf-8"))
    rg = np.random.default_rng(seed ^ 0x5A17)

    # 1. Плотность гуляет вдоль строки: низкочастотное поле, а не шум.
    step = max(3, int(a2.shape[1] * DENSITY_SCALE))
    small = rg.normal(0.0, 1.0, (max(2, a2.shape[0] // step + 2),
                                 max(2, a2.shape[1] // step + 2)))
    field = cv2.resize(small.astype(np.float32), (a2.shape[1], a2.shape[0]),
                       interpolation=cv2.INTER_CUBIC)
    field /= max(1e-6, np.abs(field).max())
    a2 = a2 * (1.0 + DENSITY_VARIATION * field)

    # 2. Край рвётся о кожу: деталь кожи = она сама минус её же размытие.
    detail = sl - cv2.GaussianBlur(sl, (0, 0), 2.0)
    detail = detail / max(1e-6, float(np.abs(detail).max()))
    edge = a2 * (1.0 - a2) * 4.0          # максимум на полутонах, ноль в ядре
    a2 = a2 * (1.0 + EDGE_BITE * edge * detail)

    # 3. Надпись идёт за светом руки: в тени плотнее, на блике тает.
    ls = cv2.GaussianBlur(sl, (0, 0), max(2.0, a2.shape[1] * 0.08))
    ls = ls / max(1e-6, float(ls.mean()))
    a2 = a2 * (1.0 + LIGHT_FOLLOW * (1.0 - np.clip(ls, 0.6, 1.6)))

    a = np.clip(a2, 0.0, 1.0)[..., None]

    # Умножение, а не замена: чернило лежит ПОД верхним слоем кожи и модулирует
    # её, а не закрашивает. Поэтому цвет ассета работает как фильтр.
    mixed = skin * (1.0 - a * (1.0 - ink))

    # 3. Зерно: ровная область в зернистом кадре видна даже глазом.
    # zlib.crc32, а не hash(): hash() строки солится на каждый запуск
    # интерпретатора, и вклейка получалась разной при одинаковых входах —
    # вопреки собственному обещанию докстринга «результат воспроизводим».
    rng = np.random.default_rng(zlib.crc32(
        os.path.basename(frame_path).encode("utf-8")))
    noise = rng.normal(0.0, 0.006, mixed.shape).astype(np.float32)
    mixed = np.clip(mixed + noise * (a > 0.02), 0.0, 1.0)

    frame[sy0:sy1, sx0:sx1] = (mixed * 255).astype(np.uint8)
    u_imwrite(out, frame)
    print(f"вклеено: {os.path.basename(out)}  {tw}x{th} px, штрих "
          f"{_stroke_px(ta[..., 3]):.1f}px, яркость кожи {lum:.2f}, "
          f"резкость участка {sharp:.0f} → размытие {blur:.1f}px")
    return out


def _mark_delivery(done):
    """Отметить в сдаче кадры, на которые чернило ЛЕГЛО НА САМОМ ДЕЛЕ.

    ЗАЧЕМ. Дека подписывает «Manolo tattoo, left wrist» по полю записи сдачи, и
    пока это поле было одно на всех — `tattoo_visible`, — она сообщала ЗАПРОС
    ячейки, а не факт. На прошлой сдаче это дало три подписи о татуировке на
    кадрах, где чернила не было ни одного пикселя, — по тому самому критерию
    брифа, который называется «Attention to detail (tattoo, styling, mood)», и
    проверялось это увеличением за десять секунд.

    Факт знает только композит: до него стоит замер запястья, который вправе
    отменить вклейку (ладонь вместо тыльной стороны, часы на площадке, рука
    вытянута к объективу). Поэтому `tattoo_applied` проставляет он, и только
    после настоящего прогона — при `--preview` не трогается ничего.

    Связь ищется по имени файла: кадр приезжает сюда из `<work_root>/<id>/big`,
    а имя ему дал `deliver.py`, и оно переживает и апскейл, и суффиксы вроде
    `_01`. Сопоставление по префиксу, а не по равенству, именно поэтому.
    """
    stems = {os.path.splitext(os.path.basename(f))[0] for f in done}
    root = os.path.join(ROOT, "deliverables")
    if not os.path.isdir(root):
        return
    for dirpath, _dirs, names in os.walk(root):
        if "selection.json" not in names:
            continue
        sel_path = os.path.join(dirpath, "selection.json")
        data = read_json(sel_path)
        if not isinstance(data, dict) or "frames" not in data:
            continue
        touched = []
        for r in data["frames"]:
            name = os.path.splitext(os.path.basename(
                r.get("delivered_as", "")))[0]
            if name and any(s.startswith(name) for s in stems):
                if not r.get("tattoo_applied"):
                    r["tattoo_applied"] = True
                    touched.append(name)
        if touched:
            write_json(sel_path, data)
            print("  тату отмечено в сдаче: " + ", ".join(touched))


def run_placements(path, preview=False, asset=None):
    """Пакетная вклейка по файлу разметки. Формат — список объектов
    {frame, at:[x,y], size, rot, flip, opacity, asset, out}, где out —
    ОТДЕЛЬНЫЙ файл вне папки сдачи (почему — в шапке модуля).

    preview прокидывается внутрь: раньше --placements его игнорировал и
    молча вклеивал по-настоящему поверх сданных кадров, хотя человек просил
    посмотреть рамки.
    """
    places = read_json(path)
    frames = [p["frame"] for p in places]
    # ПРОВЕРКА ВСЕЙ РАЗМЕТКИ ДО ПЕРВОЙ ЗАПИСИ. Приёмник одной записи не может
    # быть входным кадром другой: разметка обходится по порядку, и такая пара
    # вклеивает тату второй раз — тот же дефект, что out == frame, только
    # растянутый на две строки файла, и потому невидимый в каждой строке
    # по отдельности. Проверять посреди обхода поздно: часть кадров уже
    # записана, и «отказ» означает наполовину сделанную работу.
    # ПРИЁМНИК ПО УМОЛЧАНИЮ ПРОВЕРЯЕТСЯ ТОЖЕ. Запись без ключа out обходила эту
    # проверку целиком (`if dst and ...`), а умолчание строится РЯДОМ С КАДРОМ,
    # то есть в папке сдачи: там оседал посторонний 03_paddle_court_tattoo.jpg
    # — тот самый чужой файл, о котором ругается deliver.py и который подбирает
    # контакт-лист. Умолчание — такой же приёмник, как явный.
    seen = {}
    for i, p in enumerate(places, 1):
        dst = _expand(p["out"]) if p.get("out") else _auto_out(p["frame"], preview)
        if any(_same_file(dst, f) for f in frames):
            raise SystemExit(
                f"запись {i}: приёмник {dst}\n"
                f"  это входной кадр разметки — вклейка легла бы поверх "
                f"вклейки. Каждой записи нужен свой файл вне папки сдачи.")
        # ДВЕ ЗАПИСИ С ОДНИМ ПРИЁМНИКОМ. Вторая молча затирала первую, и
        # пропажа обнаруживалась только тем, что кадров на выходе меньше, чем
        # строк в разметке.
        key = os.path.normcase(os.path.abspath(dst))
        if key in seen:
            raise SystemExit(
                f"запись {i}: приёмник {dst} уже занят записью {seen[key]}\n"
                f"  Вторая вклейка затёрла бы первую. Разные записи — разные "
                f"файлы.")
        seen[key] = i
        if not p.get("out"):
            print(f"  запись {i}: ключа out нет, приёмник по умолчанию {dst}",
                  file=sys.stderr)

    done = []
    for p in places:
        dst = _expand(p["out"]) if p.get("out") else None
        if preview and dst:
            # Рамка кладётся рядом с ПРИЁМНИКОМ, а не рядом с кадром: рядом с
            # кадром — это папка сдачи, откуда посторонний JPEG уезжает в
            # контакт-лист и в предупреждение deliver.py о чужих файлах.
            b, e = os.path.splitext(dst)
            dst = b + "_preview" + (e or ".png")
        done.append(composite(p["frame"], p["at"], p["size"], p.get("rot", 0.0),
                              dst, p.get("asset") or asset,
                              preview=preview, flip=p.get("flip", False),
                              opacity=p.get("opacity", 0.72)))
    # КЛАСС СЦЕНЫ ПЕРЕЕЗЖАЕТ ВМЕСТЕ С КАДРОМ. Он записан в selection.json
    # рядом с входным кадром, а последняя миля берёт по нему силу зерна. Пока
    # композит уносил кадр из папки сдачи и ничего с собой не брал, человеку
    # приходилось помнить и подставлять --scene руками — факт, известный
    # конвейеру с шага 3, и ошибка в нём молчаливая: ночной кадр выходит
    # гладким, как дневной. Сайдкар пишется в том же формате, что и сдача,
    # чтобы читатель у него был один, а не два.
    scenes = {}
    for p_ in places:
        sel = os.path.join(os.path.dirname(os.path.abspath(p_["frame"])),
                           "selection.json")
        if not os.path.isfile(sel):
            continue
        for r in read_json(sel).get("frames", []):
            if os.path.basename(r.get("delivered_as", "")) ==                     os.path.basename(p_["frame"]):
                scenes[os.path.basename(p_["frame"])] = r.get("scene_class")
    if scenes and not preview:
        for d in sorted({os.path.dirname(os.path.abspath(f)) for f in done}):
            rows = [{"delivered_as": os.path.basename(f),
                     "scene_class": scenes.get(os.path.basename(f))}
                    for f in done
                    if os.path.dirname(os.path.abspath(f)) == d
                    and scenes.get(os.path.basename(f))]
            if rows:
                write_json(os.path.join(d, "selection.json"),
                           {"source": "composite_tattoo", "frames": rows})

    if not preview:
        _mark_delivery(done)

    dirs = sorted({os.path.dirname(os.path.abspath(f)) for f in done})
    # Куда легло — печатается, а не описывается в документации: следующий шаг
    # (последняя миля) читает эти файлы, и путь к ним не должен жить только в
    # памяти того, кто правил разметку.
    print(f"\n{len(done)} кадров с тату; сданные кадры не тронуты.\n"
          + "\n".join(f"  → {d}" for d in dirs))
    return done


def main():
    setup_console()
    args = sys.argv[1:]
    if not args:
        print(__doc__); raise SystemExit(1)

    def opt(k, d=None):
        return cli_opt(args, k, d)

    if "--placements" in args:
        run_placements(opt("--placements"), "--preview" in args, opt("--asset"))
        return

    at = [float(v) for v in opt("--at", "0.5,0.5").split(",")]
    composite(args[0], at, float(opt("--size", 0.1)), float(opt("--rot", 0)),
              opt("--out"), opt("--asset"), "--preview" in args, "--flip" in args,
              float(opt("--opacity", 0.72)))


if __name__ == "__main__":
    main()
