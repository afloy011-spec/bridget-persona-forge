#!/usr/bin/env python3
"""Ассет тату ИЗ ФОТОГРАФИИ настоящей тату: чернило с альфой, выпрямленное.

  py -3 tattoo_from_photo.py <фото.png> --out assets/<имя>.png [--preview <файл>]
  py -3 tattoo_from_photo.py <фото.png> --out … --no-deskew   оставить наклон

ЗАЧЕМ ОТДЕЛЬНО ОТ make_tattoo_asset.py. Тот РИСУЕТ флэш-эскиз по описанию и
нужен, когда тату придумывают. Здесь обратная задача: тату уже существует на
референсе персонажа, и придумывать её заново значит получить другую. У Бриджит
это не графика, а НАДПИСЬ рукописным шрифтом — нарисовать такую «по мотивам»
нельзя: имя либо совпадает буква в букву, либо это чужая тату.

ЧЕРНИЛО ОТДЕЛЯЕТСЯ ОТ КОЖИ ПО ТЕМНОТЕ ОТНОСИТЕЛЬНО ЛОКАЛЬНОГО ФОНА, а не по
абсолютному порогу. Кожа на фотографии освещена неровно: у запястья светлее,
к локтю уходит в тень, плюс блики. Абсолютный порог на такой картинке либо
съедает светлую часть надписи, либо прихватывает тень. Фон считается
морфологическим закрытием ядром заведомо крупнее толщины линии — то есть
«как выглядела бы кожа без надписи», — и альфа берётся из разницы.

ВЫПРЯМЛЕНИЕ. Надпись на фотографии идёт по оси предплечья, то есть под
произвольным углом. Композит (`composite_tattoo.py`) сам поворачивает ассет
ключом `rot`, и ассет обязан приехать к нему горизонтальным — иначе поворот
складывается с наклоном исходной фотографии, и подбор угла превращается в
гадание. Угол считается главной осью облака точек чернила (PCA), а не
подбирается руками.

ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Ни повышения контраста, ни «дорисовки» разрывов, ни
сглаживания дрожи линии. Выцветшая тату с расплывшейся линией и должна
остаться выцветшей: это её возраст, и он работает на достоверность персонажа
так же, как морщинки у глаз. Композит потом сам приглушит её по свету кадра.
"""
import os
import sys

import numpy as np
import cv2

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _util import setup_console, cli_opt, imread, imwrite  # noqa: E402

# Ядро фона: заведомо крупнее толщины линии, иначе закрытие «залижет» саму
# надпись и разница выйдет нулевой. Доля от меньшей стороны кропа.
BG_KERNEL = 0.055
# Порог принадлежности к чернилу — доля от размаха темноты, а не яркость.
INK_LEVEL = 0.30
# Пятна мельче этого (в долях площади кропа) — пыль, поры, волоски.
MIN_BLOB = 2.0e-5


def ink_alpha(bgr):
    """Альфа чернила: 0 — кожа, 1 — самая тёмная точка надписи."""
    gray = cv2.cvtColor(bgr, cv2.COLOR_BGR2GRAY).astype(np.float32)
    k = max(3, int(min(gray.shape) * BG_KERNEL) | 1)
    ker = cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (k, k))
    # Закрытие светлым: получаем «кожу без надписи».
    skin = cv2.morphologyEx(gray, cv2.MORPH_CLOSE, ker)
    diff = np.clip(skin - gray, 0, None)
    if diff.max() <= 0:
        raise SystemExit("на кропе нет ничего темнее кожи — надпись не найдена")
    a = diff / diff.max()
    # Слабый хвост — это фактура кожи и зерно, а не чернило.
    a[a < INK_LEVEL * 0.5] = 0.0
    return a


def largest_ink(a):
    """Маска надписи: связные пятна выше уровня, без пыли и одиночных пор."""
    m = (a >= INK_LEVEL).astype(np.uint8)
    n, lab, stats, _ = cv2.connectedComponentsWithStats(m, 8)
    keep = np.zeros_like(m)
    floor = MIN_BLOB * a.size
    for i in range(1, n):
        if stats[i, cv2.CC_STAT_AREA] >= floor:
            keep[lab == i] = 1
    if not keep.any():
        raise SystemExit("после отсева пыли от надписи ничего не осталось — "
                         "проверьте кроп и INK_LEVEL")
    return keep


def _main_run(profile, gap):
    """Границы самого «чернильного» сгустка профиля, разрывы шире `gap` режут.

    Отсев по площади убирает пыль, но не убирает КРУПНУЮ соринку в стороне от
    надписи: родинку, край рукава, точку грязи на объективе. Такая соринка
    проходит по размеру, а рамку ассета растягивает во весь кадр — композит
    получает холст, где надпись сидит в углу, а всё остальное прозрачно, и
    любое позиционирование по центру ассета уезжает.

    Считается это на ВЫПРЯМЛЕННОЙ картинке и по каждой оси отдельно: там
    строка идёт вдоль ряда, и всё, что отделено от неё пустотой шире
    межбуквенной, к надписи не относится.
    """
    on = profile > 0
    if not on.any():
        return 0, len(profile)
    idx = np.flatnonzero(on)
    runs, start = [], idx[0]
    for prev, cur in zip(idx, idx[1:]):
        if cur - prev > gap:
            runs.append((start, prev + 1))
            start = cur
    runs.append((start, idx[-1] + 1))
    # Побеждает не самый длинный отрезок, а самый насыщенный чернилом: длинный
    # редкий хвост из брызг не должен перевешивать плотную строку.
    return max(runs, key=lambda r: float(profile[r[0]:r[1]].sum()))


def _edge_scatter(a, thr=0.25):
    """Разброс верхнего и нижнего края строки, в долях высоты кропа.

    Меряется РАЗМАХ МЕЖДУ ДЕЦИЛЯМИ, и это не первый выбор, а третий. Хотелось
    устойчивости к одиночному выбросу — у надписи ровно один хвост вниз («k») и
    редкие высокие выносные, — и сначала стояло медианное отклонение (MAD). На
    настоящих фотографиях оно давало лучший запас, а на строке с РЕДКИМИ
    выносными выродилось в ноль с обеих сторон: если выносные занимают 15%
    колонок, медиана верхнего края их просто не замечает, MAD выходит нулевым,
    и правило отвечало «стоит правильно» на любой ориентации — молча и всегда.
    Дециль отрезает и одиночный хвост, и вырождение: замер на обеих
    фотографиях даёт запас 1.8 и 2.6 раза, на редких выносных — разделение
    начисто.
    """
    m = a > thr
    cols = np.flatnonzero(m.any(0))
    if len(cols) < 8:
        return 0.0, 0.0
    n = a.shape[0]
    top = np.argmax(m[:, cols], 0).astype(np.float64) / (n - 1)
    bot = (n - 1 - np.argmax(m[::-1, cols], 0)).astype(np.float64) / (n - 1)
    spread = lambda v: float(np.quantile(v, 0.9)   # noqa: E731
                             - np.quantile(v, 0.1))
    return spread(top), spread(bot)


def is_upright(a):
    """Строка стоит правильно, если её НИЖНИЙ край ровнее верхнего.

    ЭТО ЕДИНСТВЕННОЕ, ЧТО РАЗЛИЧАЕТ 0° И 180°. PCA даёт ось, а ось поворот
    на 180° не замечает; наклон почерка тоже не замечает — угол линии при
    развороте сохраняется. Различает только вертикальная асимметрия самой
    строки, и у латиницы она берётся из типографики: низ букв стоит НА
    БАЗОВОЙ ЛИНИИ и потому ровный, верх рваный, потому что заглавные и
    выносные («M», «B», «l», «h», «k») торчат над строчными.

    ЗДЕСЬ СТОЯЛО ДРУГОЕ ПРАВИЛО, И ОНО ОКАЗАЛОСЬ МОНЕТКОЙ. Считался центр
    тяжести чернила: раз выносные тянутся вверх, масса должна лежать ниже
    середины. На первой фотографии это дало 0.534 против 0.466 — сошлось.
    На второй, где выносные длиннее, — 0.451 при верной ориентации, то есть
    ПРАВИЛО ПЕРЕВЕРНУЛО НАДПИСЬ, и увидела я это только глазами по превью.
    Замер обеих фотографий: центр тяжести отходит от середины на 0.03–0.07,
    пик профиля на 0.05–0.07, а РОВНОСТЬ КРАЯ различает ориентации в 1.8 и
    2.6 раза. Разница между «работает на этой картинке» и «работает».
    """
    top, bot = _edge_scatter(a)
    return bot <= top, top, bot


def deskew_angle(mask):
    """Угол главной оси облака чернила, градусы против часовой."""
    ys, xs = np.nonzero(mask)
    pts = np.stack([xs - xs.mean(), ys - ys.mean()], 1).astype(np.float32)
    # Собственный вектор наибольшей дисперсии — направление строки.
    cov = np.cov(pts.T)
    w, v = np.linalg.eigh(cov)
    vx, vy = v[:, int(np.argmax(w))]
    return float(np.degrees(np.arctan2(vy, vx)))


def build(src, out, deskew=True, preview=None):
    img = imread(src)
    if img is None:
        raise SystemExit(f"фото не прочитано: {src}")
    a = ink_alpha(img)
    mask = largest_ink(a)
    a = a * mask                      # вне надписи альфа строго ноль

    ang = deskew_angle(mask) if deskew else 0.0
    if deskew:
        h, w = a.shape
        # Поворот на «минус угол» кладёт строку горизонтально. Холст берётся
        # с запасом: иначе углы надписи срезаются собственным поворотом.
        d = int(np.hypot(w, h))
        M = cv2.getRotationMatrix2D((w / 2, h / 2), ang, 1.0)
        M[0, 2] += (d - w) / 2
        M[1, 2] += (d - h) / 2
        a = cv2.warpAffine(a, M, (d, d), flags=cv2.INTER_LINEAR,
                           borderValue=0.0)
        img = cv2.warpAffine(img, M, (d, d), flags=cv2.INTER_LINEAR,
                             borderValue=(0, 0, 0))

    ys, xs = np.nonzero(a > 0.02)
    if not len(ys):
        raise SystemExit("после поворота альфа пуста")

    if deskew:
        # Соринки в стороне от строки режутся ЗДЕСЬ, на выпрямленной картинке:
        # до поворота «в стороне» ещё не определено, а после — строка идёт
        # ровно вдоль ряда, и посторонний след отделён от неё пустотой.
        span_y, span_x = int(np.ptp(ys)) + 1, int(np.ptp(xs)) + 1
        r0, r1 = _main_run(a.sum(1), max(8, int(0.05 * span_y)))
        c0, c1 = _main_run(a.sum(0), max(24, int(0.12 * span_x)))
        cut = (r1 - r0) * (c1 - c0) < span_y * span_x
        a[:r0], a[r1:], a[:, :c0], a[:, c1:] = 0, 0, 0, 0
        if cut:
            print(f"  вне строки обрезано: {span_y - (r1 - r0)} px по вертикали,"
                  f" {span_x - (c1 - c0)} px по горизонтали")
            # ВТОРОЙ ПРОХОД ВЫПРЯМЛЕНИЯ, И ОН НЕ ПРИДИРКА. Угол первого прохода
            # считался по облаку, в котором соринка ещё была, а она отстоит от
            # строки на пол-кадра и тянет главную ось на себя: на синтетике
            # точка в углу уводила угол на 6.4°, и рамка выпрямленной строки
            # вырастала в полтора раза от одного этого наклона. Обрезка сама по
            # себе этого не чинит — она убирает соринку из КАРТИНКИ, но угол уже
            # посчитан. Поэтому после обрезки ось считается заново, теперь по
            # одной строке, и остаточный наклон доворачивается.
            # ОСТАТОК ПРИВОДИТСЯ К (-90, 90]. `deskew_angle` возвращает угол
            # ОСИ, а ось не различает направлений: у почти горизонтальной
            # строки он с равным правом выходит и как -1°, и как 179°, и на
            # реальном фото вышел как -178.3°. На САМ АССЕТ это не влияет —
            # поворот на θ+180 оставляет строку такой же горизонтальной, а
            # определение направления ниже переворачивает её обратно. Влияет
            # на НАПЕЧАТАННЫЙ угол, по которому человек проверяет, что вынули
            # именно надпись: «наклон исходника -178°» у горизонтальной в
            # итоге строки читается как поломка там, где её нет.
            res = (deskew_angle(a > 0.02) + 90.0) % 180.0 - 90.0
            if abs(res) > 0.5:
                h2, w2 = a.shape
                M2 = cv2.getRotationMatrix2D((w2 / 2, h2 / 2), res, 1.0)
                a = cv2.warpAffine(a, M2, (w2, h2), flags=cv2.INTER_LINEAR,
                                   borderValue=0.0)
                img = cv2.warpAffine(img, M2, (w2, h2), flags=cv2.INTER_LINEAR,
                                     borderValue=(0, 0, 0))
                ang += res
                print(f"  соринка уводила ось на {res:+.1f}° — довернули")
        ys, xs = np.nonzero(a > 0.02)

    pad = 4
    y0, y1 = max(ys.min() - pad, 0), min(ys.max() + pad + 1, a.shape[0])
    x0, x1 = max(xs.min() - pad, 0), min(xs.max() + pad + 1, a.shape[1])
    a = a[y0:y1, x0:x1]
    src_bgr = img[y0:y1, x0:x1]

    # НАПРАВЛЕНИЕ СТРОКИ. PCA даёт ОСЬ, а не направление: выпрямленная надпись
    # с равной вероятностью выходит вверх ногами, и первый прогон именно так и
    # вышел. Правило — в is_upright: ровный низ против рваного верха.
    #
    # Считать это можно только на ОБРЕЗАННОЙ строке. На холсте с запасом под
    # поворот надпись сидит по центру, края уходят в пустые ряды, и проверка
    # меряет рамку холста вместо самой строки.
    if deskew:
        up, top, bot = is_upright(a)
        print(f"  край строки: верх {top:.3f}, низ {bot:.3f} "
              f"(ровнее {'низ' if up else 'верх'})")
        if not up:
            a = cv2.rotate(a, cv2.ROTATE_180)
            src_bgr = cv2.rotate(src_bgr, cv2.ROTATE_180)
            ang += 180.0
            print("  строка пришла вверх ногами — довернули на 180°")

    # ЦВЕТ ЧЕРНИЛА БЕРЁТСЯ С ФОТОГРАФИИ, а не назначается чёрным. Старая тату
    # уходит в сине-серый, и подмена её чистым чёрным добавляет кадру
    # свежести, которой у персонажа нет.
    core = a > 0.6
    ink = (src_bgr[core].reshape(-1, 3).mean(0) if core.any()
           else np.array([30, 28, 32], np.float32))
    rgba = np.zeros((a.shape[0], a.shape[1], 4), np.uint8)
    rgba[..., 0] = int(round(ink[2]))     # PNG ждёт RGBA
    rgba[..., 1] = int(round(ink[1]))
    rgba[..., 2] = int(round(ink[0]))
    rgba[..., 3] = np.clip(a * 255, 0, 255).astype(np.uint8)

    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    from PIL import Image
    Image.fromarray(rgba, "RGBA").save(out)
    cov = float((a > 0.02).mean())
    print(f"надпись: {a.shape[1]}x{a.shape[0]} px, наклон исходника "
          f"{ang:+.1f}°, чернило RGB {int(ink[2])},{int(ink[1])},{int(ink[0])}, "
          f"покрытие {cov:.1%}")
    print(f"ассет: {out}")

    if preview:
        # Превью на светло-сером: на прозрачном PNG в проводнике не видно
        # ничего, и «получилось» проверяется только глазами.
        bg = np.full((a.shape[0], a.shape[1], 3), 214, np.uint8)
        al = (a[..., None]).astype(np.float32)
        vis = (bg * (1 - al) + src_bgr.astype(np.float32) * al).astype(np.uint8)
        imwrite(preview, vis)
        print(f"превью: {preview}")
    return out


def main():
    setup_console()
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        raise SystemExit(1)
    build(args[0], cli_opt(args, "--out", "assets/tattoo.png"),
          "--no-deskew" not in args, cli_opt(args, "--preview"))


if __name__ == "__main__":
    main()
