#!/usr/bin/env python3
"""Перенос лица референса на наш же кадр. Последний рубеж идентичности.

  py -3 face_transfer.py <кадр|папка> --ref <референс.png> --out-dir <папка>
                         [--restore GFPGANv1.4.pth] [--visibility 0.4]

ЗАЧЕМ ЭТО ПОЯВИЛОСЬ. Заказчик посмотрел на прогон и сказал «это вообще не наша
женщина». Замер подтвердил: чужие женщины по тому же описанию дают косинус
0.17-0.32 к референсу, наши кадры 0.43-0.73 — разделение начисто, то есть
ворота ловят «совсем чужую» и на этом их умение кончается. «Похожая женщина
того же типа» проходит их насквозь, и заказчик увидел ровно её.

ЧТО БЫЛО ПРОВЕРЕНО ДО ЭТОГО ШАГА И НЕ СРАБОТАЛО. Одиннадцать ручек эдита, по
одной за раз, на закреплённом сиде и одной клетке:
  сила референса      плато: 8.0 → 0.750, 12.0 → 0.756, 20.0 → 0.721
  кодирование ref     768 → 0.662, 1024 → 0.685, 1280 → 0.685
  сила эдит-лоры      1.0 → 0.662, 1.3 → 0.627, 1.6 → 0.488 (ВВЕРХ ТОЛЬКО ХУЖЕ)
  cfg 2.5             0.590
  шагов 16            0.670
  референс 1536       0.670
  лицо вторым реф.    0.670
  короткий текст      0.630
Цепочка на этом материале насыщена: её потолок около 0.75, и это «того же
типа». Ни одна ручка не переводит его в «тот же человек».

ПОЧЕМУ ЭТО НЕ ТОТ СВАП, КОТОРЫЙ ЗАКАЗЧИК УЖЕ ЗАБРАКОВАЛ. Тогда базой была
СЛУЧАЙНАЯ ЖЕНЩИНА из t2i, которую после переделывали в нашу, — и заказчик был
прав, что это лишний человек в конвейере. Здесь база — наш собственный кадр,
снятый эдитом С РЕФЕРЕНСА: поза, свет, возраст, волосы, одежда и сцена уже
его. Переносится только геометрия лица, и переносится с единственной
фотографии персонажа.

ЗАКАЗЧИК СКАЗАЛ «КАЧЕСТВО УПЛЫЛО», И ОН БЫЛ ПРАВ ДВАЖДЫ. Замер детализации
(дисперсия лапласиана) по стадиям на шести кадрах показал две разные беды:
  ВЕСЬ КАДР терял 15-35% — 304→259, 176→113, 291→206, — хотя переносу положено
  трогать только лицо. Свап прогоняет через себя всю картинку и возвращает её
  мягче: волосы, ткань, фон. Это чинится начисто — см. keep_outside(): всё,
  кроме лица, берётся из исходника байт в байт, и вне маски отличие ровно ноль
  на 82% площади кадра.
  ЛИЦО теряло 85%: 111.8→16.7, 162.3→26.0, 391.6→81.6. Это лечится
  восстановителем на полной видимости (см. VISIBILITY) и прививкой кожи, но
  до конца не лечится: остаётся около 157 против 162 у исходника.

И ЕЩЁ ОДНА ЦЕНА, КОТОРУЮ Я СНАЧАЛА НЕ ЗАМЕТИЛА, ПОТОМУ ЧТО СМОТРЕЛА НЕ ТУДА.
Я вела эту ветку по косинусу — и сама же написала выше, что после свапа он
круговой. Три метрики, которые в проекте давно есть, после переноса не
прогонялись ни разу, а они показывают вот что (медианы по 14 кадрам, до → после
на видимости 0.4):
  резкость лица   138.8 → 58.9   при пороге манифеста 118 — то есть ниже
                                 собственных ворот проекта;
  тон радужки     110.2 → 79.2   зелёно-ореховый уходит в карий: радужка в
                                 128x128 это несколько точек, и восстановитель
                                 дорисовывает обобщённый тёмный глаз;
  возраст (макс)     60 → 52     восстановитель «чинит» в сторону молодости.
Полная видимость и маска лица первые две беды сильно смягчают; радужку надо
проверять отдельно и на каждом прогоне.

ЦЕНА ПО КОЖЕ ЗАМЕРЕНА ТОЖЕ. inswapper работает в 128x128 и возвращает лицо
мягче кадра вокруг — метрика кожи это видит: на трёх кадрах 0.567, 0.740 и
0.745 сразу после переноса (у исходников 0.0). Дальше два разных лекарства:
  ВОССТАНОВИТЕЛЬ (GFPGAN/codeformer) возвращает резкость и приносит свой
  «отреставрированный» вид — глянцевые ресницы и подчёркнутый глаз, ровно та
  гладкость, против которой в этом проекте написаны и прививка кожи, и
  детекторы рисованности. На 0.8 он заметен глазами, на 0.4 нет.
  ПРИВИВКА КОЖИ (skin_graft.py) возвращает фактуру настоящей кожи и уводит
  метрику обратно: 0.567 → 0.256, 0.740 → 0.271. Она обязана идти ПОСЛЕ
  переноса — перенос стирает всё, что было наложено до него.
Замер связки: сходство 0.884-0.898 при восстановителе 0.4, кожа 0.099-0.175.

КОСИНУС ПОСЛЕ ПЕРЕНОСА — КРУГОВОЙ, И ЭТО НАДО ЗНАТЬ. inswapper прямо
оптимизирует эмбеддинг ArcFace, то есть ровно то число, которым мы меряем
идентичность. 0.89 после переноса — это замер собственной пересадки, а не
независимое доказательство. Независимый судья здесь глаз, и по глазам лицо
действительно становится референсным: сужается овал, появляется нависшее веко,
меняется нос. Число оставлено как СТОРОЖ (перенос не сработал → оно не
вырастет), а не как доказательство.

КУДА ЭТО ВЕДЁТ ДАЛЬШЕ. Правильное место переноса — не каждый кадр, а СБОРКА
ДАТАСЕТА: прогон → перенос → настоящие портреты персонажа в разных позах и
свете → обучение персонажной лоры на них → генерация с лорой, где идентичность
уже родная, без переноса и без потери фактуры. Тогда и косинус снова становится
честным судьёй: лора обучалась не под ArcFace. Пока лоры нет, перенос стоит
шагом доводки и включается ключом.
"""
import os
import sys
import glob

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _util import (setup_console, cli_opt, work_dir, imread,  # noqa: E402
                   imwrite)
import comfy_client as cc  # noqa: E402

TEMPLATE = "face_transfer_api"
# Восстановитель по умолчанию и его видимость. 0.4, а не 1.0: замер на трёх
# кадрах показал, что выше 0.4 сходство не растёт (0.884 против 0.861 на 0.8),
# а «отреставрированный» вид становится виден глазами.
RESTORE = "GFPGANv1.4.pth"
# ВИДИМОСТЬ ВОССТАНОВИТЕЛЯ 0.4, И ЭТО ЧИСЛО Я МЕНЯЛА ДВАЖДЫ. ВОТ ОБА ЗАМЕРА.
# Сначала стояло 0.4 по одному взгляду на два кадра. Потом я подняла до 1.0 по
# детализации лица (дисперсия лапласиана по рамке лица; кадр D02, сырой 162.3):
#   без восстановителя   44.7 → 73.3 после прививки, сходство 0.874
#   GFPGAN 0.4           59.0 → 86.7                 сходство 0.870
#   GFPGAN 1.0          127.4 → 157.4                сходство 0.850
#   codeformer 0.7       80.2 → 112.3                сходство 0.804
# И ЭТО БЫЛА ОШИБКА, КОТОРУЮ ПОЙМАЛ ЗАКАЗЧИК: «опять генеришь не нашу».
# Резкость выросла, а сходство упало не на бумаге, а в лице. На кропе в 300 px
# межзрачкового видно, чем платится: GFPGAN на полной видимости РИСУЕТ густую
# тёмную бровь и жирную линию ресниц, а у референса бровь мягкая и редкая.
# Восстановитель тем и работает, что подтягивает лицо к своему представлению о
# «хорошем лице», и чем сильнее он включён, тем дальше уводит от конкретного
# человека. Число этого не показывает: 0.850 против 0.870 читается как мелочь,
# а глазами это разные женщины.
# Отсюда правило, а не только значение: ВОССТАНОВИТЕЛЬ — НЕ РУЧКА РЕЗКОСТИ.
# Резкость возвращает прививка кожи (skin_graft.py), она берёт фактуру с
# настоящей фотографии и своего лица не имеет.
VISIBILITY = 0.4


def face_mask(src, feather=0.18):
    """Мягкая маска лица по 106 точкам: где переносу позволено менять кадр."""
    import cv2
    from metrics import faces
    f = faces.detect(src)
    if not f or f.get("kps106") is None:
        return None
    k = np.asarray(f["kps106"], np.float32)
    img_w, img_h = f["frame_size"]
    m = np.zeros((img_h, img_w), np.uint8)
    hull = cv2.convexHull(k.astype(np.int32))
    cv2.fillConvexPoly(m, hull, 255)
    # Овал по точкам обрезан по линии бровей — лоб, который свап тоже трогает,
    # в него не попадает. Расширяем на долю межзрачкового и растушёвываем: шов
    # виден ровно там, где резко.
    ipd = float(np.linalg.norm(np.asarray(f["kps"][1]) - np.asarray(f["kps"][0])))
    r = max(3, int(ipd * 0.55))
    m = cv2.dilate(m, cv2.getStructuringElement(cv2.MORPH_ELLIPSE, (r, r)))
    b = max(3, int(ipd * feather) | 1)
    return cv2.GaussianBlur(m, (b, b), 0).astype(np.float32) / 255.0


def keep_outside(src, swapped, out):
    """Вернуть в кадр всё, кроме лица, попиксельно из исходника.

    ЗАЧЕМ. Замер детализации (дисперсия лапласиана) по стадиям на шести
    кадрах: ВЕСЬ КАДР терял 15-35% — 304→259, 176→113, 291→206, — хотя
    переносу положено трогать только лицо. Свап прогоняет через себя всю
    картинку и возвращает её мягче. Заказчик увидел это раньше метрик и
    назвал точно: «дело в качестве, качество уплыло».

    Лицо остаётся с переноса — за ним и ходили. Всё остальное берётся из
    исходника байт в байт, поэтому фон, волосы, руки и одежда теряют ровно
    ноль. Шов прячется растушёвкой маски, а не подгонкой цвета: цвет у обеих
    картинок один, это один и тот же кадр.
    """
    m = face_mask(src)
    if m is None:
        return swapped
    a = imread(src).astype(np.float32)
    b = imread(swapped).astype(np.float32)
    if a.shape != b.shape:
        return swapped
    mm = m[..., None]
    imwrite(out, np.clip(a * (1.0 - mm) + b * mm, 0, 255).astype(np.uint8))
    return out


def transfer(src, ref, out_dir, restore=RESTORE, visibility=VISIBILITY,
             up_ref=None, whole_frame=False):
    """Перенести лицо с `ref` на `src`. Возвращает путь к результату."""
    g = cc.load_template(TEMPLATE)
    cc.apply_sets(g, {
        "1.image": cc.upload(src),
        "2.image": up_ref or cc.upload(ref),
        "4.face_restore_model": restore,
        "4.face_restore_visibility": visibility,
        "3.boost_model": restore,
        "3.visibility": visibility,
        "3.enabled": restore != "none",
        "5.filename_prefix": os.path.splitext(os.path.basename(src))[0],
    })
    files = cc.run_graph(g, out_dir)
    if not files:
        raise RuntimeError("воркер не вернул кадр после переноса")
    # РАЗМЕР ОБЯЗАН СОВПАСТЬ, И ЭТО ПРОВЕРЯЕТСЯ. Один раз воркер вернул на
    # кадре 1536x1920 картинку 512x512 — разовый сбой, но кадр при этом
    # выглядел рабочим файлом. Склейка ниже такой кадр молча пропускала дальше
    # (размеры не сошлись — вернула вход воркера как есть), и в доводку уходил
    # уменьшенный в девять раз кадр. Лучше отказ: съёмка помечает его failed и
    # переснимает следующим запуском.
    a, b = imread(src), imread(files[0])
    if a is None or b is None or a.shape != b.shape:
        raise RuntimeError(
            f"перенос вернул кадр другого размера: "
            f"{None if b is None else (b.shape[1], b.shape[0])} вместо "
            f"{None if a is None else (a.shape[1], a.shape[0])}")
    if whole_frame:
        return files[0]
    return keep_outside(src, files[0],
                        os.path.splitext(files[0])[0] + "_face.png")


def _cos(a, b):
    from metrics import faces
    va, vb = faces.detect(a), faces.detect(b)
    if not va or not vb or va.get("embedding") is None \
            or vb.get("embedding") is None:
        return None
    x = np.asarray(va["embedding"], np.float32)
    y = np.asarray(vb["embedding"], np.float32)
    return float(x @ y / (np.linalg.norm(x) * np.linalg.norm(y)))


def _frames(arg):
    if os.path.isdir(arg):
        out = []
        for e in ("*.png", "*.jpg", "*.jpeg"):
            out += glob.glob(os.path.join(arg, e))
        return sorted(p for p in out
                      if "contact_sheet" not in os.path.basename(p).lower())
    return [arg]


def main():
    setup_console()
    args = sys.argv[1:]
    if not args or args[0].startswith("--"):
        print(__doc__)
        raise SystemExit(1)
    ref = cli_opt(args, "--ref")
    if not ref or not os.path.exists(ref):
        raise SystemExit(
            "--ref обязателен и должен существовать: лицо берётся С НЕГО, и "
            "подставить сюда\n  чужой файл значит поменять персонажа во всём "
            "прогоне разом.")
    out_dir = cli_opt(args, "--out-dir") or work_dir("_tmp", "face_transfer")
    restore = cli_opt(args, "--restore", RESTORE)
    vis = float(cli_opt(args, "--visibility", str(VISIBILITY)))
    os.makedirs(out_dir, exist_ok=True)
    up_ref = cc.upload(ref)
    ok = 0
    for src in _frames(args[0]):
        name = os.path.basename(src)
        if os.path.abspath(os.path.dirname(src)) == os.path.abspath(out_dir):
            raise SystemExit(
                f"приёмник совпадает с папкой входа: {out_dir}\n"
                f"  Перенос не идемпотентен — повтор наложит лицо на уже "
                f"перенесённое.")
        try:
            dst = transfer(src, ref, out_dir, restore, vis, up_ref)
        except Exception as e:
            print(f"{name:30s} сбой: {type(e).__name__}: {e}")
            continue
        before, after = _cos(src, ref), _cos(dst, ref)
        ok += 1
        print(f"{name:30s} сходство "
              f"{('%.3f' % before) if before else '—'} → "
              f"{('%.3f' % after) if after else '—'}")
    print(f"\nперенесено на {ok} кадрах → {out_dir}")
    print("  дальше — прививка кожи (skin_graft.py): перенос стирает фактуру, "
          "и вернуть её\n  можно только ПОСЛЕ него")


if __name__ == "__main__":
    main()
