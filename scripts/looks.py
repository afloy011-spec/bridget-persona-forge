def register_axis(bench=None, look_names=None):
    """Объявить ось образов стенду scripts/lab_grid.py. Возвращает ось.

    ПОЧЕМУ РЕГИСТРАЦИЯ, А НЕ СТРОКА, ВПИСАННАЯ В lab_grid.AXES РУКАМИ. Ось
    образов ВЫЧИСЛЯЕТСЯ из LOOKS — и строками сетки, и хвостами промпта.
    Скопированная в стенд, она застывает: добавленный образ меряться не
    начинает, переименованный меряется под старым именем, у которого нет
    хвоста, — и стенд честно печатает таблицу, в которой замерено не то, про
    что потом написан документ. Расхождение при этом молчит: и там и там
    получается ровно столько строк, сколько ожидает читатель.

    ХВОСТЫ ЕДУТ ВМЕСТЕ С ОСЬЮ. Стенд дописывает хвост варианту, чьё имя нашёл
    в своём словаре; ось без хвостов означает, что каждый образ меряли БЕЗ его
    промпта — то есть меряли, строго говоря, не его.

    Совпадение имён с чужой осью — отказ, а не молчаливая замена: словарь
    хвостов у стенда один на все оси, и переписанный хвост поменял бы то, что
    меряет соседняя ось, не оставив следа.
    """
    LG = bench or _bench()
    ax = axis(look_names)
    tails = suffixes()
    clash = sorted(n for n, t in tails.items()
                   if LG.AGE_SUFFIX.get(n, t) != t)
    if clash:
        raise SystemExit(
            f"имя образа занято чужим хвостом промпта в lab_grid.AGE_SUFFIX: "
            f"{', '.join(clash)}. Переименуй образ — иначе соседняя ось стенда "
            f"начнёт мерить не то, что меряла.")
    LG.AXES[AXIS] = ax
    LG.AGE_SUFFIX.update(tails)
    return ax


def _bench():
    """scripts/lab_grid.py — ЛЕНИВО, а не импортом сверху файла.

    Стенд тянет за собой comfy_client, то есть адрес воркера. Список образов,
    их стек и вердикт по готовому замеру не требуют ни сети, ни настроенной
    машины, и превращать `--look` в команду, которая падает у человека без
    ComfyUI, незачем — этой болезнью уже болел generate.py (см. тест
    test_dry_run_works_without_a_configured_host).
    """
    import importlib
    return importlib.import_module("lab_grid")


def _pipeline():
    """scripts/generate.py — тоже ЛЕНИВО, и по другой причине.

    Образ навешивается в конвейере, то есть импортировать этот модуль будет
    сам generate.py. Встречный импорт сверху файла даёт кольцо: работать оно
    будет ровно до тех пор, пока ни одна из сторон не тронет другую на уровне
    модуля, — то есть сломается не при вписывании образов в конвейер, а
    когда-нибудь потом и у того, кто ничего про это кольцо не знает.
    Односторонняя ленивая ссылка снимает вопрос совсем.
    """
    import importlib
    return importlib.import_module("generate")


def project_path(project):
    """Папка проекта по имени. Готовый путь пропускается как есть.

    Стенду нужна ПАПКА с карточкой и раскадровкой, а замеру — ИМЯ проекта, под
    которым он лёг в рабочий корень. Это разные вещи, и в одном ключе
    командной строки они помещаются только потому, что здесь их разводит одна
    функция, а не каждый вызывающий по-своему.
    """
    if os.path.isdir(project):
        return project
    p = os.path.join(ROOT, "projects", project)
    if not os.path.isdir(p):
        raise SystemExit(f"нет проекта {project!r}: ни папки {p}, ни пути с "
                         f"таким именем")
    return p


