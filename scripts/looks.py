def _bounds(g, char=None):
    """Границы метрик стенда: метрика → (низ, верх).

    Метрики, границы которой посчитать НЕ ОТ ЧЕГО, в ответе нет вовсе — и
    judge() делает из этого незамер, а не «претензий нет». Разница ровно та же,
    что между FAIL и NOT_MEASURED в воротах: судить нечем и всё в допуске — это
    два разных ответа, и второй здесь был бы враньём.

    Возраст судится полосой ЭТОГО персонажа, и считает её та же функция, что и
    ворота. Своя формула была бы четвёртой точкой правды про возраст, а
    скопированные числа — той самой подписью, которая в этом проекте
    расходилась с реальностью трижды.
    """
    out = {}
    for metric, keys in BOUNDS.items():
        if keys is FROM_CARD:
            # age_band сам решает, нужна ли ему карточка: манифест со старыми
            # age_min/age_max отвечает числами и без неё, и вердикт, снятый до
            # переезда полосы, читается без перепрогона. Нет ни того, ни
            # другого — метрика уходит в незамер.
            try:
                out[metric] = age_band(char, g)
            except SystemExit:
                pass
            continue
        lo, hi = keys
        out[metric] = (None if lo is None else float(g[lo]),
                       None if hi is None else float(g[hi]))
    return out


def _split_gates(g):
    """Обязательные и справочные ворота — теми же правилами, что gates.py.

    Синонимы и запасной список берутся оттуда же импортом, а не копией:
    манифест зовёт ворота цветности colour, метрика — chroma, и незаявленный
    синоним означает вечный незамер.

    ПУСТОЙ СПИСОК ОБЯЗАТЕЛЬНЫХ ВОРОТ — ОТКАЗ, а не зелёный свет: судить образ
    было бы нечем, и каждый вышел бы с PASS. Ровно тот ложный зелёный, ради
    которого в проекте три состояния.
    """
    inf = {G.ALIAS.get(n, n) for n in (g.get("informational") or [])}
    req = [G.ALIAS.get(n, n) for n in (g.get("required") or G.REQUIRED)]
    req = [n for n in req if n not in inf]
    if not req:
        raise SystemExit(
            "обязательных ворот не осталось — судить образы нечем, каждый "
            "вышел бы с ложным PASS. Проверь assets.json → gates.required / "
            ".informational.")
    return req, inf


def judge(measured, gates=None, char=None):
    """Замер против ворот — без привязки к образу. Словарь вердикта.

    measured — строка замера стенда: {метрика: число или None}. Ровно тот
    словарь, который кладёт в grid.json scripts/lab_grid.py.

    char — карточка персонажа: от её age считается полоса возраста. Без неё
    возраст не судится ЧУЖОЙ полосой и не выпадает из отчёта — он становится
    незамером с причиной.

    ОТДЕЛЬНО ОТ check() потому, что судить надо и БАЗОВУЮ строку сетки: без
    неё читатель документа видит четыре провала справочных ворот подряд и
    решает, что их наделали образы. Их наделала связка модель+промпт, база
    проваливает те же ворота — и это ровно та причина, по которой они
    справочные.

    ТРИ СОСТОЯНИЯ. Метрика, которой в замере нет, — это NOT_MEASURED, а не
    «претензий нет»: образ, у которого не померили резкость, неотличим от
    образа, у которого она в допуске, и разница между ними — это ровно то,
    ради чего образ и меряют. Правила сведения состояний берутся из
    metrics/verdict.py, чтобы не разойтись с воротами в определениях.

    СПРАВОЧНЫЕ ВОРОТА НЕ БЛОКИРУЮТ, но их числа остаются в ответе — так же,
    как в gates.py. Идентичность на этом конвейере провалена у всех кадров
    (см. gates._identity_is_informational), и судить ею образы значило бы
    забраковать все разом, включая базу.
    """
    V = G._verdict_api()
    g = gates or manifest()["gates"]
    required, informational = _split_gates(g)

    bounds = _bounds(g, char)
    results = {}
    for metric in BOUNDS:
        value = measured.get(metric)
        if metric not in bounds:
            # Границ нет — судить нечем. Пропустить метрику молча значило бы
            # выдать образ проверенным по батарее, из которой тихо вынули
            # ворота: ровно тот ложный зелёный, ради которого здесь три
            # состояния.
            results[metric] = V.not_measured(
                metric, "границы этой метрики считаются от карточки персонажа "
                        "(character.json → age), а карточка сюда не передана: "
                        "зови looks.py с --project <имя>")
        elif value is None:
            results[metric] = V.not_measured(
                metric, "стенд не дал числа по этой метрике")
        else:
            lo, hi = bounds[metric]
            results[metric] = V.gate(metric, value, lo=lo, hi=hi)
    # ОБЯЗАТЕЛЬНЫЕ ВОРОТА, КОТОРЫХ СТЕНД НЕ МЕРЯЕТ, — тоже незамер, а не
    # «к образу не относится». Тату и внешний детектор считаются по
    # содержимому кадра, и соблазн молча выкинуть их из вердикта — это ровно
    # тот ложный зелёный, от которого лечит третье состояние: образ вышел бы
    # проверенным, ни разу не встретившись с половиной блокирующей батареи.
    # Причина пишется явно: незамер без причины неотличим от ненаписанной
    # метрики.
    for name_ in required:
        if name_ not in results:
            results[name_] = V.not_measured(
                name_, "стенд образов этих ворот не меряет — они про "
                       "содержимое кадра; см. scripts/gates.py")

    judged = {k: v for k, v in results.items() if k not in informational}
    res = V.verdict(judged, required=required)
    return {"verdict": res["verdict"], "failed": list(res["failed"]),
            "missing": list(res["missing"]), "gates": results,
            "required": required,
            "informational": sorted(informational & set(results))}


def busted_seeds(rows, name, gates=None, char=None):
    """Обязательные ворота, которые образ валит НЕ НА КАЖДОМ сиде. {ворота: [сиды]}.

    ЗАЧЕМ ОТДЕЛЬНО ОТ ВЕРДИКТА. Вердикт считается по среднему трёх кадров, а
    среднее прячет одиночный провал: образ, у которого один сид из трёх вышел
    за ворота, отличается от чистого тем, что треть его кадров уедет в брак, —
    и в таблице средних он выглядит ровно так же. Это тот же дефект, из-за
    которого в проекте частичный вердикт перестал выдавать себя за полный, и
    здесь он воспроизводится один в один, только усреднением, а не выборкой.
    """
    out = {}
    per_seed = by_seed(rows).get(name, {})
    for seed in sorted(per_seed, key=lambda s: (s is None, str(s))):
        for metric in judge(per_seed[seed], gates, char)["failed"]:
            out.setdefault(metric, []).append(seed)
    return out


def check(name, measured, gates=None, per_seed=None, char=None):
    """Выносит ли ОБРАЗ метрику за ворота — и сходится ли это с тем, что он
    сам про себя объявил в поле out.

    per_seed — то, что вернул busted_seeds: ворота, провáленные на отдельных
    сидах. Они попадают в тот же счёт, что и провал по среднему, потому что
    объявлять про себя образ обязан и их: «в среднем проходит» — это не
    «проходит», если каждый третий кадр отправляется в брак.
    """
    look = get(name)
    res = judge(measured, gates, char)

    per_seed = per_seed or {}
    failed = sorted(set(res["failed"]) | set(per_seed))
    declared = list(look.get("out") or [])
    # ОБЪЯВЛЕНИЕ СВЕРЯЕТСЯ В ОБЕ СТОРОНЫ. Необъявленный провал — это образ,
    # который врёт про себя. Объявление, которое замер больше не
    # подтверждает, — это устаревшее предупреждение: оно приучает читателя
    # проходить мимо красного, и следующий настоящий провал он тоже
    # пролистает.
    undeclared = sorted(set(failed) - set(declared))
    stale = sorted(set(declared) - set(failed))
    # НЕЗАМЕР НЕ ОБЪЯВЛЯЕТСЯ ЗАРАНЕЕ НИКОГДА. Объявить можно измеренный
    # провал, а «мы знали, что не померим» — это и есть ложный зелёный.
    accepted = not undeclared and not stale and not res["missing"]

    out = dict(res)
    out.update({"look": name, "accepted": accepted, "undeclared": undeclared,
                "stale_declarations": stale, "declared": declared,
                "seed_fails": {m: list(s) for m, s in per_seed.items()}})
    return out


def _mean(values):
    """Среднее по числам; None, если чисел нет вовсе.

    Пустое среднее — это НЕ ноль: ноль означал бы «померили и вышло ничего», а
    здесь не померили. Разницу между ними и держат три состояния вердикта.
    """
    import statistics as st
    got = [v for v in values if isinstance(v, (int, float))]
    return st.mean(got) if got else None


def by_seed(rows):
    """Строки grid.json → {вариант: {сид: {метрика: среднее по кадрам сида}}}.

    Сид сохраняется, а не сворачивается сразу в среднее по варианту, потому что
    сетка ПАРНАЯ: строка «база» и строка образа сняты на одном и том же сиде, и
    вся конструкция стенда держится на этом. Свернув сиды первым же действием,
    цену потом считают как разницу двух средних — и вместе с сидом теряют
    единственный способ узнать, устойчива ли она (см. paired_cost).
    """
    out = {}
    for row in rows:
        (out.setdefault(row.get("вариант"), {})
            .setdefault(row.get("сид"), []).append(row))
    return {variant: {seed: {m: _mean([r.get(m) for r in got]) for m in BOUNDS}
                      for seed, got in seeds.items()}
            for variant, seeds in out.items()}


def by_variant(rows):
    """{вариант: {метрика: среднее по сидам}} — то, что судят ворота.

    Усреднение повторяет lab_grid._summary, а не зовёт его: там оно заперто
    внутри печатающей функции, которая заодно пишет свой markdown и ничего не
    возвращает. Правило одно и то же — среднее по замерам, где число получено;
    вариант, где не получено ни одного, остаётся None и доезжает до вердикта
    незамером.
    """
    agg = {}
    for variant, per_seed in by_seed(rows).items():
        agg[variant] = {m: _mean([s[m] for s in per_seed.values()])
                        for m in BOUNDS}
        agg[variant]["_кадров"] = sum(1 for r in rows
                                      if r.get("вариант") == variant)
    return agg


def paired_cost(rows, name):
    """Цена ПО СИДАМ: разница с базой НА ТОМ ЖЕ СИДЕ. {метрика: [дельты]}.

    ПОЧЕМУ ПАРНО, А НЕ РАЗНИЦЕЙ СРЕДНИХ. Сид закреплён по строке сетки ровно
    ради этого: на этом конвейере один промпт с разными сидами даёт разных
    женщин одного типажа, и разброс между сидами БОЛЬШЕ, чем цена образа.
    Разница двух средних этот разброс не убирает, а прячет: получается одно
    аккуратное число, про которое неизвестно даже, в одну ли сторону тянули
    все три пары. Парные дельты этот вопрос задают — и иногда отвечают «нет».
    """
    seeded = by_seed(rows)
    base, look = seeded.get(BASE, {}), seeded.get(name, {})
    out = {m: [] for m in BOUNDS}
    for seed in sorted(set(base) & set(look), key=lambda s: (s is None, str(s))):
        for metric in BOUNDS:
            a, b = base[seed][metric], look[seed][metric]
            if a is not None and b is not None:
                out[metric].append(b - a)
    return out


def firm(deltas):
    """Устойчива ли цена по сидам: True / False / None («проверять нечем»).

    Три состояния и здесь, по той же причине, что в воротах: на одном сиде
    устойчивость не проверяется вовсе, и выдать в этом случае True значило бы
    назвать проверенным то, что не проверялось.

    УСТОЙЧИВЫ ДВА СЛУЧАЯ. Все дельты одного знака — цена есть и она в одну
    сторону. Все дельты нулевые — цены НЕТ, и это ровно такой же измеренный
    результат: «образ не трогает эту метрику» три пары подтверждают так же
    твёрдо, как и любой сдвиг. Смешанный случай — ноль вперемешку со сдвигом
    или разные знаки — не устойчив: среднее по таким парам выглядит ценой, но
    ею не является.
    """
    if len(deltas) < 2:
        return None
    return (all(d > 0 for d in deltas) or all(d < 0 for d in deltas)
            or all(d == 0 for d in deltas))


def _short(path):
    """Путь замера для отчёта: рабочий корень заменяется на <work_root>.

    Абсолютный путь личной машины в файле репозитория — та же болезнь, что
    адрес воркера в манифесте (assets.json → _host_default): у рецензента он
    не значит ничего, а документ выглядит воспроизводимым. Имя внутри
    рабочего корня воспроизводимо у всех, потому что корень объявлен.
    """
    if not path:
        return path
    root = work_root()
    p, r = os.path.normpath(path), os.path.normpath(root)
    if os.path.normcase(p).startswith(os.path.normcase(r)):
        p = "<work_root>" + p[len(r):]
    return p.replace("\\", "/")


def grid_path(project, root=None):
    """Где лежит замер образов. work_root, а НЕ work_dir: тот создаёт каталог.

    Скрипт, который на вопрос «а замер есть?» отвечает созданием пустой
    папки, потом сам же говорит «замера нет» — и делает это в чужом рабочем
    корне.
    """
    return os.path.join(root or work_root(), project, "lab", AXIS, "grid.json")


def check_grid(path, gates=None, char=None):
    """Вердикт по всем образам разом из grid.json стенда.

    Образ, которого в замере нет, получает NOT_MEASURED с причиной, а не
    выпадает из отчёта: молчание неотличимо от «всё хорошо», и именно так из
    таблицы исчезали непромеренные кадры.

    char — карточка того персонажа, на котором снят замер: полоса возраста
    считается от неё. Берётся вместе с путём из project_grid(), чтобы вердикт
    и полоса не оказались про разных людей.
    """
    data = read_json(path) if path and os.path.exists(path) else None
    rows = (data or {}).get("rows") or []
    agg = by_variant(rows)
    out = {"source": _short(path), "measured": data is not None,
           "cell": (data or {}).get("cell"), "seeds": (data or {}).get("seeds"),
           "base": agg.get(BASE), "looks": {}}
    # База судится теми же воротами и попадает в отчёт наравне с образами:
    # иначе четыре одинаковых провала справочных ворот подряд читаются как
    # «образы всё сломали», хотя это состояние конвейера до всякого образа.
    out["base_judged"] = judge(out["base"] or {}, gates, char)
    for name in names():
        measured = agg.get(name)
        res = check(name, measured or {}, gates,
                    busted_seeds(rows, name, gates, char), char)
        res["frames"] = (measured or {}).get("_кадров", 0)
        res["values"] = {m: (measured or {}).get(m) for m in BOUNDS}
        # Цена — среднее ПАРНЫХ дельт, а не разница средних. Совпадают они
        # только когда у базы и образа один и тот же набор сидов; когда не
        # совпадают — разница средних врёт, а парная считает по общим сидам.
        per_seed = paired_cost(rows, name)
        res["cost_by_seed"] = per_seed
        res["cost"] = {m: _mean(per_seed[m]) for m in BOUNDS}
        res["cost_firm"] = {m: firm(per_seed[m]) for m in BOUNDS}
        if not measured:
            res["why_not_measured"] = (
                "стенд этого образа не гонял" if data is not None else
                f"замера нет вовсе: {out['source']}")
        out["looks"][name] = res
    return out


