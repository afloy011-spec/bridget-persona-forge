def names():
    return sorted(LOOKS)


def get(name):
    """Образ по имени. Незнакомое имя — отказ вслух, а не пустой стек.

    Пустой стек на опечатку страшнее, чем падение: кадр отрисовался бы,
    попал бы в реестр и в сдачу, и отличить его от кадра С образом было бы
    нечем — оба выглядят «просто снятыми».
    """
    if name not in LOOKS:
        raise SystemExit(f"нет образа {name!r}; есть: {', '.join(names())}")
    return LOOKS[name]


def stack(name):
    """Добавка к базовому стеку лор: [(имя файла, сила), ...].

    None означает «образ не назначен» и даёт пустой список: так вызывающему
    не приходится ветвиться, а конвейер без образа работает ровно как
    работал. Это штатный режим, а не деградация.
    """
    if not name:
        return []
    return [(n, float(s)) for n, s in get(name)["loras"]]


def tail(name):
    """Хвост промпта образа. Пусто, если образа нет или он не трогает текст."""
    return get(name)["tail"] if name else ""


def dress(prompt, name):
    """Промпт с хвостом образа. Без образа — тот же промпт, байт в байт.

    Отдельной функцией на две строки по двум причинам. Первая: пустой хвост
    даёт промпт с висящей запятой, а висящая запятая при cfg 1.0 — это лишний
    пустой токен в конце, то есть другой кадр на том же сиде.

    Вторая важнее. СКЛЕЙКА ЗДЕСЬ ОБЯЗАНА СОВПАДАТЬ СО СКЛЕЙКОЙ СТЕНДА: он
    дописывает хвост сам (lab_grid.run, через свой словарь AGE_SUFFIX), и если
    конвейер соберёт ту же пару иначе — хоть пробелом, хоть порядком, — то
    сдаётся кадр, снятый не тем промптом, который померили, а цена в документе
    остаётся от померенного. Разойтись эти две строки могут только молча,
    поэтому совпадение проверяется тестом, а не глазами.
    """
    return f"{prompt}, {tail(name)}" if name and tail(name) else prompt


def apply(graph, name):
    """Навесить образ на граф: дописать лоры образа в конец цепочки.

    ЛОГИКА ЦЕПОЧКИ НЕ КОПИРУЕТСЯ, а берётся у стенда (lab_grid.stack_loras):
    шаблон держит пять слотов, они заняты все, и добавка нарастает звеном с
    перецепкой сэмплера. Своя копия этого кода в конвейере значила бы, что
    образ на сдаче и образ на стенде собираются разными руками — и меряли бы
    тогда не то, что сдают. Именно это и есть вопрос, ради которого стенд
    существует.

    Импорт стенда ленивый (см. _bench): конвейеру он нужен ровно здесь, а
    lab_grid импортирует generate — на уровне модуля вышло бы кольцо.
    """
    return _bench().stack_loras(graph, stack(name)) if name else graph


def suits(name, scene_class):
    """Уместен ли образ на ячейке с таким светом.

    Отдельной функцией, потому что это единственное поле, которое можно
    проверить ДО GPU: грейд не на своей сцене виден только на готовом кадре,
    а стоит он столько же, сколько правильный.
    """
    return not name or scene_class in get(name)["fits"]


def axis(look_names=None):
    """Ось для scripts/lab_grid.py: [(имя строки, добавка), ...].

    Первая строка — база с пустой добавкой: цена образа считается как
    разница с ней, и без неё в таблице стенда вся колонка цены станет
    прочерками.

    Имена строк — латинские ключи образов, потому что lab_grid делает из них
    ИМЕНА ФАЙЛОВ. Кириллица там работает, но выданный наружу кадр с именем
    «тёплая_квартира_s17.png» переживает не всякую пересылку.
    """
    return [(BASE, [])] + [(n, stack(n)) for n in (look_names or names())]


def suffixes():
    """Хвосты промпта по имени строки сетки — для lab_grid.AGE_SUFFIX.

    Стенд дописывает хвост варианту, чьё имя нашлось в этом словаре. Образ
    без хвоста в словарь не попадает: пустая строка дала бы промпт с висящей
    запятой.
    """
    return {n: LOOKS[n]["tail"] for n in names() if LOOKS[n].get("tail")}


