def _fmt(metric, value, sign=False):
    if value is None:
        return "—"
    digits = 0 if metric in ("age", "sharp") else 3
    return f"{value:{'+' if sign else ''}.{digits}f}"


def _role(res, metric):
    """Роль ворот в вердикте — одним правилом на отчёт и на документ.

    Раздельные копии этого правила разъехались бы с манифестом по одной: он
    может перевести ворота из обязательных в справочные ключом, и «роль» в
    документе обязана переехать вместе с ним.
    """
    return ("справочные" if metric in res["informational"]
            else "обязательные" if metric in res["required"]
            else "не блокируют")


def _seed_fails_txt(res):
    """«sharp на сидах 11, 33» — одной строкой на отчёт и на документ."""
    return "; ".join(
        f"{TITLES.get(m, m)} на сид{'ах' if len(s) > 1 else 'е'} "
        + ", ".join(str(x) for x in s)
        for m, s in sorted(res.get("seed_fails", {}).items()))


def _cost_note(res, metric):
    """Как показать цену: сами дельты и вердикт по их знаку.

    Число цены без этого читается как результат замера, хотя это среднее трёх
    чисел, которые могли смотреть в разные стороны. Пометка одна на отчёт и на
    документ — чтобы «устойчиво» в них не разъехалось.
    """
    deltas = res.get("cost_by_seed", {}).get(metric) or []
    if not deltas:
        return "—"
    txt = ", ".join(_fmt(metric, d, sign=True) for d in deltas)
    state = res.get("cost_firm", {}).get(metric)
    if state is None:
        return f"{txt} (сид один — устойчивость не проверена)"
    if state:
        # Нулевая цена называется вслух: строка «+0.000, +0.000, +0.000» в
        # колонке цены читается как погрешность округления, хотя это
        # измеренный ответ «образ этой метрики не трогает».
        return ("0 на всех сидах — метрику не трогает"
                if all(d == 0 for d in deltas) else txt)
    # РАЗНЫЕ ФОРМУЛИРОВКИ ДЛЯ РАЗНОГО. Знак, который меняется, и сид, на
    # котором сдвига просто не случилось, — это две разные новости, и общее
    # «не устойчиво» на обе стирает ту, что важнее.
    if any(d > 0 for d in deltas) and any(d < 0 for d in deltas):
        return f"знак плавает: {txt}"
    return f"не на каждом сиде: {txt}"


def _range(gate):
    lo, hi = gate.get("min"), gate.get("max")
    if lo is None and hi is None:
        return "—"
    return f"[{'−∞' if lo is None else _fmt(gate['gate'], lo)}, " \
           f"{'+∞' if hi is None else _fmt(gate['gate'], hi)}]"


def report(res):
    """Таблица в stdout: строка — образ, худшие сверху."""
    print(f"замер: {res['source']}"
          + (f" · ячейка {res['cell']} · сиды {res['seeds']}"
             if res["measured"] else " — ФАЙЛА НЕТ"))
    print(f"\n{'образ':<16}{'вердикт':<14}{'кадров':>7}  замечания")
    print("-" * 78)
    order = {"FAIL": 0, "NOT_MEASURED": 1, "PASS": 2}
    for name in sorted(res["looks"],
                       key=lambda n: (order.get(res["looks"][n]["verdict"], 9),
                                      n)):
        r = res["looks"][name]
        notes = []
        if r.get("seed_fails"):
            notes.append("в среднем проходит, а на сидах — нет: "
                         + _seed_fails_txt(r))
        if r["undeclared"]:
            notes.append("НЕ ОБЪЯВЛЕНО: " + ", ".join(r["undeclared"]))
        if r["stale_declarations"]:
            notes.append("объявление устарело: "
                         + ", ".join(r["stale_declarations"]))
        if r["missing"]:
            notes.append("не замерено: " + ", ".join(r["missing"]))
        if r.get("why_not_measured"):
            notes.append(r["why_not_measured"])
        print(f"{name:<16}{r['verdict']:<14}{r['frames']:>7}  "
              + ("; ".join(notes) if notes else "объявление сходится с замером"))

    base = res["base_judged"]
    print(f"\n{BASE} (без образа) — {base['verdict']}")
    for metric in BOUNDS:
        gate = base["gates"][metric]
        print(f"  {TITLES[metric]:<14}{_fmt(metric, gate['value']):>9}"
              f"  {'':>15}{_range(gate):>16}  {gate['state']}")

    for name in sorted(res["looks"]):
        r = res["looks"][name]
        print(f"\n{name} — {LOOKS[name]['title']}")
        for metric in BOUNDS:
            gate = r["gates"][metric]
            mark = _role(r, metric)
            print(f"  {TITLES[metric]:<14}{_fmt(metric, r['values'][metric]):>9}"
                  f"  цена {_fmt(metric, r['cost'][metric], sign=True):>9}"
                  f"  {_range(gate):>16}  {gate['state']:<13}{mark:<14}"
                  f"по сидам {_cost_note(r, metric)}")
    print("\nЧисла печатает scripts/lab_grid.py — здесь они только сведены с "
          "воротами.\nNOT_MEASURED — это не «нормально»: образ без замера "
          "ставить в сдачу нельзя.")


