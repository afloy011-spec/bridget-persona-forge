def write_doc(path, res):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(doc(res))
    return path


def main():
    setup_console()
    args = sys.argv[1:]

    def opt(k, d=None):
        return cli_opt(args, k, d)

    project, grid = opt("--project"), opt("--grid")
    if "--look" in args:
        name = opt("--look")
        look = get(name)
        print(f"{look['title']} — {name}\n\n{look['why']}\n\n{look['light']}\n")
        print("стек поверх базового: "
              + ", ".join(f"{n} {s}" for n, s in look["loras"]))
        print(f"хвост промпта: {look['tail']}")
        print("сцены: " + ", ".join(look["fits"]))
        print(f"ограничения: {look['limits']}")
        clash = conflicts_with_base(name)
        if clash:
            print(f"ВНИМАНИЕ: {', '.join(clash)} уже есть в базовом стеке — "
                  f"силы сложатся молча")
        return

    if "--measure" in args:
        if not project:
            raise SystemExit("нужен --project <имя или путь к папке проекта>")
        # Путь к замеру берётся ОТ ПРОГОНА, а не собирается заново по имени:
        # замер и вердикт расходятся ровно в тот момент, когда их связывает
        # память человека, а не одна переменная.
        grid = measure(project, opt("--cell", "P1"), opt("--seed-list"),
                       int(opt("--seeds", 3)), "--dry" in args)
        if "--dry" in args:
            return

    # Прогон без вердикта — это кадры, про которые никто не сказал, годятся ли
    # они: --measure идёт в общий хвост и заканчивается тем же кодом возврата.
    if not ("--check" in args or "--md" in args or "--measure" in args):
        print(__doc__)
        print(f"{'образ':<16}{'название':<22}лоры")
        for name in names():
            print(f"{name:<16}{LOOKS[name]['title']:<22}"
                  + ", ".join(f"{n} {s}" for n, s in LOOKS[name]["loras"]))
        print(f"\nЦена образа известна только из замера стенда:\n  "
              f"{measure_cmd()}\n  {doc_cmd()}")
        return

    # Карточка нужна для полосы возраста, и берётся она ТОЙ ЖЕ функцией, что и
    # путь к замеру: иначе вердикт читается по одному проекту, а возраст
    # судится полосой другого. Без --project карточки нет, и возраст честно
    # уходит в незамер вместо чужой полосы.
    char = None
    if project:
        found, char = project_grid(project)
        grid = grid or found
    elif not grid:
        raise SystemExit("нужен --project <имя> (или прямой путь --grid "
                         "<...>/grid.json): без него неизвестно, чей "
                         "замер читать")
    res = check_grid(grid, char=char)
    if "--md" in args:
        print(f"отчёт: {write_doc(opt('--md'), res)}")
    report(res)
    # Ненулевой код, пока хоть один образ не сходится с замером. NOT_MEASURED
    # здесь такой же красный, как FAIL: образ без цены — это ровно тот
    # ложный зелёный, ради которого в проекте заведено третье состояние.
    raise SystemExit(0 if all(r["accepted"] for r in res["looks"].values())
                     else 1)


if __name__ == "__main__":
    main()
