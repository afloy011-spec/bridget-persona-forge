#!/usr/bin/env python3
"""Точечная правка кадра: окно вокруг выделения → свой холст → назад в кадр.

ЗДЕСЬ ТОЛЬКО ЧИСТАЯ ЛОГИКА, БЕЗ ЕДИНОГО ИМПОРТА ИЗ ComfyUI. Так она проверяется
обычным pytest на любой машине, а не только внутри запущенного сервера: узлы в
nodes.py — тонкие обёртки над этими функциями. Тензоры те же, что у ComfyUI:
IMAGE — [B, H, W, C] float 0..1, MASK — [B, H, W] float 0..1.

ЗАЧЕМ ЭТО ВООБЩЕ ОТДЕЛЬНЫМ ПАКЕТОМ, ЕСЛИ ДЕТЕЙЛЕРЫ УЖЕ ЕСТЬ. Приём «вырезать
область, отдать ей полный холст, вернуть обратно» — стандартный, он живёт в
Impact Pack (DetailerForEach). Своего здесь три вещи, и каждая замерена на
живом материале, а не придумана:

  1. РАЗМЕР ОКНА — ЭТО РУЧКА МАСШТАБА, А НЕ ПРОСТО ЗАПАС КОНТЕКСТА. Модель
     рисует деталь в масштабе того, что видит. Надпись на запястье, снятая с
     окном 0.24 кадра, вышла ВДВОЕ мельче эталона и легла поперёк косточки; то
     же самое с окном 0.42, где в кадр попал кусок предплечья, легло вдоль руки
     и нужного размера. Крутили при этом denoise — и это было не то. Поэтому
     узел печатает «увеличение», отношение холста к окну: именно оно говорит,
     во сколько раз крупнее модель будет рисовать, чем видно в кадре.

  2. НОСИТЕЛЬ ОБЯЗАН БЫТЬ РЕЗКИМ, и это проверяется до прохода, а не после.
     Замер на двух кадрах одного запястья: у снятого мягко дисперсия лапласиана
     по участку 19, у снятого под правку — 99. На расфокусе бессильны и проход,
     и вклейка графики: дело в носителе, а не в настройках. Порог 40 стоит
     между этими двумя числами, и узел ГОВОРИТ ВСЛУХ, когда участок ниже, —
     раньше это число печаталось в лог и никого не останавливало.

  3. МЕСТО ЗАДАЁТ ОКНО, А НЕ МОДЕЛЬ. Если резать вокруг выбранной точки и
     возвращать ровно туда же, дрейф размещения исчезает ПО ПОСТРОЕНИЮ. Это
     снимает главное возражение против диффузии для повторяющейся детали: та же
     метка того же размера в том же месте на всех кадрах персонажа. Проверено:
     пересъёмка по записанному сиду совпала с прежним результатом побайтно.

ПЕРО ПО КРАЮ ОБЯЗАТЕЛЬНО. Без него шов виден полосой — проход слегка меняет
яркость всего окна, и граница читается прямоугольником. Внутри правим всё, к
границе растворяем.

СИЛА ВКЛЕЙКИ (blend) — ОТДЕЛЬНАЯ РУЧКА, И ОНА НЕ ЛИШНЯЯ. Диффузия рисует
деталь ярче, чем нужно, чаще, чем бледнее; менять ради этого denoise значит
менять и рисунок тоже. blend гасит правку, не трогая её форму.
"""
import math

import torch

# Порог резкости участка. Ниже — носитель мягкий: см. пункт 2 в шапке.
SHARP_MIN = 40.0
# Доля короткой стороны окна, на которой перо гасит правку к краю.
FEATHER = 0.14
# Холст, который получает окно. Тот же, что у detail_face и detail_tattoo.
CANVAS = 1024

_LAPLACIAN = torch.tensor([[0., 1., 0.], [1., -4., 1.], [0., 1., 0.]])


def _as_bhwc(image):
    """Привести к [B, H, W, C]. Одиночный кадр [H, W, C] тоже принимается."""
    if image.dim() == 3:
        return image.unsqueeze(0)
    if image.dim() != 4:
        raise ValueError("ожидался тензор [B,H,W,C], пришёл %s"
                         % (tuple(image.shape),))
    return image


def sharpness(patch):
    """Дисперсия лапласиана по яркости участка [H, W, C].

    Считается в torch, а не через cv2, намеренно: узел не должен требовать
    зависимостей сверх тех, что уже есть у ComfyUI, иначе он не поставится там,
    где opencv собран без нужного модуля.
    """
    if patch.numel() == 0:
        return 0.0
    grey = patch[..., :3].mean(dim=-1)[None, None]
    k = _LAPLACIAN.to(grey.dtype).to(grey.device)[None, None]
    lap = torch.nn.functional.conv2d(grey, k, padding=0)
    return float(lap.var().item() * 255.0 * 255.0)


def box_from_mask(mask, w, h, pad=1.6, square=True):
    """Рамка вокруг выделения. None, если в маске ничего нет.

    pad — во сколько раз окно шире самого выделения. Это и есть ручка масштаба
    из пункта 1 шапки, а не «запас контекста»: узкое окно заставляет модель
    рисовать деталь мелко, широкое даёт ей место.
    """
    if mask is None:
        return None
    m = mask[0] if mask.dim() == 3 else mask
    ys, xs = torch.nonzero(m > 0.5, as_tuple=True)
    if len(xs) == 0:
        return None
    x0, x1 = float(xs.min()), float(xs.max()) + 1.0
    y0, y1 = float(ys.min()), float(ys.max()) + 1.0
    cx, cy = (x0 + x1) / 2.0, (y0 + y1) / 2.0
    bw, bh = (x1 - x0) * pad, (y1 - y0) * pad
    if square:
        bw = bh = max(bw, bh)
    return _clamp(cx, cy, bw, bh, w, h)


def box_from_point(at_x, at_y, size, w, h, square=True):
    """Рамка вокруг точки в долях кадра. Путь без маски — для скриптов.

    `size` — доля КОРОТКОЙ стороны кадра. Короткой, а не ширины: иначе одно и
    то же число даёт разные окна на портрете и на альбомном кадре, и настройка,
    подобранная на одном, молча уезжает на другом.
    """
    side = min(w, h) * float(size)
    return _clamp(at_x * w, at_y * h, side, side if square else side, w, h)


def _clamp(cx, cy, bw, bh, w, h):
    """Рамка внутри кадра, БЕЗ изменения размера при упоре в край.

    Сдвигаем, а не обрезаем: обрезка у края кадра молча уменьшила бы окно, то
    есть изменила бы масштаб рисования — ровно ту величину, ради управления
    которой узел и написан.

    А ЕСЛИ РАМКА БОЛЬШЕ КАДРА, ОБЕ СТОРОНЫ ЖМУТСЯ ОДНИМ МНОЖИТЕЛЕМ. Первая
    редакция резала стороны независимо (`min(bw, w)`, `min(bh, h)`) — и
    квадратная рамка при pad=40 на кадре 300x200 выходила 300x200, то есть
    переставала быть квадратной. Холст квадратный, значит такая рамка
    растянула бы деталь по одной оси; поймано тестом
    test_box_larger_than_frame_is_capped_to_the_frame.
    """
    k = min(1.0, float(w) / max(bw, 1e-6), float(h) / max(bh, 1e-6))
    bw, bh = bw * k, bh * k
    x0 = min(max(cx - bw / 2.0, 0.0), w - bw)
    y0 = min(max(cy - bh / 2.0, 0.0), h - bh)
    return (int(round(x0)), int(round(y0)),
            int(round(x0 + bw)), int(round(y0 + bh)))


def _resize(img_bhwc, width, height):
    """Билинейный ресайз [B,H,W,C] без зависимости от comfy.utils."""
    x = img_bhwc.permute(0, 3, 1, 2)
    x = torch.nn.functional.interpolate(x, size=(height, width),
                                        mode="bilinear", align_corners=False)
    return x.permute(0, 2, 3, 1).clamp(0.0, 1.0)


def cut(image, box, canvas=CANVAS):
    """Окно → свой холст canvas×canvas.

    ХОЛСТ ОБЯЗАТЕЛЕН, и это половина результата. На окне 230 px модель рисует
    деталь в 230 px — мелко и мыльно. Растянутое окно даёт детали собственный
    масштаб; тот же приём, что у детейлера лица.
    """
    image = _as_bhwc(image)
    x0, y0, x1, y1 = box
    crop = image[:, y0:y1, x0:x1, :]
    if crop.numel() == 0:
        raise ValueError("окно пустое: %s при кадре %dx%d"
                         % (box, image.shape[2], image.shape[1]))
    return _resize(crop, canvas, canvas)


def feather_mask(hh, ww, feather=FEATHER, dtype=torch.float32):
    """Перо по краю окна: 1 внутри, 0 на границе, косинусом между.

    Косинус, а не линейка: у линейного спада излом на стыке виден полосой на
    ровном фоне вроде кожи, а у косинуса производная на концах нулевая.
    """
    b = max(1, int(round(min(hh, ww) * float(feather))))
    ramp = torch.linspace(0.0, math.pi, 2 * b, dtype=dtype)
    ramp = (1.0 - torch.cos(ramp)) / 2.0            # 0 → 1, гладко
    col = torch.ones(hh, dtype=dtype)
    row = torch.ones(ww, dtype=dtype)
    col[:b] = ramp[:b]
    col[hh - b:] = ramp[:b].flip(0)
    row[:b] = ramp[:b]
    row[ww - b:] = ramp[:b].flip(0)
    return torch.minimum(col[:, None], row[None, :])


def paste(image, edited, box, feather=FEATHER, blend=1.0):
    """Правленое окно назад в кадр. Возвращает НОВЫЙ тензор, вход не трогает.

    Идемпотентности здесь нет и быть не может: второй проход положит правку
    поверх первой. Поэтому узел возвращает копию, а не пишет на месте.
    """
    image = _as_bhwc(image)
    edited = _as_bhwc(edited)
    x0, y0, x1, y1 = box
    hh, ww = y1 - y0, x1 - x0
    back = _resize(edited, ww, hh).to(image.dtype).to(image.device)
    m = feather_mask(hh, ww, feather, image.dtype).to(image.device)
    m = (m * float(blend))[None, ..., None]
    out = image.clone()
    src = out[:, y0:y1, x0:x1, :]
    n = min(src.shape[0], back.shape[0])
    out[:n, y0:y1, x0:x1, :] = (src[:n] * (1.0 - m) + back[:n] * m)
    return out.clamp(0.0, 1.0)


def report(box, frame_w, frame_h, canvas, sharp, sharp_min=SHARP_MIN):
    """Строка отчёта. Печатается на холст, а не только в консоль.

    Главное число здесь — УВЕЛИЧЕНИЕ: во сколько раз крупнее модель рисует, чем
    видно в кадре. Из него сразу понятно, почему деталь выходит не того
    размера, и его нельзя вывести из одного лишь denoise.
    """
    x0, y0, x1, y1 = box
    ww, hh = x1 - x0, y1 - y0
    zoom = canvas / max(1, min(ww, hh))
    lines = [
        "окно %dx%d в кадре %dx%d (%.0f%% короткой стороны)"
        % (ww, hh, frame_w, frame_h, 100.0 * min(ww, hh) / min(frame_w,
                                                               frame_h)),
        "холст %d → увеличение %.2fx: во столько раз крупнее модель рисует"
        % (canvas, zoom),
        "резкость участка %.0f (порог %.0f)" % (sharp, sharp_min),
    ]
    if sharp < sharp_min:
        lines.append(
            "ВНИМАНИЕ: участок мягкий. Чёткой детали не получится ни этим "
            "проходом, ни любым другим — дело в носителе, а не в настройках.")
    if zoom < 1.0:
        lines.append(
            "ВНИМАНИЕ: увеличение меньше единицы — окно крупнее холста, деталь "
            "будет нарисована МЕЛЬЧЕ, чем видна в кадре.")
    return "\n".join(lines)
