"""Ассет, вынутый из фотографии референса: надпись тату.

Поведения, которых до референса в конвейере не было и каждое из которых уже
один раз сломалось молча:

  ВЫПРЯМЛЕНИЕ НАДПИСИ отдаёт ось, а не направление, и «Manolo Blahnik» выходит
  вверх ногами — ассет при этом выглядит рабочим: правильный размер, правильная
  альфа, читаемая линия. Сломалось ДВАЖДЫ: первый раз потому, что направления
  не считали вовсе, второй — потому, что считали центром тяжести чернила, а на
  второму референсу выносные оказались длиннее, и правило
  перевернуло надпись.
  РАМКА АССЕТА растягивалась случайной тёмной точкой в углу фотографии до
  вчетверо большей, и надпись оказывалась в углу прозрачного холста, а весь
  подбор места в композите съезжал.
  ПОТОЛОК РАЗМЫТИЯ композита был завязан на ШИРИНУ вклейки, что верно для
  жирного силуэта и неверно для рукописного штриха: на запястье оставалось
  грязное пятно вместо имени.

Проверяются они на синтетике, а не на самой фотографии: сам кроп в репозитории
есть (references/), но поведение должно проверяться и без конкретной картинки —
и, главное, на фактуре, которую можно сделать НАРОЧНО НЕУДОБНОЙ.
"""
