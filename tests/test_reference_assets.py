# ЧЕРЕЗ _util, А НЕ cv2 НАПРЯМУЮ: cv2 на Windows отдаёт путь в системную ANSI и
# на C:/Users/<имя>/... молча ничего не пишет, вернув False. Тест на этом падал
# не в проверяемом коде, а в собственной подготовке.
from _util import imwrite as u_imwrite  # noqa: E402


def _load(name):
    path = os.path.join(ROOT, "scripts", name + ".py")
    spec = importlib.util.spec_from_file_location("t_" + name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _line_photo(angle, size=(520, 520), stray=None):
    """«Фотография» строки: светлая кожа, тёмные штрихи, выносные элементы вверх.

    Строка нарочно НЕСИММЕТРИЧНА по вертикали — основная масса чернила внизу,
    редкие высокие штрихи вверху. Именно этим отличается латинская строка от
    своей перевёрнутой копии, и именно на это смотрит определение направления.
    """
    h, w = size
    img = np.full((h, w, 3), 208, np.uint8)
    line = np.zeros((60, 300), np.uint8)
    line[38:52, :] = 255                       # тело строки: сплошная масса
    for x in range(8, 300, 34):                # выносные элементы вверх
        line[10:38, x:x + 5] = 255
    m = cv2.getRotationMatrix2D((150, 30), angle, 1.0)
    m[0, 2] += w / 2 - 150
    m[1, 2] += h / 2 - 30
    ink = cv2.warpAffine(line, m, (w, h), flags=cv2.INTER_NEAREST)
    img[ink > 0] = (58, 46, 44)
    if stray:
        cv2.circle(img, stray, 7, (52, 44, 42), -1)
    return img


def _ink_rows(alpha):
    """Центр тяжести чернила по вертикали, в долях высоты."""
    rows = alpha.astype(np.float64).sum(1)
    return float((rows * np.arange(len(rows))).sum() / rows.sum() / len(rows))


@pytest.mark.parametrize("angle", [0, 37, -37, 95, -95, 179])
def test_lettering_never_comes_out_upside_down(tmp_path, angle):
    """Под любым наклоном исходника строка выходит одной и той же стороной вверх.

    PCA даёт ОСЬ строки, и знак собственного вектора ничем не закреплён:
    выпрямленная надпись с равной вероятностью выходит перевёрнутой. Проверяется
    не угол, а результат — где после выпрямления лежит масса чернила. У строки с
    выносными элементами вверх она обязана быть НИЖЕ середины; у перевёрнутой
    она выше, и тогда надпись читается вверх ногами.
    """
    mod = _load("tattoo_from_photo")
    src = tmp_path / f"src{angle}.png"
    u_imwrite(str(src), _line_photo(angle))
    out = tmp_path / f"out{angle}.png"
    mod.build(str(src), str(out))

    from PIL import Image
    a = np.asarray(Image.open(out).convert("RGBA"))[..., 3]
    assert a.shape[1] > a.shape[0], (
        f"наклон {angle}°: строка не выпрямлена — рамка {a.shape[1]}x{a.shape[0]}")
    assert _ink_rows(a) > 0.5, (
        f"наклон {angle}°: строка вышла вверх ногами — центр тяжести чернила "
        f"на {_ink_rows(a):.2f} высоты, а у строки с выносными элементами "
        f"вверх он обязан быть ниже середины")


def test_a_speck_across_the_frame_does_not_inflate_the_asset(tmp_path):
    """Соринка в стороне от строки не растягивает рамку ассета.

    Она проходит отсев по площади (крупнее пыли) и лежит НЕ поперёк строки, а
    вдоль неё — то есть коридором вокруг оси не ловится. Ловится разрывом:
    строка сплошная, соринка отделена пустотой.
    """
    mod = _load("tattoo_from_photo")
    clean, dirty = tmp_path / "clean.png", tmp_path / "dirty.png"
    u_imwrite(str(clean), _line_photo(20))
    u_imwrite(str(dirty), _line_photo(20, stray=(28, 496)))
    from PIL import Image
    a = np.asarray(Image.open(mod.build(str(clean), str(tmp_path / "a.png"))))
    b = np.asarray(Image.open(mod.build(str(dirty), str(tmp_path / "b.png"))))
    assert abs(a.shape[0] - b.shape[0]) <= 2 and abs(a.shape[1] - b.shape[1]) <= 2, (
        f"соринка изменила рамку ассета: {a.shape[1]}x{a.shape[0]} без неё "
        f"против {b.shape[1]}x{b.shape[0]} с ней")


def test_blur_ceiling_follows_the_stroke_not_the_width():
    """Потолок размытия вклейки считается по толщине линии, а не по её ширине.

    Ширина ассета ничего не говорит о том, ЧТО размывается. Пока потолок стоял
    как доля ширины, он был подобран под жирный силуэт, а рукописную надпись той
    же ширины стирал в пятно: у неё штрих в пятнадцать раз тоньше.
    """
    mod = _load("composite_tattoo")
    thin = np.zeros((40, 400), np.float32)
    thin[19:21, :] = 1.0                      # штрих 2 px при ширине 400
    fat = np.zeros((40, 400), np.float32)
    fat[8:32, :] = 1.0                        # штрих 24 px при той же ширине
    s_thin, s_fat = mod._stroke_px(thin), mod._stroke_px(fat)
    assert s_thin < 4.0, f"тонкий штрих измерен как {s_thin:.1f} px"
    assert s_fat > 3 * s_thin, (
        f"толщина не различает линии: {s_thin:.1f} и {s_fat:.1f} px при "
        f"одинаковой ширине ассета — значит потолок снова считается по ширине")


def test_thin_lettering_survives_the_composite_on_soft_skin(tmp_path):
    """Тонкая надпись остаётся читаемой на расфокусированной коже.

    Проверка на РЕЗУЛЬТАТЕ, а не на вспомогательной функции: замер толщины
    может быть исправен, а потолок размытия считаться по-старому — ровно это и
    показал мутационный прогон, когда тест выше был единственным. Кожа здесь
    нарочно гладкая, то есть дисперсия лапласиана около нуля и формула просит
    максимального размытия: если его ограничивает ширина вклейки, штрих в два
    пикселя размазывается в ровное пятно, и контраст надписи падает в разы.
    """
    mod = _load("composite_tattoo")
    frame = tmp_path / "skin.png"
    u_imwrite(str(frame), np.full((600, 600, 3), 196, np.uint8))

    asset = np.zeros((60, 600, 4), np.uint8)
    asset[..., :3] = (40, 34, 32)
    asset[28:32, 20:580, 3] = 255            # штрих 4 px при ширине 600
    from PIL import Image
    apath = tmp_path / "ink.png"
    Image.fromarray(asset[..., [2, 1, 0, 3]], "RGBA").save(apath)

    out = mod.composite(str(frame), (0.5, 0.5), 0.6, 0.0, str(tmp_path / "o.png"),
                        str(apath), opacity=1.0)
    from _util import imread as u_imread
    got = u_imread(out).astype(np.float32)
    contrast = 196.0 - float(got.min())
    # 100 стоит между замеренными значениями: потолок по штриху даёт 148,
    # потолок по ширине — 65. Порог «лишь бы что-то осталось» пропускал бы обе.
    assert contrast > 100.0, (
        f"надпись стёрта композитом: самая тёмная точка отличается от кожи на "
        f"{contrast:.0f} уровня — при штрихе в 4 px это значит, что потолок "
        f"размытия снова считается по ширине вклейки, а не по толщине линии")


def _long_ascender_photo(angle, size=(520, 520)):
    """Строка, на которой ПРЕЖНЕЕ правило ориентации ошибается.

    Прежнее правило считало центр тяжести чернила: раз выносные тянутся вверх,
    масса обязана лежать ниже середины. Здесь выносные длинные и частые — как
    на второй фотографии референса, — и масса уезжает ВЫШЕ середины при верной
    ориентации. Базовая линия при этом остаётся ровной, потому что базовая
    линия ровная всегда: этим строка и отличается от своей перевёрнутой копии.
    """
    h, w = size
    img = np.full((h, w, 3), 208, np.uint8)
    line = np.zeros((80, 300), np.uint8)
    line[76:80, :] = 255                       # базовая линия: тонкая и ровная
    for x in range(2, 300, 12):                # стойки выносных: длинные
        line[8:76, x:x + 4] = 255
    for x in range(2, 300, 24):                # петли сверху, как у прописных
        line[8:30, x:min(x + 16, 300)] = 255
    m = cv2.getRotationMatrix2D((150, 40), angle, 1.0)
    m[0, 2] += w / 2 - 150
    m[1, 2] += h / 2 - 40
    ink = cv2.warpAffine(line, m, (w, h), flags=cv2.INTER_NEAREST)
    img[ink > 0] = (58, 46, 44)
    return img


def _densest_row(alpha):
    """Где лежит самый плотный ряд чернила, в долях высоты.

    ПРОВЕРЯЕТСЯ ДРУГИМ ЧИСЛОМ, ЧЕМ РЕШАЕТСЯ. Рабочее правило смотрит на
    ровность краёв; если бы тест смотрел туда же, он проверял бы, что функция
    равна самой себе. Здесь берётся независимый типографский признак: у
    латинской строки самая плотная полоса — это тело строки над базовой
    линией, и лежит она в НИЖНЕЙ половине. Замер на обеих фотографиях
    референса: 0.567 и 0.549.
    """
    rows = alpha.astype(np.float64).sum(1)
    k = max(3, int(0.05 * len(rows)) | 1)
    sm = cv2.blur(rows.reshape(-1, 1), (1, k)).ravel()
    return float(np.argmax(sm)) / (len(rows) - 1)


@pytest.mark.parametrize("angle", [0, 37, -37, 95, -95, 179])
def test_long_ascenders_do_not_flip_the_lettering(tmp_path, angle):
    """Строка с длинными выносными не выходит вверх ногами.

    ЭТО РЕГРЕССИЯ НА ЖИВОЙ ДЕФЕКТ. Появился второй референс тату, у
    неё выносные длиннее, и прежнее правило («масса ниже середины») перевернуло
    надпись — ассет при этом выглядел исправным: верный размер, верная альфа,
    читаемая линия, только «Manolo Blahnik» вверх ногами. Замер на обеих
    фотографиях: центр тяжести отходит от середины на 0.03-0.07 и на второй
    отходит НЕ В ТУ сторону, а ровность края различает ориентации в 2.7 и 3.3
    раза. Тест держит именно это: фактура, на которой прежнее правило
    ошибается, обязана выходить правильно.
    """
    mod = _load("tattoo_from_photo")
    src = tmp_path / f"long{angle}.png"
    u_imwrite(str(src), _long_ascender_photo(angle))
    out = mod.build(str(src), str(tmp_path / f"long{angle}_out.png"))

    from PIL import Image
    a = np.asarray(Image.open(out).convert("RGBA"))[..., 3]
    # Сначала — что фактура действительно ловит прежнее правило: без этого
    # тест зелен потому, что проверять нечего.
    assert _ink_rows(a) < 0.5, (
        f"наклон {angle}°: у этой строки масса чернила легла ниже середины "
        f"({_ink_rows(a):.2f}) — фактура перестала быть контрпримером, и тест "
        f"больше не проверяет то, ради чего написан")
    dense = _densest_row(a)
    assert dense > 0.5, (
        f"наклон {angle}°: строка вышла вверх ногами — самая плотная полоса "
        f"чернила легла на {dense:.2f} высоты, а тело латинской строки обязано "
        f"лежать в нижней половине")


def test_orientation_rule_is_not_the_centre_of_mass():
    """Правило ориентации спрашивается у краёв строки, а не у центра тяжести.

    Поведенческие тесты выше держат результат, но результат может совпасть и
    случайно: у обычной строки оба правила отвечают одинаково. Здесь
    проверяется сама функция на двух фактурах сразу — обычной и с длинными
    выносными, — и требуется верный ответ на обеих, в обе стороны.
    """
    mod = _load("tattoo_from_photo")
    for make in (_line_photo, _long_ascender_photo):
        alpha = mod.ink_alpha(make(0))
        a = alpha * mod.largest_ink(alpha)
        ys, xs = np.nonzero(a > 0.02)
        crop = a[ys.min():ys.max() + 1, xs.min():xs.max() + 1]
        up, top, bot = mod.is_upright(crop)
        assert up, (f"{make.__name__}: строка объявлена перевёрнутой (верх "
                    f"{top:.3f}, низ {bot:.3f})")
        down, top2, bot2 = mod.is_upright(crop[::-1, ::-1])
        assert not down, (f"{make.__name__}: перевёрнутая строка объявлена "
                          f"стоящей правильно (верх {top2:.3f}, низ {bot2:.3f})")
