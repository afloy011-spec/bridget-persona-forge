#!/usr/bin/env python3
"""Отбор прогона: одна квота выбраковки, а не три сложенные.

ЧТО ЗДЕСЬ ЗАЩИЩАЕТСЯ. Пороги признаков рисованности относительные — режется
худшая доля прогона, — и это верно: «нейрослоп» зависит от сцены и от плана, и
абсолютное число означало бы, что он известен заранее. Но три независимые
квоты по 20% СКЛАДЫВАЛИСЬ. Замер на прогоне в 39 кадров: выжило 14, волосы
отрезали семь, фон ещё семь, взгляд четыре, сходство пять. Это не ворота, а
фиксированная норма выбраковки в две трети.

И била она по разнообразию: у широких планов оставалось 2 из 10 и 1 из 10,
то есть набор сам собой сползал в одни портреты — ровно в ту скуку, против
которой сетка осей и строится.

Тесты гоняют настоящий judge() на синтетическом плане, где числа расставлены
руками: так видно, что режется, а что нет, без единого кадра и без GPU.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

import produce  # noqa: E402


def _plan(n=40, plans=("portrait", "bust", "half", "full")):
    """План, где каждый кадр плох РОВНО ПО ОДНОЙ оси и по разному месту в ней.

    Оси нарочно разведены: у кадра i плохой признак — i % 3, и он тем хуже,
    чем больше i. Если квоты складываются, вылетит около 60%; если квота одна
    — около 20%.
    """
    items = []
    for i in range(n):
        bad = i % 3
        vals = [0.10, 0.10, 0.10]
        vals[bad] = 0.10 + i / float(n)
        items.append({
            "id": f"X{i:02d}", "plan": plans[i % len(plans)],
            "state": "screened", "cos": 0.70,
            "hair": vals[0], "background": vals[1], "gaze": vals[2],
            "faces_in_frame": 1,
        })
    return {"project": "t", "n": n, "items": items}


def _run(data, tmp_path, **kw):
    produce.judge(data, str(tmp_path / "plan.json"), **kw)
    return [i for i in data["items"] if i.get("verdict") == "ok"]


def test_one_quota_not_three(tmp_path):
    """Выбраковка по признакам рисованности — одна доля, а не сумма трёх."""
    data = _plan(40)
    ok = _run(data, tmp_path, per_axis=0.2)
    share = 1 - len(ok) / 40.0
    assert 0.15 <= share <= 0.30, (
        f"выброшено {share:.0%} при квоте 20% — похоже, квоты снова "
        f"складываются по осям (три по 20% дают около 50-60%)")


def test_the_worst_axis_is_the_one_named(tmp_path):
    """Кадр вылетает за СВОЙ худший признак, и в причине стоит именно он."""
    data = _plan(40)
    _run(data, tmp_path, per_axis=0.2)
    RU = {"hair": "волосы", "background": "фон", "gaze": "взгляд"}
    for it in data["items"]:
        if it["verdict"] != "reject":
            continue
        worst = max(RU, key=lambda k: it[k])
        assert RU[worst] in it["reason"], (
            f"{it['id']}: худший признак {worst}={it[worst]:.2f}, "
            f"а в причине «{it['reason']}»")


def test_wide_plans_survive_as_often_as_close_ones(tmp_path):
    """Разнообразие планов переживает отбор.

    Прежняя редакция оставляла 2 из 10 по пояс и 1 из 10 в рост при 6 из 10
    портретов — набор сползал в портреты сам собой. Здесь все планы одинаково
    хороши по числам, и отбор обязан обойтись с ними одинаково.
    """
    data = _plan(40)
    ok = _run(data, tmp_path, per_axis=0.2)
    by = {}
    for it in ok:
        by[it["plan"]] = by.get(it["plan"], 0) + 1
    assert by and min(by.values()) >= 0.6 * max(by.values()), (
        f"планы выживают неравномерно: {by}")


def test_identity_floor_is_relative_without_repair(tmp_path):
    """Без починки лица планка сходства своя внутри каждого плана.

    Косинус растёт с крупностью лица: общий порог оставил бы одни портреты.
    """
    data = _plan(40)
    for i, it in enumerate(data["items"]):
        it["cos"] = 0.30 + 0.01 * i          # худшие — первые
    ok = _run(data, tmp_path, repaired=False)
    ids = {i["id"] for i in ok}
    assert "X00" not in ids, "худший по сходству кадр не отбракован"
    # Отбраковка по сходству идёт ВНУТРИ плана, а не общим порогом: у каждого
    # плана обязан выжить хотя бы один кадр, даже у самого слабого.
    assert len({i["plan"] for i in ok}) == 4, (
        f"общий порог сходства выкосил целые планы: "
        f"{sorted({i['plan'] for i in ok})}")


def test_a_repairable_face_is_not_thrown_away(tmp_path):
    """Если перенос лица чинит идентичность, планка становится абсолютной.

    Замер переносом на четырёх худших кадрах прогона: 0.482 → 0.819 и
    0.489 → 0.848 чинятся начисто, 0.213 → 0.251 и 0.340 → 0.340 не чинятся
    вовсе. Относительная планка выбрасывала ровно те кадры, которые доводка
    вылечила бы.
    """
    data = _plan(40)
    for i, it in enumerate(data["items"]):
        it["cos"] = 0.48 if i % 2 else 0.20
    ok = _run(data, tmp_path, repaired=True)
    good = [i for i in ok if i["cos"] > 0.4]
    dead = [i for i in ok if i["cos"] < 0.4]
    assert good, "кадры со сходством 0.48 отбракованы, хотя перенос их чинит"
    assert not dead, "кадры со сходством 0.20 приняты, хотя перенос их не чинит"


def test_a_second_face_is_rejected_whatever_else(tmp_path):
    """Второе лицо в кадре — отказ независимо от всех признаков.

    Датасету оно ломает обучение (лора тянет чужого человека в кадр), а
    переносу — работу: свап уходит не на то лицо. На прогоне такой кадр и
    остался единственным, кого перенос не починил вовсе (0.340 → 0.340).
    """
    data = _plan(40)
    for it in data["items"]:
        it["hair"] = it["background"] = it["gaze"] = 0.01
    data["items"][7]["faces_in_frame"] = 2
    ok = _run(data, tmp_path)
    assert data["items"][7]["verdict"] == "reject"
    assert "второе лицо" in data["items"][7]["reason"]
    assert len(ok) >= 30, "отказ по второму лицу утянул за собой остальных"


def test_upscale_is_part_of_the_pipeline():
    """Увеличение — шаг конвейера, а не ручная доводка в блокноте.

    ЭТО ЧИНИТ НАЙДЕННОЕ РЕВЬЮ РАСХОЖДЕНИЕ. Сдача собиралась скриптами из
    временной папки: она была увеличена и БЕЗ прививки кожи, а `produce.py` в
    это же время делал прививку и не делал апскейла. Инструмент, документация
    и результат были тремя разными вещами — а весь смысл этого репозитория в
    том, чтобы они были одним.

    УВЕЛИЧЕНИЕ И ФАКТУРА — ДВА РАЗНЫХ ШАГА, и сторожатся оба. Увеличивает
    ESRGAN, поверх него идёт проход фактуры в масштабе лица (ключ
    --no-texture его снимает). Ставить их наоборот уже пробовали: заказчик
    сказал «очень плохое качество», см. шапку finish().
    """
    import inspect
    sig = inspect.signature(produce.finish)
    assert sig.parameters["upscale_frames"].default is True, (
        "апскейл выключен по умолчанию — значит конвейер снова отдаёт кадры, "
        "у которых лицо занимает 124 px межзрачкового")
    # ПРОХОД ФАКТУРЫ ОБЯЗАН БЫТЬ ВЫКЛЮЧЕН, и это не послабление, а замер.
    # На кадре ПОСЛЕ ESRGAN он портит обе оси сразу: фактура лица 190 → 74,
    # сходство к эталону 0.655 → 0.554. Он писался под кадры со свопом, где
    # лицо приходило ватой (5.3) и поднять его было чем; с лорой лечить
    # нечего. Ключ --texture оставлен для кадров без увеличения.
    assert sig.parameters["refine_frames"].default is False, (
        "проход фактуры включён по умолчанию — на кадре после апскейла он "
        "сглаживает лицо и уводит сходство")
    src = inspect.getsource(produce.finish)
    assert "dfc.detail(" in src, "доводка не зовёт детейлер лица"
    assert "up_frame(" in src, "апскейл потерян"
    # И ВЫЗОВЫ ОБЯЗАНЫ БЫТЬ ДОСТИЖИМЫ. Первая редакция теста проверяла только
    # наличие вызова — мутационный прогон показал СЛЕПОТУ: подмена условия на
    # `if False:` оставляла вызов в тексте, и тест не краснел. Сторожится сам
    # сторож: ключ включает шаг, а не украшает подпись функции.
    # Отступ в шаблоне не украшение: условие встречается в функции ДВАЖДЫ —
    # снаружи цикла (импорт и печать) и внутри него, где собственно решается
    # судьба кадра. Первая редакция проверки смотрела на подстроку без
    # отступа и оставалась зелёной, когда мутант ломал именно внутреннее
    # условие: сторожила не тот из двух.
    for guard in ("if upscale_frames:", "if refine_frames:"):
        assert "\n" + " " * 12 + guard in src, (
            f"внутри цикла нет ветки «{guard}» — увеличение вызывается под "
            f"другим условием, и ключи больше не решают судьбу кадра")


def test_graft_is_off_by_default():
    """Прививка кожи выключена по умолчанию, и это замер, а не вкус.

    На кадрах С ПЕРЕНОСОМ ЛИЦА она даёт регулярную сетку вместо пор — разбор
    по стадиям на увеличенном вдвое кропе щеки. Ключ оставлен для прогонов без
    переноса, где её смысл прежний.
    """
    import inspect
    sig = inspect.signature(produce.finish)
    assert sig.parameters["graft_skin"].default is False, (
        "прививка снова включена по умолчанию — она вернёт сетку на кожу")
    doc = inspect.getdoc(produce.finish) or ""
    assert "сетк" in doc.lower(), (
        "причина выключения не записана рядом с кодом — через месяц её включат "
        "обратно, потому что «она же про реализм»")
