def test_the_paste_is_feathered():
    """Вклейка кропа растушёвана: жёсткий край дал бы видимый квадрат.

    ПРОВЕРЯЕТСЯ КОНСТАНТА МОДУЛЯ, А НЕ ЧИСЛО ИЗ ТЕСТА, и это исправление по
    мутационному прогону. Первая редакция звала _feathered(100, 0.10) с явной
    величиной — подмена FEATHER на 0.0 её не касалась вовсе. Хуже того, даже
    при нулевой растушёвке полоса схлопывается в один пиксель, у которого
    крайнее значение всё равно ноль, так что проверка «край погашен»
    оставалась зелёной. Сторожить надо ШИРИНУ полосы: маска обязана гаситься
    не в одном пикселе, а на заметном расстоянии от края.
    """
    side = 200
    m = detail_face._feathered(side, detail_face.FEATHER)
    assert m.shape == (side, side)
    assert m[side // 2, side // 2] == pytest.approx(1.0), (
        "середина вклейки ослаблена")
    assert m.min() >= 0.0 and m.max() <= 1.0
    edge = int(side * 0.015)
    assert m[edge, side // 2] < 0.5 and m[side // 2, edge] < 0.5, (
        f"на {edge} px от края маска уже почти непрозрачна — растушёвка "
        f"схлопнулась, и на кадре будет виден квадрат вклейки")


