def _blur(a, sigma=2.0):
    import cv2
    k = int(sigma * 6) | 1
    return cv2.GaussianBlur(a.astype(np.float32), (k, k), sigma)


def test_texture_back_moves_detail_and_leaves_structure(tmp_path, monkeypatch):
    """Возврат высоких частот не двигает низкие.

    Инструмент из конвейера убран, но оставлен: он верен сам по себе и
    понадобится, когда личность будет держать лора. Тест сторожит арифметику.

    СИНТЕТИКА ОБЯЗАНА ОТЛИЧАТЬСЯ И ПО НИЗКИМ ЧАСТОТАМ. Первая редакция брала
    гладкий градиент и тот же градиент плюс зерно — на такой паре наивное
    `detail = R - S` неотличимо от верного `R - blur(R)`, и мутационный
    прогон показал слепоту.
    """
    from _util import imwrite, imread

    h, w = 96, 96
    grad = np.tile(np.linspace(40, 200, w, dtype=np.float32), (h, 1))
    S = np.dstack([grad] * 3)
    drift = np.dstack([np.tile(np.linspace(60, 120, h, dtype=np.float32),
                               (w, 1)).T] * 3)
    rng = np.random.default_rng(0)
    R = np.clip(0.6 * S + 0.4 * drift + rng.normal(0, 12, S.shape), 0, 255)
    ps, pr = str(tmp_path / "s.png"), str(tmp_path / "r.png")
    out = str(tmp_path / "o.png")
    imwrite(ps, S.astype(np.uint8))
    imwrite(pr, R.astype(np.uint8))
    monkeypatch.setattr("face_transfer.face_mask",
                        lambda p, feather=0.18: np.ones((h, w), np.float32))
    refine.texture_back(ps, pr, out, sigma=2.0, strength=1.0)
    O = imread(out).astype(np.float32)
    low = float(np.abs(_blur(O) - _blur(S)).mean())
    high = float(np.abs(O - S).mean())
    assert low < 1.5, (
        f"перенос фактуры сдвинул низкие частоты на {low:.2f} — именно на них "
        f"живёт ArcFace")
    assert high > 4.0, f"фактура не перенеслась вовсе (разница {high:.2f})"
