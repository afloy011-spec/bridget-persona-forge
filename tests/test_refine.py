def test_texture_pass_is_opt_in_not_default():
    """Проход фактуры включается ключом, а не по умолчанию.

    ПЕРЕВЁРНУТО ПО ЗАМЕРУ. Он был умолчанием, пока лицо в кадр ставил своп и
    приходило оно ватой (фактура 5.3): там проход поднимал её до 34.9. С
    обученной лорой лицо рисует модель, ESRGAN даёт разрешение, и на готовом
    кадре проход только отнимает — фактура 190 → 74, сходство 0.655 → 0.554.
    Заказчик увидел это раньше метрик: «при приближении женщина неестественная
    и не похожа на нашу».
    """
    # УМОЛЧАНИЕ ПРОВЕРЯЕТСЯ ЗДЕСЬ ЖЕ, а не только в соседнем файле.
    # Мутационный прогон показал слепоту: строка «проход фактуры снова стал
    # умолчанием» указывала на этот тест, а он смотрел только на наличие ключа
    # и оставался зелёным при перевёрнутом умолчании. Тест, названный «включён
    # ключом, а не по умолчанию», обязан проверять именно умолчание.
    assert inspect.signature(produce.finish).parameters[
        "refine_frames"].default is False, (
        "проход фактуры снова включён по умолчанию — на кадре после апскейла "
        "он сглаживает лицо (фактура 190 → 74) и уводит сходство "
        "(0.655 → 0.554)")
    doc = inspect.getdoc(produce.finish) or ""
    assert "--texture" in doc, "ключ не описан рядом с кодом"
    src = inspect.getsource(produce.main)
    assert '"--texture" in args' in src, (
        "ключ --texture не разобран в main() — документация обещает то, чего "
        "нет")


