#!/usr/bin/env python3
"""Фактура: рисуется в масштабе ЛИЦА, и перенос лица в конвейер не возвращается.

ЧТО ЗДЕСЬ ЗАЩИЩАЕТСЯ, И ПОЧЕМУ ЭТО ВАЖНЕЕ ОСТАЛЬНЫХ ТЕСТОВ ПРОЕКТА.
Заказчик трижды подряд сказал одно и то же разными словами: «плывёт по
пикселям», «очень плохое качество», «качество всё ещё поплывшее». Причина у
всех трёх одна и она измерена — ПЕРЕНОС ЛИЦА. На 14 парах «сырой кадр / он же
после переноса» дисперсия лапласиана по маске лица падает в среднем со 180 до
40, то есть теряется 78% фактуры, и теряется на КАЖДОМ кадре (от -53% до
-87%). inswapper синтезирует лицо в 128x128 — вернуть оттуда нечего.

И это уже было измерено и записано в шапке generate.generate() ДО меня. Ветку
свопа удалили, я построила её заново, не прочитав запись, и три круга чинила
её последствия компенсациями. Тесты ниже нужны затем, чтобы четвёртого круга
не было: они краснеют, если своп снова станет частью доводки.

Вторая половина — про масштаб. Диффузия рисует детали в масштабе холста, а
лицу при съёмке достаётся 72-161 px межзрачкового (медианы по планам: в рост
72, по пояс 120, погрудный 146, портрет 161). Проход по всему кадру физически
не может положить туда поры. Кроп лица на холсте 1024 может: замер на кропе
52.7 -> 71.3 против 5.3 -> 11.5 у прохода по кадру.

GPU тесты не трогают: проверяется подпись, достижимость веток, порядок и — на
синтетике — арифметика вклейки.
"""
