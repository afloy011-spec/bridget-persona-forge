def test_the_face_swap_is_not_part_of_finishing():
    """Доводка не зовёт перенос лица иначе как по явному ключу.

    ЭТО ГЛАВНЫЙ СТОРОЖ ФАЙЛА. Перенос стоял первым шагом цикла и уничтожал
    78% фактуры на каждом кадре. Мутант, возвращающий его безусловно, оставит
    код рабочим, а кадры — оплывшими, и поймает это только заказчик.
    """
    src = inspect.getsource(produce.finish)
    body = src[src.index("for i, it in enumerate"):]
    calls = [ln for ln in body.splitlines() if "transfer(" in ln]
    assert len(calls) <= 1, (
        f"перенос лица зовётся {len(calls)} раза в цикле доводки: {calls}")
    if calls:
        guard = body[:body.index(calls[0])].splitlines()[-1]
        assert "if face_ref:" in guard, (
            f"перенос лица зовётся без проверки ключа, под «{guard.strip()}» "
            f"— он вернётся в конвейер по умолчанию и снова съест 78% фактуры")


def test_the_compensation_chain_is_gone():
    """Цепочки компенсаций больше нет: она лечила вред свопа, свопа нет.

    Проход по всему кадру, возврат овала лица (keep_outside) и подмешивание
    высоких частот (texture_back) существовали ровно затем, чтобы вернуть
    уничтоженную свопом фактуру, и возвращали от силы её пятую часть. Каждая
    ступень стоила прогона на воркере.
    """
    src = inspect.getsource(produce.finish)
    for dead in ("keep_outside(", "texture_back(", "rf.refine("):
        assert dead not in src, (
            f"в доводке снова стоит «{dead}» — это ступень компенсации свопа, "
            f"а не самостоятельный шаг")


